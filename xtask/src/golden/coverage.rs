//! The coverage report, `tests/golden/COVERAGE.md`: every command path of
//! `opentide --json commands` against every mode, with the number of cases,
//! generated from the case list and the recordings, and committed.

use crate::golden::case::{Case, Mode};
use crate::golden::oracle::Oracle;
use anyhow::{Context, Result};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;

/// The proposed budget for everything under `tests/golden/cases/` and `tests/golden/blobs/`.
pub const BUDGET_BYTES: u64 = 128 * 1024 * 1024;

/// The command paths in the oracle's `opentide --json commands` document.
pub fn command_paths(commands_json: &[u8]) -> Result<Vec<String>> {
    let doc: serde_json::Value = serde_json::from_slice(commands_json)
        .context("parse the `opentide --json commands` recording")?;
    let commands = doc["commands"]
        .as_array()
        .context("`commands` is not a list")?;
    commands
        .iter()
        .map(|c| {
            c["path"]
                .as_str()
                .map(str::to_owned)
                .context("a command without a `path`")
        })
        .collect()
}

/// Sizes of the recordings.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Size {
    /// Files under `cases/`.
    pub files: u64,
    /// Their bytes.
    pub bytes: u64,
}

/// Counts the files and bytes under `dir`.
pub fn measure(dir: &Path) -> Result<Size> {
    let mut size = Size::default();
    if !dir.exists() {
        return Ok(size);
    }
    let mut stack = vec![dir.to_path_buf()];
    while let Some(dir) = stack.pop() {
        for entry in std::fs::read_dir(&dir).with_context(|| format!("read {}", dir.display()))? {
            let entry = entry.with_context(|| format!("read {}", dir.display()))?;
            let meta = entry
                .metadata()
                .with_context(|| format!("stat {}", entry.path().display()))?;
            if meta.is_dir() {
                stack.push(entry.path());
            } else {
                size.files += 1;
                size.bytes += meta.len();
            }
        }
    }
    Ok(size)
}

/// The report and the command paths × modes that have no case.
pub struct Report {
    /// `COVERAGE.md`.
    pub markdown: String,
    /// `(command, mode)` pairs without a case.
    pub missing: Vec<(String, Mode)>,
    /// Commands the cases name that `opentide --json commands` does not list.
    pub unknown: Vec<String>,
}

/// Builds the report.
pub fn report(oracle: &Oracle, paths: &[String], cases: &[Case], size: Size) -> Report {
    let mut counts: BTreeMap<(&str, Mode), usize> = BTreeMap::new();
    let mut fixtures: BTreeMap<&str, BTreeSet<&str>> = BTreeMap::new();
    for case in cases {
        *counts
            .entry((case.command.as_str(), case.mode))
            .or_default() += 1;
        fixtures
            .entry(case.command.as_str())
            .or_default()
            .insert(case.fixture.as_str());
    }
    let mut rows: Vec<&str> = vec![""];
    rows.extend(paths.iter().map(String::as_str));
    let known: BTreeSet<&str> = rows.iter().copied().collect();
    let unknown: Vec<String> = fixtures
        .keys()
        .filter(|c| !known.contains(*c))
        .map(|c| (*c).to_owned())
        .collect();
    let mut missing = Vec::new();
    for path in paths {
        for mode in Mode::ALL {
            if !counts.contains_key(&(path.as_str(), mode)) {
                missing.push((path.clone(), mode));
            }
        }
    }
    let mut by_fixture: BTreeMap<&str, usize> = BTreeMap::new();
    let mut by_mode: BTreeMap<Mode, usize> = BTreeMap::new();
    for case in cases {
        *by_fixture.entry(case.fixture.as_str()).or_default() += 1;
        *by_mode.entry(case.mode).or_default() += 1;
    }

    let mut md = String::new();
    let _ = writeln!(md, "# Golden coverage\n");
    let _ = writeln!(
        md,
        "Generated by `cargo xtask golden record` from `cases.toml` and the recordings: never edit. \
         `cargo xtask golden check` fails when it is out of date.\n"
    );
    let _ = writeln!(
        md,
        "- Oracle: {} {} (`{}`, {}), Python {}, {}",
        oracle.package,
        oracle.version,
        oracle.tag,
        &oracle.commit[..oracle.commit.len().min(12)],
        oracle.python,
        oracle.platform
    );
    let _ = writeln!(
        md,
        "- Cases: {} over {} command paths of `opentide --json commands` and the root; {}",
        cases.len(),
        paths.len(),
        Mode::ALL
            .iter()
            .map(|m| format!("{} {m}", by_mode.get(m).copied().unwrap_or(0)))
            .collect::<Vec<_>>()
            .join(", ")
    );
    let _ = writeln!(
        md,
        "- Fixtures: {}",
        by_fixture
            .iter()
            .map(|(f, n)| format!("{f} {n}"))
            .collect::<Vec<_>>()
            .join(", ")
    );
    let _ = writeln!(
        md,
        "- Recordings (`cases/` and `blobs/`): {} files, {} bytes ({:.1} MiB) of a {} MiB budget",
        size.files,
        size.bytes,
        mib(size.bytes),
        BUDGET_BYTES / (1024 * 1024)
    );
    let _ = writeln!(
        md,
        "- Command paths × modes without a case: {}\n",
        if missing.is_empty() {
            "none".to_owned()
        } else {
            missing.len().to_string()
        }
    );
    let _ = writeln!(
        md,
        "| Command path | human | plain | json | agent | Fixtures |"
    );
    let _ = writeln!(
        md,
        "|--------------|------:|------:|-----:|------:|----------|"
    );
    for path in rows {
        let name = if path.is_empty() {
            "(root)".to_owned()
        } else {
            format!("`{path}`")
        };
        let cells: Vec<String> = Mode::ALL
            .iter()
            .map(|&m| match counts.get(&(path, m)) {
                Some(n) => n.to_string(),
                None => "**0**".to_owned(),
            })
            .collect();
        let used = fixtures
            .get(path)
            .map(|f| f.iter().copied().collect::<Vec<_>>().join(", "))
            .unwrap_or_default();
        let _ = writeln!(md, "| {name} | {} | {used} |", cells.join(" | "));
    }
    Report {
        markdown: md,
        missing,
        unknown,
    }
}

#[expect(
    clippy::cast_precision_loss,
    reason = "a size printed to one decimal place"
)]
fn mib(bytes: u64) -> f64 {
    bytes as f64 / (1024.0 * 1024.0)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::golden::case::Spec;

    fn oracle() -> Oracle {
        Oracle {
            tag: "v0.23.0".into(),
            commit: "f41fe5e5c5a8631b3cc3ab5f80aba39b4e65f2d7".into(),
            package: "opentide".into(),
            version: "0.23.0".into(),
            wheel: "opentide-0.23.0-x.whl".into(),
            wheel_sha256: "0".repeat(64),
            python: "3.13.14".into(),
            platform: "linux-x86_64".into(),
            exclude_newer: "2026-11-08T00:00:00Z".into(),
            requirements: "oracle-requirements.txt".into(),
        }
    }

    #[test]
    fn reports_missing_modes_and_unknown_commands() {
        let spec = Spec::parse(
            r#"
[defaults]
modes = ["human", "plain", "json", "agent"]
fixtures = ["none"]
timeout_secs = 60
[fixtures.none]
kind = "skeleton"
[[case]]
command = "validate"
variant = "a"
args = ["validate"]
[[case]]
command = "lint"
variant = "a"
args = ["lint"]
modes = ["json"]
[[case]]
command = "valdate"
variant = "typo"
args = ["valdate"]
"#,
        )
        .unwrap();
        let cases = spec.expand().unwrap();
        let paths = vec!["validate".to_owned(), "lint".to_owned()];
        let r = report(
            &oracle(),
            &paths,
            &cases,
            Size {
                files: 3,
                bytes: 2048,
            },
        );
        assert_eq!(
            r.missing,
            [
                ("lint".to_owned(), Mode::Human),
                ("lint".to_owned(), Mode::Plain),
                ("lint".to_owned(), Mode::Agent)
            ]
        );
        assert_eq!(r.unknown, ["valdate"]);
        assert!(
            r.markdown
                .contains("| `lint` | **0** | **0** | 1 | **0** | none |"),
            "{}",
            r.markdown
        );
        assert!(r.markdown.contains("| `validate` | 1 | 1 | 1 | 1 | none |"));
        assert!(r.markdown.contains("3 files, 2048 bytes"));
    }

    #[test]
    fn reads_command_paths() {
        let doc =
            br#"{"commands": [{"path": "validate"}, {"path": "generate docs"}], "duration_ms": 0}"#;
        assert_eq!(command_paths(doc).unwrap(), ["validate", "generate docs"]);
        assert!(command_paths(b"{}").is_err());
    }
}
