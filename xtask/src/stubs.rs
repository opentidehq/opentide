//! `cargo xtask stubs [--check] [--library FILE]` (UC-1.9, #815; UC-5.2b,
//! #837): the type stubs of `opentide._native.models` and
//! `opentide._native.sdk`, generated from the extension, never written by
//! hand.
//!
//! PyO3 compiles a description of every class, method and attribute into the
//! extension when its `experimental-inspect` feature is on (`opentide-native`'s
//! `stubs` feature); `pyo3-introspection`, the crate `maturin generate-stubs`
//! uses, reads it back and writes the stubs. The command builds the extension
//! with that feature (the `develop` profile, which `uv sync` builds too, so
//! only PyO3 and the crates that use it rebuild), introspects it, and writes
//! each of [`STUBS`], or with `--check` fails when a file differs.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use anyhow::{Context, Result, bail};

/// A generated stub: the submodule it describes and where it is written.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Stub {
    /// The file, from the repository root.
    pub path: &'static str,
    /// The submodule's file in pyo3-introspection's output (`models.pyi`).
    pub module: &'static str,
    /// The lines the file starts with.
    pub header: &'static str,
}

/// The generated stub of the Tide models, from the repository root.
pub const STUB: &str = "src/opentide/_native/models.pyi";

/// The generated stub of the SDK's core, from the repository root.
pub const SDK_STUB: &str = "src/opentide/_native/sdk.pyi";

/// The lines the models' stub starts with. The rest is pyo3-introspection's
/// output as it writes it: its docstrings are the Rust doc comments,
/// indented, and its layout is not ruff's, so ruff lints and formats the file
/// as the generated file it is (one file-level suppression, here, with its
/// reason).
pub const HEADER: &str = "\
# Generated by `cargo xtask stubs` from bindings/python/ and crates/opentide-schema/src/python.rs
# (UC-1.9, ADR 0011). Do not edit: regenerate. Generated text is not ruff's to lay out:
# the docstrings are the Rust doc comments (E501) and `__all__` is in introspection's order (RUF022).
# ruff: noqa: E501, RUF022
# fmt: off
";

/// The lines the SDK's stub starts with, for the same reasons as [`HEADER`];
/// its imports (`_typeshed` among them) are in introspection's order too.
pub const SDK_HEADER: &str = "\
# Generated by `cargo xtask stubs` from bindings/python/src/sdk.rs and bindings/python/src/sdk/
# (UC-5.2, #837). Do not edit: regenerate. Generated text is not ruff's to lay out: the docstrings
# are the Rust doc comments (E501), the imports and `__all__` are in introspection's order (I001, RUF022).
# ruff: noqa: E501, I001, RUF022
# fmt: off
";

/// Every generated stub, in the order the command reports them.
pub const STUBS: [Stub; 2] = [
    Stub {
        path: STUB,
        module: "models.pyi",
        header: HEADER,
    },
    Stub {
        path: SDK_STUB,
        module: "sdk.pyi",
        header: SDK_HEADER,
    },
];

const USAGE: &str = "\
usage: cargo xtask stubs [--check] [--library FILE]

Writes src/opentide/_native/models.pyi and src/opentide/_native/sdk.pyi from the
extension's introspection data.
  --check          fail (exit 1) when a file differs from what is generated
  --library FILE   introspect FILE, an extension built with
                   `cargo build -p opentide-native --lib --features stubs`,
                   instead of building it
";

/// Runs the command; the exit code.
pub fn main(args: &[String]) -> std::process::ExitCode {
    match run(args) {
        Ok(true) => std::process::ExitCode::SUCCESS,
        Ok(false) => std::process::ExitCode::FAILURE,
        Err(error) => {
            eprintln!("xtask stubs: {error:#}");
            std::process::ExitCode::from(2)
        }
    }
}

fn run(args: &[String]) -> Result<bool> {
    let mut check = false;
    let mut library = None;
    let mut rest = args.iter();
    while let Some(arg) = rest.next() {
        match arg.as_str() {
            "--check" => check = true,
            "--library" => {
                library = Some(PathBuf::from(
                    rest.next().context("--library takes a file")?,
                ));
            }
            "help" | "--help" | "-h" => {
                print!("{USAGE}");
                return Ok(true);
            }
            other => bail!("unknown option `{other}`\n\n{USAGE}"),
        }
    }
    let root = workspace_root();
    let library = match library {
        Some(library) => library,
        None => build(&root)?,
    };
    let generated = generate(&library)?;
    let mut fresh = true;
    for (stub, text) in STUBS.iter().zip(generated) {
        let path = root.join(stub.path);
        if check {
            let current = match fs::read_to_string(&path) {
                Ok(text) => Some(text),
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => None,
                Err(error) => {
                    return Err(error).with_context(|| format!("reading {}", path.display()));
                }
            };
            match drift(stub.path, current.as_deref(), &text) {
                None => println!("{} is up to date", stub.path),
                Some(report) => {
                    eprint!("{report}");
                    fresh = false;
                }
            }
            continue;
        }
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(&path, text).with_context(|| format!("writing {}", path.display()))?;
        println!("wrote {}", stub.path);
    }
    Ok(fresh)
}

/// What `--check` reports when the stub on disk at `path` (`current`,
/// `None` when there is none) is not `generated`: the instruction, then the
/// unified diff from the file to what is generated. `None` when they are the
/// same.
pub fn drift(path: &str, current: Option<&str>, generated: &str) -> Option<String> {
    let Some(current) = current else {
        return Some(format!("{path} is missing: run `cargo xtask stubs`\n"));
    };
    if current == generated {
        return None;
    }
    let mut report = format!("{path} differs from the generated stub: run `cargo xtask stubs`\n");
    report.push_str(
        &similar::TextDiff::from_lines(current, generated)
            .unified_diff()
            .header(path, "generated")
            .to_string(),
    );
    Some(report)
}

/// The text of each of [`STUBS`] in `library`, in that order: its header,
/// then what `pyo3-introspection` writes for its submodule.
pub fn generate(library: &Path) -> Result<Vec<String>> {
    let module = pyo3_introspection::introspect_cdylib(library, "_native")
        .with_context(|| format!("introspecting {}", library.display()))?;
    let mut files = pyo3_introspection::module_stub_files(&module);
    STUBS
        .iter()
        .map(|stub| {
            let text = files
                .remove(Path::new(stub.module))
                .with_context(|| format!("the extension has no `{}` submodule", stub.module))?;
            Ok(format!("{}{text}", stub.header))
        })
        .collect()
}

fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .map_or_else(|| PathBuf::from("."), Path::to_path_buf)
}

/// Builds the extension with its introspection data; the library cargo
/// reports writing.
fn build(root: &Path) -> Result<PathBuf> {
    let cargo = std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
    let output = Command::new(cargo)
        .current_dir(root)
        .args([
            "build",
            "--locked",
            "-p",
            "opentide-native",
            "--lib",
            "--features",
            "stubs",
            "--profile",
            "develop",
            "--message-format=json-render-diagnostics",
        ])
        .stderr(Stdio::inherit())
        .output()
        .context("running cargo build")?;
    if !output.status.success() {
        bail!("cargo build -p opentide-native --features stubs failed");
    }
    library_in(&String::from_utf8_lossy(&output.stdout))
}

/// The `_native` cdylib in cargo's JSON messages.
pub fn library_in(messages: &str) -> Result<PathBuf> {
    for line in messages.lines() {
        let Ok(message) = serde_json::from_str::<serde_json::Value>(line) else {
            continue;
        };
        let target = &message["target"];
        let is_native = target["name"] == "_native"
            && target["kind"]
                .as_array()
                .is_some_and(|kinds| kinds.iter().any(|kind| kind == "cdylib"));
        if !is_native {
            continue;
        }
        for file in message["filenames"].as_array().into_iter().flatten() {
            if let Some(file) = file.as_str()
                && [".so", ".dylib", ".dll"]
                    .iter()
                    .any(|suffix| file.ends_with(suffix))
            {
                return Ok(PathBuf::from(file));
            }
        }
    }
    bail!("cargo reported no _native library")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_check_passes_only_on_the_generated_text() {
        let generated = "# header\nclass A: ...\nclass B: ...\n";
        assert_eq!(drift(STUB, Some(generated), generated), None);

        let stale = "# header\nclass A: ...\n";
        let report = drift(STUB, Some(stale), generated).expect("a stale stub is drift");
        assert!(
            report.starts_with(&format!("{STUB} differs from the generated stub")),
            "{report}"
        );
        // The diff goes from the file to what is generated.
        assert!(
            report.contains(&format!("--- {STUB}\n+++ generated\n")),
            "{report}"
        );
        assert!(report.contains("\n+class B: ...\n"), "{report}");
        assert!(!report.contains("\n-class"), "{report}");

        // A missing stub is drift, even where nothing would be generated.
        let missing = drift(SDK_STUB, None, "").expect("a missing stub is drift");
        assert_eq!(
            missing,
            format!("{SDK_STUB} is missing: run `cargo xtask stubs`\n")
        );
        // An empty file is not the generated text.
        assert!(drift(STUB, Some(""), generated).is_some());
    }

    #[test]
    fn each_stub_has_its_own_file_and_header() {
        let paths: Vec<&str> = STUBS.iter().map(|stub| stub.path).collect();
        assert_eq!(paths, [STUB, SDK_STUB]);
        for stub in STUBS {
            assert!(
                stub.path.ends_with(stub.module),
                "{} is written from {}",
                stub.path,
                stub.module
            );
            assert!(
                stub.header
                    .starts_with("# Generated by `cargo xtask stubs`")
                    && stub.header.contains("# ruff: noqa: E501, ")
                    && stub.header.ends_with("\n# fmt: off\n"),
                "{}",
                stub.header
            );
        }
    }

    #[test]
    fn the_library_is_the_native_cdylib_cargo_reports() {
        let messages = r#"{"reason":"compiler-artifact","target":{"name":"opentide_schema","kind":["lib"]},"filenames":["/t/libopentide_schema.rlib"]}
not json
{"reason":"compiler-artifact","target":{"name":"_native","kind":["cdylib"]},"filenames":["/t/develop/lib_native.so"]}"#;
        assert_eq!(
            library_in(messages).unwrap(),
            PathBuf::from("/t/develop/lib_native.so")
        );
        assert!(library_in("{}").is_err());
        let rlib_only =
            r#"{"target":{"name":"_native","kind":["cdylib"]},"filenames":["/t/lib_native.rlib"]}"#;
        assert!(library_in(rlib_only).is_err());
    }

    fn words(words: &[&str]) -> Vec<String> {
        words.iter().map(|word| (*word).to_owned()).collect()
    }

    #[test]
    fn options_are_checked_before_anything_is_built() {
        assert_eq!(main(&words(&["--help"])), std::process::ExitCode::SUCCESS);
        assert_eq!(
            main(&words(&["--frobnicate"])),
            std::process::ExitCode::from(2)
        );
        let error = run(&words(&["--library"])).unwrap_err();
        assert!(
            format!("{error:#}").contains("--library takes a file"),
            "{error:#}"
        );
        let error = run(&words(&["--check", "--bogus"])).unwrap_err();
        assert!(
            format!("{error:#}").starts_with("unknown option `--bogus`"),
            "{error:#}"
        );
    }

    #[test]
    fn a_file_that_is_not_the_extension_cannot_be_introspected() {
        let dir = tempfile::tempdir().unwrap();
        let missing = dir.path().join("lib_native.so");
        let stubs: Vec<PathBuf> = STUBS
            .iter()
            .map(|stub| workspace_root().join(stub.path))
            .collect();
        let before: Vec<Option<Vec<u8>>> = stubs.iter().map(|stub| fs::read(stub).ok()).collect();
        // Neither with --check nor without is anything written: the stub on
        // disk is left as it is when there is nothing to introspect.
        for check in [true, false] {
            let mut args = words(&["--library", &missing.to_string_lossy()]);
            if check {
                args.push("--check".into());
            }
            let error = run(&args).unwrap_err();
            assert!(
                format!("{error:#}").starts_with(&format!("introspecting {}", missing.display())),
                "{error:#}"
            );
        }
        std::fs::write(&missing, "not a shared library").unwrap();
        assert!(generate(&missing).is_err());
        assert_eq!(
            main(&words(&[
                "--check",
                "--library",
                &missing.to_string_lossy()
            ])),
            std::process::ExitCode::from(2)
        );
        let after: Vec<Option<Vec<u8>>> = stubs.iter().map(|stub| fs::read(stub).ok()).collect();
        assert_eq!(after, before);
    }

    #[test]
    fn the_stub_is_under_the_workspace_root() {
        let root = workspace_root();
        assert!(
            root.join("xtask/Cargo.toml").is_file(),
            "{}",
            root.display()
        );
        for stub in STUBS {
            assert!(
                root.join(stub.path).parent().is_some_and(Path::is_dir),
                "{} is in an existing folder",
                stub.path
            );
        }
    }
}
