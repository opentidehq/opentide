//! The typed AST generator of `cargo xtask codegen` (`xtask/src/astgen.rs`):
//! what it writes, what `--check` finds, and the grammars it refuses. The
//! generated AST of the toolkit's test language compiles and runs in
//! `crates/opentide-parse/tests/ast_fixture`.

use std::path::{Path, PathBuf};

use xtask::astgen::{generate, sync};

type TestResult = Result<(), Box<dyn std::error::Error>>;

fn repository() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .map(Path::to_path_buf)
        .unwrap_or_default()
}

/// A workspace with one language, `opentide-toy`, whose grammar is `grammar`.
fn workspace(grammar: &str) -> Result<tempfile::TempDir, Box<dyn std::error::Error>> {
    let root = tempfile::tempdir()?;
    let src = root.path().join("crates/opentide-toy/src");
    std::fs::create_dir_all(&src)?;
    std::fs::write(src.join("toy.ungram"), grammar)?;
    std::fs::create_dir_all(root.path().join("crates/opentide-other/src"))?;
    Ok(root)
}

const TOY: &str = "Root = Item*\nItem = 'word'\n";

#[test]
fn the_committed_asts_are_current() -> TestResult {
    let problems = sync(&repository(), true)?;
    assert!(problems.is_empty(), "{problems:#?}");
    Ok(())
}

#[test]
fn sync_writes_then_checks_then_finds_drift() -> TestResult {
    let root = workspace(TOY)?;
    let ast = root.path().join("crates/opentide-toy/src/generated/ast.rs");
    assert_eq!(
        sync(root.path(), true)?,
        ["crates/opentide-toy/src/generated/ast.rs: missing"]
    );
    assert!(sync(root.path(), false)?.is_empty());
    let text = std::fs::read_to_string(&ast)?;
    assert!(text.starts_with("// @generated by `cargo xtask codegen` from"));
    assert!(text.contains("pub fn items(&self) -> AstChildren<Item>"));
    assert!(sync(root.path(), true)?.is_empty());

    std::fs::write(&ast, text.replace("items", "things"))?;
    assert_eq!(
        sync(root.path(), true)?,
        [
            "crates/opentide-toy/src/generated/ast.rs: differs from what \
          crates/opentide-toy/src/toy.ungram generates"
        ]
    );
    // Writing repairs it.
    assert!(sync(root.path(), false)?.is_empty());
    assert_eq!(std::fs::read_to_string(&ast)?, text);

    // A grammar that is gone leaves its generated file stale.
    std::fs::remove_file(root.path().join("crates/opentide-toy/src/toy.ungram"))?;
    let problems = sync(root.path(), true)?;
    assert_eq!(problems.len(), 1);
    assert!(problems[0].ends_with("which is gone"), "{problems:?}");
    Ok(())
}

#[test]
fn a_tree_without_grammars_generates_nothing() -> TestResult {
    let root = tempfile::tempdir()?;
    std::fs::create_dir_all(root.path().join("crates/opentide-toy/src"))?;
    assert!(sync(root.path(), true)?.is_empty());
    assert!(
        !root
            .path()
            .join("crates/opentide-toy/src/generated")
            .exists()
    );
    Ok(())
}

#[test]
fn accessors_are_named_by_labels_nodes_and_tokens() -> TestResult {
    let text = generate(
        "Root = type:Name? 'where' ('a' | 'b') Entry* x:('x' | 'y') '::' Extra Extras?\n\
         Name = 'ident'\nEntry = Name\nExtra = 'e'\nExtras = 'e'\n",
        "toy.ungram",
    )?;
    for expected in [
        "pub fn type_(&self) -> Option<Name>",
        "pub fn where_token(&self) -> Option<SyntaxToken>",
        "pub fn entries(&self) -> AstChildren<Entry>",
        "pub fn x(&self) -> Option<SyntaxToken>",
        "support::token_in(&self.syntax, &[T![x], T![y]])",
        "pub fn coloncolon_token(&self)",
        "pub fn extra(&self) -> Option<Extra>",
        "pub fn a_token(&self)",
    ] {
        assert!(text.contains(expected), "{expected}\n{text}");
    }
    Ok(())
}

#[test]
fn a_choice_of_choices_casts_through_the_inner_one() -> TestResult {
    let text = generate(
        "A = B | C\nB = D | E\nC = 'c'\nD = 'd'\nE = 'e'\n",
        "toy.ungram",
    )?;
    assert!(
        text.contains("SyntaxKind::C => Self::C(C { syntax }),"),
        "{text}"
    );
    assert!(
        text.contains("B::cast(syntax.clone()).map(Self::B)"),
        "{text}"
    );
    assert!(text.contains("impl From<B> for A"), "{text}");
    // The rule of a node that holds the outer choice lists the leaves.
    let text = generate(
        "R = A\nA = B | C\nB = D | E\nC = 'c'\nD = 'd'\nE = 'e'\n",
        "toy.ungram",
    )?;
    for leaf in ["C", "D", "E"] {
        assert!(
            text.contains(&format!("Rule::Kind(SyntaxKind::{leaf} as u16)")),
            "{text}"
        );
    }
    Ok(())
}

fn refusal(grammar: &str) -> String {
    match generate(grammar, "toy.ungram") {
        Ok(text) => panic!("generated\n{text}"),
        Err(error) => format!("{error:#}"),
    }
}

#[test]
fn what_it_cannot_name_it_refuses() {
    let same = refusal("Root = Name '+' Name\nName = 'ident'\n");
    assert!(
        same.contains("`Name` occurs 2 times") && same.contains("Root"),
        "{same}"
    );
    let optional = refusal("Root = a:Name b:Name?\nName = 'ident'\n");
    assert!(optional.contains("`Name` occurs 2 times"), "{optional}");
    let clash = refusal("Root = x:Name x:Other\nName = 'ident'\nOther = 'n'\n");
    assert!(clash.contains("two children are named `x`"), "{clash}");
    let bad_token = refusal("Root = '\u{00a7}'\n");
    assert!(
        bad_token.contains("no accessor name for the token"),
        "{bad_token}"
    );
    let seq = refusal("Root = x:('a' Name)\nName = 'ident'\n");
    assert!(seq.contains("label one node or token"), "{seq}");
    let cycle = refusal("Root = A\nA = B | C\nB = A | D\nC = 'c'\nD = 'd'\n");
    assert!(cycle.contains("contains itself"), "{cycle}");
    let syntax = refusal("Root = Missing\n");
    assert!(!syntax.is_empty());
}
