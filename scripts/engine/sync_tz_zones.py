#!/usr/bin/env python3
"""Generate catalogs/tz/zones.txt, the IANA time zone names.

`schedule.timezone` on a Graylog block (platform::graylog::1.0,
`graylog_schedule`) is an IANA time zone name. The engine is I/O-free, so it
cannot ask the system's zoneinfo: it reads this list. Every zone (`Z`) and
link (`L`) name of the tz database is listed, one per line, sorted, after a
header naming the tzdata version.

Inputs (read as data, never executed):

- ``--tzdata FILE``: a ``tzdata.zi`` (the tz database's compact form, shipped
  in ``/usr/share/zoneinfo/tzdata.zi`` and in every tzdata release).

Usage:
    python -I scripts/sync_tz_zones.py --tzdata /usr/share/zoneinfo/tzdata.zi [--check]

``--check`` exits 1 when the committed file differs. Standard library only.
The tz database is in the public domain (catalogs/tz/NOTICE).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "catalogs" / "tz" / "zones.txt"


def render(text: str) -> str:
    version = "unknown"
    names: set[str] = set()
    for line in text.splitlines():
        if line.startswith("# version "):
            version = line.removeprefix("# version ").strip()
        parts = line.split()
        if len(parts) >= 2 and parts[0] == "Z":
            names.add(parts[1])
        elif len(parts) >= 3 and parts[0] == "L":
            names.add(parts[2])
    if not names:
        raise SystemExit("no Z or L lines: not a tzdata.zi file")
    header = [
        "# IANA time zone names (zones and links), one per line.",
        f"# Generated by scripts/sync_tz_zones.py from tzdata {version}; do not edit.",
    ]
    return "\n".join(header + sorted(names)) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tzdata", required=True, type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = render(args.tzdata.read_text(encoding="utf-8"))
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != rendered:
            print(f"{OUT.relative_to(ROOT)} is stale; regenerate it", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} is current")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
