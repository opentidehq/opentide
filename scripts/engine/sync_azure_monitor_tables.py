#!/usr/bin/env python3
"""Generate catalogs/kql/azure-monitor/tables.toml from a MicrosoftDocs/azure-monitor-docs checkout.

Reads articles/azure-monitor/reference/tables/*.md, the Azure Monitor Logs
table reference that Microsoft generates from the service's own schemas
("This file is automatically generated"), and writes one row per table: its
name, the first sentence of its description, its categories, the Learn page,
and every column with its type and the first sentence of its description. That covers the tables Microsoft Sentinel
workspaces hold (SigninLogs, NTANetAnalytics, SentinelHealth, the
ASim*Logs ingest-time tables) and the Defender XDR tables the Defender XDR
connector streams into them (DeviceProcessEvents, ...).

The reference is CC BY 4.0 (its LICENSE); the table and column descriptions
are kept, cut to their first sentence, with attribution in NOTICE. Hover and
completion show a column's description and link the table's Learn page.

Each column is a `[[tables.columns]]` sub-table, one key per line, so a
change to one column is a one-line diff.

The KQL engine checks columns against these lists (`kql_unknown_column`). A
table without a "## Columns" section (AzureDiagnostics, whose columns depend
on the resources that write to it) is written with `open = true`: known by
name, its columns unchecked. The resource-type index pages have no table.

With --sentinel, the columns of Azure-Sentinel's KQL validation schemas
(.script/tests/KqlvalidationsTests/CustomTables, MIT), which Microsoft's own
CI checks Sentinel content against, are added to the tables the reference
has: they carry columns the reference lags behind on (IdentityInfo's
advanced hunting AccountUpn beside AccountUPN).

Usage (a sparse checkout is enough):
    git clone --depth 1 --filter=blob:none --sparse \\
        https://github.com/MicrosoftDocs/azure-monitor-docs.git
    git -C azure-monitor-docs sparse-checkout set --no-cone \\
        '/articles/azure-monitor/reference/tables/*' /LICENSE
    python scripts/sync_azure_monitor_tables.py --docs azure-monitor-docs --sentinel Azure-Sentinel
    python scripts/sync_azure_monitor_tables.py --docs azure-monitor-docs --sentinel Azure-Sentinel --check
"""

from __future__ import annotations

import argparse
import json
import tomllib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "catalogs/kql/azure-monitor/tables.toml"
TABLES = Path("articles/azure-monitor/reference/tables")
VALIDATION = Path(".script/tests/KqlvalidationsTests/CustomTables")
LEARN = "https://learn.microsoft.com/azure/azure-monitor/reference/tables/"
# Kusto scalar types, as the reference spells them, to the names the KQL
# catalog uses (catalogs/kql/core/types.toml).
TYPES = {
    "string": "string",
    "datetime": "datetime",
    "date": "datetime",
    "long": "long",
    "int": "int",
    "real": "real",
    "double": "real",
    "decimal": "decimal",
    "bool": "bool",
    "boolean": "bool",
    "dynamic": "dynamic",
    "guid": "guid",
    "uniqueidentifier": "guid",
    "timespan": "timespan",
    "time": "timespan",
}


# A full stop that ends these does not end the sentence.
ABBREVIATIONS = re.compile(r"(?:\b(?:e\.g|i\.e|vs|approx|incl)\.)$", re.I)


def first_sentence(text: str) -> str:
    text = " ".join(text.split())
    for match in re.finditer(r"[.!?](?=\s|$)", text):
        if not ABBREVIATIONS.search(text[: match.end()]):
            return text[: match.end()]
    return text


def parse_table(path: Path) -> dict | None:
    text = path.read_text(encoding="utf-8")
    title = re.search(r"^# (\S+)\s*$", text, re.M)
    if title is None:
        return None
    name = title.group(1)
    after = text[title.end() :]
    description = after.split("\n## ", 1)[0].strip()
    categories: list[str] = []
    cats = re.search(r"^\|\*\*Categories\*\*\|(.*)\|\s*$", text, re.M)
    if cats:
        categories = [c.strip() for c in cats.group(1).split(",") if c.strip() and c.strip() != "-"]
    columns_section = re.search(r"^## Columns\s*$(.*?)(?=^## |\Z)", text, re.M | re.S)
    if columns_section is None:
        # AzureDiagnostics: each Azure service adds its own columns, so the
        # table is known and its schema is open.
        return {
            "name": name,
            "docs": first_sentence(description),
            "categories": categories,
            "citation": LEARN + path.stem,
            "open": True,
        }
    columns: list[dict[str, str]] = []
    seen: set[str] = set()
    for line in columns_section.group(1).splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 2 or cells[0] in ("Column", "") or set(cells[0]) <= {"-", ":"}:
            continue
        column, kind = cells[0].strip("`"), cells[1].strip("`").lower()
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", column) or column in seen:
            continue
        if kind not in TYPES:
            raise SystemExit(f"{path.name}: column {column} has unknown type {cells[1]!r}")
        seen.add(column)
        entry = {"name": column, "type": TYPES[kind]}
        # The Description cell is Markdown, as hover renders it; a pipe in it
        # is written `&#124;`, so the row splits on its own pipes.
        summary = first_sentence(" | ".join(cells[2:])) if len(cells) > 2 else ""
        # Some cells hold only punctuation ("."): no description.
        if any(ch.isalpha() for ch in summary):
            entry["description"] = summary
        columns.append(entry)
    if not columns:
        return None
    columns.sort(key=lambda c: c["name"].lower())
    return {
        "name": name,
        "docs": first_sentence(description),
        "categories": categories,
        "citation": LEARN + path.stem,
        "columns": columns,
    }


def head(checkout: Path) -> str:
    return subprocess.run(
        ["git", "-C", str(checkout), "rev-parse", "HEAD"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()


def validation_columns(sentinel: Path) -> dict[str, list[dict[str, str]]]:
    """The table schemas Azure-Sentinel's own CI validates content against.
    They carry no descriptions."""
    out: dict[str, list[dict[str, str]]] = {}
    for path in sorted((sentinel / VALIDATION).glob("*.json")):
        # Some files carry trailing commas, which .NET's reader accepts.
        text = re.sub(r",(\s*[\]}])", r"\1", path.read_text(encoding="utf-8-sig"))
        try:
            doc = json.loads(text)
        except json.JSONDecodeError as err:
            print(f"skipping {path.name}: {err}", file=sys.stderr)
            continue
        name = doc.get("Name")
        if not isinstance(name, str) or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
            continue
        columns = []
        for prop in doc.get("Properties") or []:
            column, kind = str(prop.get("Name", "")), str(prop.get("Type", "")).lower()
            if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", column) and kind in TYPES:
                columns.append({"name": column, "type": TYPES[kind]})
        out[name] = columns
    return out


def generate(docs: Path, sentinel: Path | None) -> dict:
    tables = []
    names: set[str] = set()
    for path in sorted((docs / TABLES).glob("*.md")):
        if path.stem in ("index", "tables-category", "tables-resourcetype"):
            continue
        row = parse_table(path)
        if row is None or row["name"] in names:
            continue
        names.add(row["name"])
        tables.append(row)
    sources = [
        {
            "source": "MicrosoftDocs/azure-monitor-docs articles/azure-monitor/reference/tables",
            "commit": head(docs),
            "license": "CC-BY-4.0",
        }
    ]
    if sentinel is not None:
        # Columns the reference does not list but Microsoft's own validation
        # schemas have (advanced hunting columns such as IdentityInfo's
        # AccountUpn): added to the tables the reference has.
        extra = validation_columns(sentinel)
        for row in tables:
            listed = row.get("columns")
            if listed is None or row["name"] not in extra:
                continue
            have = {c["name"] for c in listed}
            for column in extra[row["name"]]:
                if column["name"] not in have:
                    listed.append(column)
                    have.add(column["name"])
            listed.sort(key=lambda c: c["name"].lower())
        sources.append(
            {
                "source": f"Azure/Azure-Sentinel {VALIDATION.as_posix()}",
                "commit": head(sentinel),
                "license": "MIT",
            }
        )
    tables.sort(key=lambda t: t["name"])
    return {
        "sources": sources,
        "generator": "scripts/sync_azure_monitor_tables.py",
        "tables": tables,
    }


def toml_string(value: str) -> str:
    # A JSON string is a TOML basic string: same quotes and escapes.
    return json.dumps(value, ensure_ascii=False)


def toml_value(value: object) -> str:
    if isinstance(value, str):
        return toml_string(value)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(v) for v in value) + "]"
    raise TypeError(value)


def dump(payload: dict) -> str:
    lines = [
        "# Azure Monitor Logs tables and their columns.",
        f"# Generated by {payload['generator']}; do not edit by hand.",
    ]
    for source in payload["sources"]:
        lines.append(f"# {source['source']}@{source['commit']} ({source['license']})")
    for table in payload["tables"]:
        lines.append("")
        lines.append("[[tables]]")
        for key in ("name", "docs", "categories", "citation", "open"):
            if key in table:
                lines.append(f"{key} = {toml_value(table[key])}")
        for column in table.get("columns", []):
            lines.append("[[tables.columns]]")
            for key in ("name", "type", "description"):
                if key in column:
                    lines.append(f"{key} = {toml_value(column[key])}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--docs", type=Path, required=True, help="azure-monitor-docs checkout")
    parser.add_argument(
        "--sentinel", type=Path, help="Azure-Sentinel checkout: adds its validation schemas' columns"
    )
    parser.add_argument("--out", type=Path, default=OUT)
    parser.add_argument("--check", action="store_true", help="fail if the catalog is stale")
    args = parser.parse_args()
    text = dump(generate(args.docs.resolve(), args.sentinel.resolve() if args.sentinel else None))
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        if current != text:
            print(f"{args.out} is stale; rerun without --check", file=sys.stderr)
            return 1
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    payload = tomllib.loads(text)
    print(f"wrote {args.out}: {len(payload['tables'])} tables")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
