#!/usr/bin/env python3
"""Generate the Datadog attribute catalogue (data/catalogs/datadog/) from Datadog's docs.

Reads a checkout of DataDog/documentation (BSD-3-Clause), the "Default Standard Attributes"
table (``hugo/content/en/standard-attributes/_index.md``, whose YAML front matter lists every
reserved and standard attribute with its type, its group and the products that set it), and
writes ``data/catalogs/datadog/attributes.toml`` in ADR 0013's form:

- ``[[reserved]]``: the reserved attributes (a group whose name holds ``Reserved``), searched
  by their bare name (``host``, ``source``, ``status``, ``service``, ``trace_id``,
  ``message``, ``device``, ``env``, ``version``);
- ``[[attributes]]``: the standard attributes, searched as ``@<name>``.

Each row holds facts only: the name, the type, the group (``domain``) and the products (logs,
APM, RUM). Datadog's descriptions are not copied (docs/internal/rfc-datadog-cloud-siem.md, §6.9):
hover is written from the facts. An attribute the table lists twice (once per product family,
such as ``usr.id``) is one row, with the products of both.

Usage:
    python scripts/engine/sync_datadog_catalog.py --docs ../documentation [--check]
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "data" / "catalogs" / "datadog"
REPOSITORY = "DataDog/documentation"
PINNED_COMMIT = "12f7b8d3cc0cea32358affe1ec0fe99fb09e13b0"
PAGE = "hugo/content/en/standard-attributes/_index.md"

# The table's types. A type this list lacks fails the run, so a new one is read before the
# engine relies on it.
TYPES = ("string", "number", "integer", "boolean", "object")

# The table's product icons, as the catalogue names the product. The platform icons
# (`android`, `ios`, `browser`, `roku`, `kotlin-multiplatform`, `flutter`) come with
# `icon-rum` (the page's own build check) and add nothing.
PRODUCTS = {"icon-log": "logs", "icon-apm": "apm", "icon-rum": "rum"}
PLATFORM_ICONS = {"android", "ios", "browser", "roku", "kotlin-multiplatform", "flutter"}


def toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def head_commit(source: Path) -> str | None:
    try:
        out = subprocess.run(
            ["git", "-C", str(source), "rev-parse", "HEAD"],
            check=True,
            capture_output=True,
            text=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    return out.stdout.strip()


def read_attributes(docs: Path) -> list[dict[str, object]]:
    """The rows of the table, merged by name, in the table's order."""
    text = (docs / PAGE).read_text(encoding="utf-8")
    parts = text.split("---")
    if len(parts) < 3:
        raise SystemExit(f"{PAGE}: no YAML front matter")
    front = yaml.safe_load(parts[1])
    rows: dict[str, dict[str, object]] = {}
    for item in front["attributes"]:
        name = str(item["name"]).strip()
        kind = str(item["type"]).strip()
        if kind not in TYPES:
            raise SystemExit(f"{name}: unknown type {kind!r}; add it to TYPES after reading it")
        products: list[str] = []
        for icon in item.get("product_source") or []:
            if icon in PRODUCTS:
                products.append(PRODUCTS[icon])
            elif icon not in PLATFORM_ICONS:
                raise SystemExit(f"{name}: unknown product icon {icon!r}")
        domain = " ".join(str(item["domain"]).split())
        row = rows.get(name)
        if row is None:
            rows[name] = {"name": name, "type": kind, "domain": domain, "products": products}
            continue
        if row["type"] != kind:
            raise SystemExit(f"{name}: listed as {row['type']} and as {kind}")
        merged = list(row["products"])  # type: ignore[arg-type]
        merged.extend(p for p in products if p not in merged)
        row["products"] = merged
    return list(rows.values())


def render(rows: list[dict[str, object]], commit: str) -> str:
    def item(table: str, row: dict[str, object]) -> str:
        products = ", ".join(toml_string(p) for p in row["products"])  # type: ignore[union-attr]
        return (
            f"[[{table}]]\n"
            f"name = {toml_string(str(row['name']))}\n"
            f"type = {toml_string(str(row['type']))}\n"
            f"domain = {toml_string(str(row['domain']))}\n"
            f"products = [{products}]\n"
        )

    reserved = [r for r in rows if "Reserved" in str(r["domain"])]
    standard = [r for r in rows if "Reserved" not in str(r["domain"])]
    out = [
        "# Generated by scripts/engine/sync_datadog_catalog.py. Do not edit.",
        f"# Source: {REPOSITORY}@{commit}, {PAGE}",
        "# BSD-3-Clause (LICENSE-BSD-3-Clause.txt, NOTICE). Facts only: no description is copied.",
        "",
        "# Reserved attributes, searched by their bare name (`host:web-1`).",
    ]
    out.extend(item("reserved", r) for r in reserved)
    out.append("# Standard attributes, searched as `@<name>` (`@network.client.ip:10.0.0.1`).")
    out.extend(item("attributes", r) for r in standard)
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--docs", type=Path, required=True, help="a DataDog/documentation checkout")
    parser.add_argument("--check", action="store_true", help="fail if the output would change")
    args = parser.parse_args()
    commit = head_commit(args.docs) or PINNED_COMMIT
    if commit != PINNED_COMMIT:
        print(
            f"note: {args.docs} is at {commit}, not the pinned {PINNED_COMMIT}; "
            "update PINNED_COMMIT when the new output is reviewed",
            file=sys.stderr,
        )
    text = render(read_attributes(args.docs), commit)
    target = OUT / "attributes.toml"
    if args.check:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != text:
            print(f"{target.relative_to(ROOT)} is stale: re-run the sync", file=sys.stderr)
            return 1
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
