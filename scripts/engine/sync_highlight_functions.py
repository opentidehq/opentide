#!/usr/bin/env python3
"""Generate crates/opentide-highlight/src/function_names.rs.

The TextMate grammars colour a call of a built-in function as
`support.function` (`function.builtin`) before any language server answers.
The names are the catalogs' (`data/catalogs/<lang>/functions.toml`, KQL's under
`kql/core/`), copied here because the highlight crate sits below the language
crates and reads no catalog. Names only: facts, no prose.

Usage:
    python -I scripts/engine/sync_highlight_functions.py [--check]

``--check`` exits 1 when the committed file differs. Standard library only.
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "crates" / "opentide-highlight" / "src" / "function_names.rs"

SOURCES = [
    ("KQL", "kql/core/functions.toml"),
    ("ESQL", "esql/functions.toml"),
    ("EQL", "eql/functions.toml"),
    ("CQL", "cql/functions.toml"),
    ("YARAL", "yaral/functions.toml"),
]
NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_.:]*$")


def render() -> str:
    lines = [
        "//! The built-in function names of each language's catalog, for the TextMate",
        "//! grammars (`tm_extras`). Generated by `scripts/engine/sync_highlight_functions.py`",
        "//! from `data/catalogs/<lang>/functions.toml`; never hand-edit.",
        "",
    ]
    for const, rel in SOURCES:
        data = tomllib.loads((ROOT / "data" / "catalogs" / rel).read_text(encoding="utf-8"))
        names = sorted({f["name"] for f in data["functions"] if NAME.match(f["name"])})
        lines.append(f"pub(crate) const {const}: &[&str] = &[")
        lines += [f'    "{n}",' for n in names]
        lines += ["];", ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    text = render()
    if ap.parse_args().check:
        if OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale: run scripts/engine/sync_highlight_functions.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
