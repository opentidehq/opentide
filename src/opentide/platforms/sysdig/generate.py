"""Write a compiled Falco rule as a Falco rules file (sysdig-1.0, Deploy: file).

The document is built as data and dumped with PyYAML, never concatenated:
leaf lists are written in flow style (``tags: [a, b]``), long lines are not
folded, and a value a YAML 1.1 reader would take for something else (``=``,
``yes``, ``1.0``) is quoted by the dumper.
"""

from __future__ import annotations

from typing import Any

import yaml

from opentide.platforms.sysdig.compile import FalcoRule


class _FalcoDumper(yaml.SafeDumper):
    """Block mappings; a list of scalars in flow style, as Falco's own rules files are."""


def _represent_dict(dumper: yaml.SafeDumper, data: dict[str, Any]) -> yaml.Node:
    return dumper.represent_mapping("tag:yaml.org,2002:map", data, flow_style=False)


def _represent_list(dumper: yaml.SafeDumper, data: list[Any]) -> yaml.Node:
    scalars = all(not isinstance(item, (dict, list)) for item in data)
    return dumper.represent_sequence("tag:yaml.org,2002:seq", data, flow_style=scalars)


_FalcoDumper.add_representer(dict, _represent_dict)
_FalcoDumper.add_representer(list, _represent_list)

HEADER = "# Generated by opentide from rule {uuid}. Do not edit: changes are overwritten.\n"


def falco_items(compiled: FalcoRule) -> list[dict[str, Any]]:
    """The YAML items of the rules file, in Falco's definition-before-use order."""
    items: list[dict[str, Any]] = []
    if compiled.required_engine_version:
        items.append({"required_engine_version": compiled.required_engine_version})
    if compiled.required_plugin_versions:
        items.append({"required_plugin_versions": compiled.required_plugin_versions})
    rule: dict[str, Any] = {"rule": compiled.name}
    if compiled.tuning:
        override: dict[str, str] = {}
        if compiled.condition is not None:
            rule["condition"] = compiled.condition
            override["condition"] = "append"
        if compiled.exceptions:
            rule["exceptions"] = compiled.exceptions
            override["exceptions"] = "append"
        rule["override"] = override
    else:
        rule["desc"] = compiled.desc
        rule["condition"] = compiled.condition
        rule["output"] = compiled.output
        rule["priority"] = compiled.priority
        rule["source"] = compiled.source
        rule["enabled"] = compiled.enabled
        rule["tags"] = compiled.tags
        if compiled.exceptions:
            rule["exceptions"] = compiled.exceptions
    items.append(rule)
    return items


def rules_file(compiled: FalcoRule) -> str:
    """The rules file text: the header comment, then the items. LF line endings."""
    body = yaml.dump(
        falco_items(compiled),
        Dumper=_FalcoDumper,
        sort_keys=False,
        allow_unicode=True,
        width=float("inf"),
    )
    return HEADER.format(uuid=compiled.uuid) + body
