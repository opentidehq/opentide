"""Configure validate-on-commit hooks for detection repositories."""

from __future__ import annotations

import json
import os
import re
import shlex
import subprocess
from dataclasses import dataclass
from pathlib import Path

import structlog
import yaml

from opentide.core.io import parse_yaml
from opentide.registry.discovery import OPENTIDE_DIR, is_opentide_workspace

logger = structlog.get_logger("opentide.cli.services.setup.hooks")

HOOK_ID = "opentide-validate"
HOOK_MARKER = "opentide-setup-hooks"
PRE_COMMIT_CONFIG_PATH = ".pre-commit-config.yaml"
VERSIONED_HOOK_PATH = f"{OPENTIDE_DIR}/hooks/pre-commit"
GIT_HOOK_PATH = ".git/hooks/pre-commit"

#: ``opentide validate`` resolves its tree from ``OPENTIDE_REPO_ROOT`` before it
#: looks at the working directory, and ``.env.example`` tells users to export
#: that variable. A hook that does not pin ``--repo`` therefore validates
#: whichever repository the shell last pointed at and lets broken YAML through.
_TOP_LEVEL = "$(git rev-parse --show-toplevel)"


def _workspace_word(relative: str) -> str:
    """Shell word naming the workspace: the Git root, plus *relative* when nested.

    Git and pre-commit run hooks from the Git root. A workspace in a
    subdirectory has to be named below it, or ``validate --strict`` checks a
    tree with no objects and passes.
    """
    top = f'"{_TOP_LEVEL}"'
    return top if not relative else f"{top}/{shlex.quote(relative)}"


def _workspace_label(relative: str) -> str:
    return relative or "the repository root"


def hook_entry(relative: str = "") -> str:
    """The pre-commit ``entry`` command for a workspace *relative* to the Git root.

    ``validate --strict`` passes on a directory without ``.opentide/``, so a
    pin left behind by a moved or renamed workspace would pass every commit.
    """
    script = (
        f"repo={_workspace_word(relative)}; "
        f'if [ ! -d "$repo/{OPENTIDE_DIR}" ]; then '
        f'echo "No OpenTide workspace at $repo (missing {OPENTIDE_DIR}/). '
        f'Re-run opentide setup hooks, or set SKIP={HOOK_ID} to bypass." >&2; exit 1; fi; '
        'exec opentide --repo "$repo" validate --strict'
    )
    return "sh -c " + shlex.quote(script)


def _yaml_value(value: str) -> str:
    """*value* as a YAML scalar that reads back unchanged.

    A plain scalar ends early at ``": "``, ``" #"`` or a tab before ``#``,
    breaks at a newline, and changes meaning after a leading indicator such
    as ``&`` or ``-``. JSON is a valid double-quoted YAML scalar.
    """
    candidates = [json.dumps(value, ensure_ascii=False), json.dumps(value)]
    if not any(char in value for char in "\t\r\n"):
        candidates.insert(0, value)
    for candidate in candidates:
        try:
            if yaml.safe_load(f"entry: {candidate}") == {"entry": value}:
                return candidate
        except yaml.YAMLError:
            continue
    return json.dumps(value)


HOOK_ENTRY = hook_entry()


def pre_commit_config(relative: str = "") -> str:
    return f"""\
# Generated by OpenTide. Re-run `opentide setup hooks` to refresh.
repos:
{local_hook_block(relative)}"""


def local_hook_block(relative: str = "") -> str:
    return f"""\
  - repo: local
    hooks:
      - id: opentide-validate
        name: opentide validate
        entry: {_yaml_value(hook_entry(relative))}
        language: system
        pass_filenames: false
        always_run: true
"""


#: ``validate --strict`` passes on a missing or empty directory; a hook still
#: pinned to a moved workspace has to fail instead of passing every commit.
_MISSING_WORKSPACE = (
    f"No OpenTide workspace at $OPENTIDE_HOOK_REPO (missing {OPENTIDE_DIR}/). "
    "Re-run 'opentide setup hooks' or set OPENTIDE_SKIP_HOOKS=1 to bypass."
)


#: One line per validated workspace, JSON-encoded so no path can end the comment.
_WORKSPACE_MARKER = "# opentide-workspace: "


def pre_commit_script(*workspaces: str) -> str:
    """Hook script validating each of *workspaces* (relative to the Git root; ``""`` is the root).

    A repository has a single ``pre-commit`` hook, so it has to cover every
    workspace set up in it. Every workspace is validated even after one fails,
    so a commit reports all of its problems at once.
    """
    pinned = workspaces or ("",)
    markers = "".join(f"{_WORKSPACE_MARKER}{json.dumps(w or '.')}\n" for w in pinned)
    words = " ".join(shlex.quote(w or ".") for w in pinned)
    return f"""\
#!/bin/sh
# opentide-setup-hooks: validate detection objects before commit.
# Generated by OpenTide. Re-run `opentide setup hooks` to refresh.
{markers}set -e
if [ -n "${{OPENTIDE_SKIP_HOOKS:-}}" ]; then
  exit 0
fi
if ! command -v opentide >/dev/null 2>&1; then
  echo "opentide not found on PATH. Install the package or set OPENTIDE_SKIP_HOOKS=1 to bypass." >&2
  exit 1
fi
# Validate the worktree being committed, not whatever OPENTIDE_REPO_ROOT names.
OPENTIDE_HOOK_TOP={_TOP_LEVEL}
OPENTIDE_HOOK_STATUS=0
for OPENTIDE_HOOK_WORKSPACE in {words}; do
  if [ "$OPENTIDE_HOOK_WORKSPACE" = . ]; then
    OPENTIDE_HOOK_REPO=$OPENTIDE_HOOK_TOP
  else
    OPENTIDE_HOOK_REPO=$OPENTIDE_HOOK_TOP/$OPENTIDE_HOOK_WORKSPACE
  fi
  if [ ! -d "$OPENTIDE_HOOK_REPO/{OPENTIDE_DIR}" ]; then
    echo "{_MISSING_WORKSPACE}" >&2
    OPENTIDE_HOOK_STATUS=1
  elif ! opentide --repo "$OPENTIDE_HOOK_REPO" validate --strict; then
    OPENTIDE_HOOK_STATUS=1
  fi
done
exit "$OPENTIDE_HOOK_STATUS"
"""


PRE_COMMIT_CONFIG = pre_commit_config()
LOCAL_HOOK_BLOCK = local_hook_block()
