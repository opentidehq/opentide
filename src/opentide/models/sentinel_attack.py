"""The ATT&CK ids Microsoft Sentinel accepts in ``configurations.sentinel.alert.techniques``.

Sentinel is aligned to ATT&CK v18, while opentide's ``att&ck`` vocabulary follows
the current release, so the Sentinel field carries its own list rather than the
vocabulary's: every technique and sub-technique of the ATT&CK 18.1 Enterprise,
Mobile and ICS matrices that is neither revoked nor deprecated (18.0 has the same
ids). The list lives in ``data/sentinel/attack-v18.json``, generated by
``scripts/build/sync_sentinel_attack.py``; nothing outside the Sentinel schema
reads it (#686). The file also names the ids of the release the vocabulary pins
that are not in v18, with the v18 ids they replaced, and the ids ATT&CK retired
before v18, with the v18 ids that replaced them, so a rejected id comes with what
to write instead.
"""

from __future__ import annotations

import difflib
import json
from collections.abc import Mapping
from functools import cache
from importlib.resources import files
from types import MappingProxyType
from typing import Annotated, Any

from pydantic import AfterValidator, Field, JsonValue
from pydantic_core import PydanticCustomError

#: The ATT&CK major version Sentinel is aligned to.
SENTINEL_ATTACK_VERSION = "18"


@cache
def _data() -> dict[str, Any]:
    text = (files("opentide.data") / "sentinel" / "attack-v18.json").read_text(encoding="utf-8")
    return dict(json.loads(text))


def sentinel_techniques() -> Mapping[str, str]:
    """``{id: name}`` for every id Sentinel accepts, sorted by id."""
    return MappingProxyType(_data()["techniques"])


def _hint(value: str, known: Mapping[str, str]) -> str:
    """What to write instead of *value*, or ``""``."""
    later = _data()["later"]
    if entry := later["techniques"].get(value):
        newer = f"; {value} ({entry['name']}) is newer than ATT&CK v{SENTINEL_ATTACK_VERSION}"
        if replaced := entry["replaces"]:
            return f"{newer}: use {' or '.join(replaced)}, which it replaced"
        return f"{newer} and has no v{SENTINEL_ATTACK_VERSION} equivalent"
    if entry := _data()["retired"].get(value):
        retired = f"; ATT&CK retired {value} ({entry['name']}) before v{SENTINEL_ATTACK_VERSION}"
        if replaced := entry["replaced_by"]:
            return f"{retired}: use {' or '.join(replaced)}, which replaced it"
        return f"{retired} without a replacement"
    close = difflib.get_close_matches(value.strip().upper(), list(known), n=1, cutoff=0.8)
    return f"; did you mean {close[0]} ({known[close[0]]})?" if close else ""


def check_sentinel_technique(value: str) -> str:
    """Return *value* when it is an ATT&CK v18 id; raise ``sentinel_attack_technique`` otherwise."""
    known = sentinel_techniques()
    if value in known:
        return value
    hint = _hint(value, known)
    raise PydanticCustomError(
        "sentinel_attack_technique",
        "{value} is not an ATT&CK v{version} technique or sub-technique id, which is what "
        "Sentinel is aligned to{hint}",
        {"value": repr(value), "version": SENTINEL_ATTACK_VERSION, "hint": hint},
    )


def _item_schema(schema: dict[str, JsonValue]) -> None:
    """Add the v18 ids to an item schema, when a schema is generated rather than at import."""
    techniques = sentinel_techniques()
    schema["enum"] = list(techniques)
    schema["markdownEnumDescriptions"] = [f"**{key}** {name}" for key, name in techniques.items()]


#: One ``alert.techniques`` entry: an ATT&CK v18 technique or sub-technique id.
SentinelTechnique = Annotated[
    str,
    AfterValidator(check_sentinel_technique),
    Field(json_schema_extra=_item_schema),
]
