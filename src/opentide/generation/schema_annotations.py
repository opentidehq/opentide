"""Editor annotations on generated JSON Schemas.

Adds annotation keywords only, so validation is unchanged:

* a root ``$comment`` naming opentide and its tagline, and a root
  ``description`` when the schema has none;
* ``markdownDescription`` next to a ``description`` written in Markdown, which
  then becomes plain text (VS Code renders the first, other editors the second);
* ``enumDescriptions`` derived from ``markdownEnumDescriptions`` when an enum
  has only the Markdown form, and ``x-enumDescriptions`` mirroring
  ``enumDescriptions`` for editors that do not read VS Code's keyword.
"""

from __future__ import annotations

import re
from typing import Any

TAGLINE = "Spec-driven development for agentic detection engineering"
SCHEMA_COMMENT = (
    f"Generated by opentide, {TAGLINE[0].lower()}{TAGLINE[1:]}. "
    "Regenerate with `opentide generate schemas`; do not edit by hand."
)

#: Keywords whose values are data, not subschemas: never rewrite inside them.
_DATA_KEYWORDS = frozenset(
    {
        "const",
        "default",
        "enum",
        "examples",
        "enumDescriptions",
        "markdownEnumDescriptions",
        "x-enumDescriptions",
    }
)

#: Keywords whose values map names to subschemas.
_SCHEMA_MAPS = frozenset({"properties", "patternProperties", "$defs", "definitions"})

_LINK = re.compile(r"\[([^\]]+)\]\([^)]*\)")
_EMPHASIS = re.compile(r"(\*\*|__)(.+?)\1")
_ITALIC = re.compile(r"(?<![\w`])_(?=\S)([^_\n]+?)(?<=\S)_(?![\w`])")
#: ATT&CK descriptions carry ``(Citation: ...)`` markers and inline HTML.
_CITATION = re.compile(r"\s*\(Citation:[^)]*\)")
_HTML_TAG = re.compile(r"</?[a-zA-Z][^>]*>")
_HEADING = re.compile(r"^#{1,6}\s+", re.MULTILINE)
_MARKDOWN = re.compile(r"`|\*\*|__|\[[^\]]+\]\([^)]*\)|^#{1,6}\s", re.MULTILINE)


def _unwrap(text: str) -> str:
    """Join hard-wrapped lines; keep blank-line paragraph breaks."""
    paragraphs = re.split(r"\n\s*\n", text.strip())
    return "\n\n".join(" ".join(part.split()) for part in paragraphs if part.strip())


_SENTENCE_END = re.compile(r"[.!?](?=\s|$)")
_ABBREVIATIONS = ("e.g", "i.e", "etc", "vs", "cf", "Inc", "Ltd", "No")


def first_sentence(text: str) -> str:
    """First sentence of *text*, whitespace collapsed.

    Enum value descriptions are cut to it: full vocabulary descriptions
    already sit in ``markdownEnumDescriptions``, and a second and third full
    copy more than doubled the size of the largest schemas.
    """
    flat = " ".join(_HTML_TAG.sub("", _CITATION.sub("", text)).split())
    for match in _SENTENCE_END.finditer(flat):
        head = flat[: match.start()]
        if head.endswith(_ABBREVIATIONS) or re.search(r"\b[A-Z]$", head):
            continue
        return flat[: match.end()]
    return flat


def plain_text(markdown: str, *, one_line: bool = False) -> str:
    """Markdown to plain text: one paragraph per Markdown paragraph, or one line."""
    text = _LINK.sub(r"\1", markdown)
    text = _HEADING.sub("", text)
    text = _EMPHASIS.sub(r"\2", text)
    text = _ITALIC.sub(r"\1", text)
    text = text.replace("`", "")
    return " ".join(text.split()) if one_line else _unwrap(text)


def _annotate_description(node: dict[str, Any]) -> None:
    description = node.get("description")
    if not isinstance(description, str):
        return
    if "markdownDescription" not in node and _MARKDOWN.search(description):
        # Kept as written: a line break inside a Markdown list is meaningful.
        node["markdownDescription"] = description.strip()
        node["description"] = plain_text(description)
    else:
        node["description"] = _unwrap(description)


def _annotate_enum(node: dict[str, Any]) -> None:
    enum = node.get("enum")
    if not isinstance(enum, list):
        return
    markdown = node.get("markdownEnumDescriptions")
    if "enumDescriptions" not in node and isinstance(markdown, list) and len(markdown) == len(enum):
        node["enumDescriptions"] = [plain_text(str(item), one_line=True) for item in markdown]
    plain = node.get("enumDescriptions")
    if isinstance(plain, list) and "x-enumDescriptions" not in node:
        node["x-enumDescriptions"] = list(plain)


def _walk(node: Any) -> None:
    if isinstance(node, list):
        for item in node:
            _walk(item)
        return
    if not isinstance(node, dict):
        return
    _annotate_description(node)
    _annotate_enum(node)
    for key, value in node.items():
        if key in _SCHEMA_MAPS and isinstance(value, dict):
            # Keys here are property names, so a field called ``default`` is
            # still a subschema.
            for subschema in value.values():
                _walk(subschema)
        elif key not in _DATA_KEYWORDS:
            _walk(value)


def annotate_editor_schema(schema: dict[str, Any]) -> dict[str, Any]:
    """Add editor annotations to *schema* in place and return it."""
    schema.setdefault("$comment", SCHEMA_COMMENT)
    if not isinstance(schema.get("description"), str):
        title = schema.get("title")
        subject = f"{title}, generated" if isinstance(title, str) and title else "Generated"
        schema["description"] = f"{subject} by opentide: {TAGLINE.lower()}."
    _walk(schema)
    return schema
