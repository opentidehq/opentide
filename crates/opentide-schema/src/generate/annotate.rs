    #[test]
    fn the_hand_written_matches_equal_the_patterns_on_every_bundled_description() {
        let vocabularies = crate::vocab::Vocabularies::bundled();
        let mut count = 0;
        for field in vocabularies.fields() {
            let Some(vocabulary) = vocabularies.get(field) else {
                continue;
            };
            for entry in vocabulary.entries.values() {
                assert_as_the_patterns(&entry.description);
                count += 1;
            }
        }
        assert!(count > 1000, "{count} descriptions");
    }

    #[test]
    fn the_hand_written_matches_equal_the_patterns_on_generated_text() {
        // A fixed xorshift over the characters the patterns look at.
        const ALPHABET: &[&str] = &[
            "_", "_", "*", "*", "#", "-", "+", "`", "\n", "\n", " ", "\t", "1", ".", "a", "B", "é",
            "\u{a0}", "!", "?", "😀", "\u{2003}",
        ];
        let mut state: u64 = 0x9e37_79b9_7f4a_7c15;
        let mut next = || {
            state ^= state << 13;
            state ^= state >> 7;
            state ^= state << 17;
            usize::try_from(state % 1024).unwrap()
        };
        for _ in 0..20_000 {
            let length = next() % 24;
            let text: String = (0..length)
                .map(|_| ALPHABET[next() % ALPHABET.len()])
                .collect();
            assert_as_the_patterns(&text);
        }
    }
