//! The YAML node tree a model is converted from (UC-1.2, #808), read as the
//! oracle reads an object file.
//!
//! The oracle (opentide 0.23.0) reads YAML with `opentide.core.io.load_yaml`:
//! UTF-8 with an optional BOM, PyYAML's `CSafeLoader` (libyaml, YAML 1.1),
//! timestamps turned into ISO 8601 text, and a document refused when it repeats
//! a key or holds a recursive alias. This module does the same:
//!
//! - **The parser is libyaml.** [`libyaml_safer`] is libyaml ported to safe
//!   Rust, so what parses, what does not, and every mark (line, column) are
//!   the oracle's. saphyr, the other candidate the issue names, is a YAML 1.2
//!   parser: it accepts and refuses other documents (tabs, `%YAML 1.1`,
//!   duplicate anchors) and does not report anchor names.
//! - **Resolution is PyYAML's** (YAML 1.1, [`yaml11`]): `yes`/`on` are
//!   booleans and `y`/`n` strings, `017` is octal and `0o17` a string, `1_000`
//!   and `1:20` are integers, `.inf`, dates become text.
//! - **Construction is `SafeConstructor`'s**: merge keys (`<<`), aliases
//!   (shared, never copied: a node aliased a million times costs one node),
//!   dictionary semantics for keys (the first position, the last value).
//!
//! The table of each rule against PyYAML is `tests/oracle/yaml_table.json`,
//! generated by `tests/oracle/yaml_table.py` and checked by
//! `tests/yaml_table.rs`.
//!
//! Positions are the parser's: 0-based lines, columns in Unicode code points
//! (the CLI prints both 1-based). [`Document::span`] and
//! [`Document::yaml_line`] compute where the CLI points for a field path, as
//! `opentide.cli.ui.diagnostics.SourceFiles.span` and
//! `opentide.validation.errors._find_line` do.

