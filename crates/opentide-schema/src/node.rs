/// A position in the document: the byte offset, the 0-based line and the
/// 0-based column in Unicode code points, as libyaml counts them.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash)]
pub struct Mark {
    /// Byte offset in the text the document was read from (after its BOM).
    pub index: usize,
    /// Line, from 0.
    pub line: usize,
    /// Column, from 0, in code points.
    pub column: usize,
}

impl Mark {
    fn from_libyaml(mark: libyaml_safer::Mark) -> Self {
        Self {
            index: usize::try_from(mark.index).unwrap_or(usize::MAX),
            line: usize::try_from(mark.line).unwrap_or(usize::MAX),
            column: usize::try_from(mark.column).unwrap_or(usize::MAX),
        }
    }
}

/// One node of the tree, where it starts and ends.
#[derive(Debug, Clone, PartialEq)]
pub struct Node {
    /// The value.
    pub value: Value,
    /// Where the node starts: its anchor or tag when it has one, as libyaml
    /// and PyYAML mark it.
    pub start: Mark,
    /// Where the node ends.
    pub end: Mark,
}

/// A key and its value in a mapping.
#[derive(Debug, Clone, PartialEq)]
pub struct Entry {
    /// The key node.
    pub key: Arc<Node>,
    /// The value node.
    pub value: Arc<Node>,
    /// The entry came from a merge key (`<<`), not from the mapping itself.
    /// The CLI's position lookup (ruamel.yaml's line markers) has no
    /// position for it.
    pub merged: bool,
}

/// A value, as Python holds what PyYAML constructed.
#[derive(Debug, Clone, PartialEq)]
pub enum Value {
    /// `None`.
    Null,
    /// `bool`.
    Bool(bool),
    /// `int`, of any size.
    Int(Integer),
    /// `float`.
    Float(f64),
    /// `str`; dates and timestamps are text (`2026-01-01T10:00:00Z`).
    Str(String),
    /// `list`.
    Seq(Vec<Arc<Node>>),
    /// `dict`: keys unique under Python's equality, in the order each first
    /// appeared, each with the value it was last given.
    Map(Vec<Entry>),
}

impl Value {
    /// Python's `str()` of a key or scalar: `None`, `True`, `12`, `1.5`, the
    /// text. A field path holds keys this way (`validation/errors.py`).
    pub fn python_str(&self) -> String {
        match self {
            Self::Null => "None".to_owned(),
            Self::Bool(true) => "True".to_owned(),
            Self::Bool(false) => "False".to_owned(),
            Self::Int(integer) => integer.to_string(),
            Self::Float(float) => python_float_repr(*float),
            Self::Str(text) => text.clone(),
            Self::Seq(_) => "[...]".to_owned(),
            Self::Map(_) => "{...}".to_owned(),
        }
    }

    /// The Python type's name: `NoneType`, `bool`, `int`, `float`, `str`,
    /// `list`, `dict`.
    pub fn type_name(&self) -> &'static str {
        match self {
            Self::Null => "NoneType",
            Self::Bool(_) => "bool",
            Self::Int(_) => "int",
            Self::Float(_) => "float",
            Self::Str(_) => "str",
            Self::Seq(_) => "list",
            Self::Map(_) => "dict",
        }
    }

    /// The text, for a `str`.
    pub fn as_str(&self) -> Option<&str> {
        match self {
            Self::Str(text) => Some(text),
            _ => None,
        }
    }
}

impl Node {
    /// The value of `key` in this mapping (a `str` key equal to `key`).
    pub fn get(&self, key: &str) -> Option<&Arc<Node>> {
        self.entry(key).map(|entry| &entry.value)
    }

    /// The entry of `key` in this mapping (a `str` key equal to `key`).
    pub fn entry(&self, key: &str) -> Option<&Entry> {
        match &self.value {
            Value::Map(entries) => entries
                .iter()
                .find(|entry| entry.key.value.as_str() == Some(key)),
            _ => None,
        }
    }
}

// A deep tree (ten thousand nested lists, which the oracle reads) would
// overflow the stack if dropped recursively: children are moved out and
// dropped one by one.
impl Drop for Node {
    fn drop(&mut self) {
        let mut stack: Vec<Arc<Node>> = Vec::new();
        take_children(&mut self.value, &mut stack);
        while let Some(child) = stack.pop() {
            if let Some(mut node) = Arc::into_inner(child) {
                take_children(&mut node.value, &mut stack);
            }
        }
    }
}

fn take_children(value: &mut Value, stack: &mut Vec<Arc<Node>>) {
    match value {
        Value::Seq(items) => stack.append(items),
        Value::Map(entries) => {
            for entry in entries.drain(..) {
                stack.push(entry.key);
                stack.push(entry.value);
            }
        }
        _ => {}
    }
}

/// Why a document could not be read.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum LoadErrorKind {
    /// The bytes are not UTF-8 (`UnicodeDecodeError`).
    NotUtf8,
    /// A `yaml.YAMLError`: the parser's, a duplicate key, a recursive alias,
    /// an unknown tag, a date that cannot exist. The CLI reports `yaml_parse`.
    Yaml,
    /// An exception PyYAML raises that is not a `YAMLError` (`!!int 0b_`,
    /// `!!bool maybe`): the oracle's loader lets it escape.
    Python,
    /// A tag PyYAML constructs and the tree has no value for: `!!binary`,
    /// `!!omap`, `!!pairs`, `!!set`. The oracle reads them; this is a known
    /// difference, recorded in `tests/oracle/yaml_table.json`.
    Unsupported,
}

/// A document that could not be read: what PyYAML's `MarkedYAMLError` holds.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("{problem}")]
pub struct LoadError {
    /// What kind of failure.
    pub kind: LoadErrorKind,
    /// The problem, in libyaml's or PyYAML's words where they have one.
    pub problem: String,
    /// Where the problem is.
    pub problem_mark: Option<Mark>,
    /// What the parser was doing (`while parsing a flow sequence`).
    pub context: Option<String>,
    /// Where that started.
    pub context_mark: Option<Mark>,
}

impl LoadError {
    fn new(kind: LoadErrorKind, problem: impl Into<String>, mark: Option<Mark>) -> Self {
        Self {
            kind,
            problem: problem.into(),
            problem_mark: mark,
            context: None,
            context_mark: None,
        }
    }

    fn yaml(problem: impl Into<String>, mark: Mark) -> Self {
        Self::new(LoadErrorKind::Yaml, problem, Some(mark))
    }

    fn from_libyaml(error: &libyaml_safer::Error) -> Self {
        Self {
            kind: LoadErrorKind::Yaml,
            problem: error.problem().to_owned(),
            problem_mark: error.problem_mark().map(Mark::from_libyaml),
            context: error.context().map(str::to_owned),
            context_mark: error.context_mark().map(Mark::from_libyaml),
        }
    }
}

/// A document read from text: the text, for positions, and its root node
/// (`None` for a stream with no document: empty, or only comments).
#[derive(Debug, Clone)]
pub struct Document {
    source: String,
    root: Option<Arc<Node>>,
}

impl Document {
    /// The root node.
    pub fn root(&self) -> Option<&Arc<Node>> {
        self.root.as_ref()
    }

    /// The text the document was read from, without its BOM.
    pub fn source(&self) -> &str {
        &self.source
    }
}

/// Reads `bytes` as `load_yaml` reads a file: UTF-8 with an optional BOM
/// (`utf-8-sig`), then [`load`].
pub fn load_bytes(bytes: &[u8]) -> Result<Document, LoadError> {
    let text = std::str::from_utf8(bytes).map_err(|error| {
        LoadError::new(
            LoadErrorKind::NotUtf8,
            format!("not UTF-8 at byte offset {}", error.valid_up_to()),
            None,
        )
    })?;
    load(text)
}

/// Reads `text` as `opentide.core.io.parse_yaml` does (one leading BOM is
/// dropped, as reading the file with `utf-8-sig` drops it).
pub fn load(text: &str) -> Result<Document, LoadError> {
    let source = text.strip_prefix('\u{feff}').unwrap_or(text).to_owned();
    let root = Composer::default().run(&source)?;
    Ok(Document { source, root })
}

/// A finished node with what composing its parent still needs.
#[derive(Debug, Clone)]
struct Built {
    node: Arc<Node>,
    /// The tag it resolved to (a key tagged `merge` is merged).
    tag: Tag,
    /// The raw text, for a scalar: `_reject_duplicate_keys` compares keys on it.
    raw: Option<String>,
}

#[derive(Debug)]
enum Frame {
    Seq {
        tag: Tag,
        anchor: Option<String>,
        start: Mark,
        items: Vec<Built>,
    },
    Map {
        tag: Tag,
        anchor: Option<String>,
        start: Mark,
        pairs: Vec<(Built, Built)>,
        key: Option<Built>,
        /// Block style (`key: value` lines), not flow (`{key: value}`).
        block: bool,
    },
}

/// Composes events into nodes and constructs each as it completes: one
/// iterative pass, so nesting depth costs no stack.
#[derive(Debug, Default)]
struct Composer {
    frames: Vec<Frame>,
    anchors: BTreeMap<String, Built>,
    /// Anchors of collections not finished yet: an alias to one is recursive.
    open: BTreeSet<String>,
    /// The first error PyYAML finds after composing (`_reject_duplicate_keys`).
    check_error: Option<LoadError>,
    /// The first error constructing a value.
    construct_error: Option<LoadError>,
    documents: usize,
    root: Option<Built>,
    /// An empty value of a block mapping, waiting for the next event's mark.
    pending_empty: Option<Built>,
}

fn collection_tag(tag: Option<&str>, default: Tag) -> Tag {
    match tag {
        None | Some("!") => default,
        Some(tag) => Tag::explicit(tag),
    }
}

impl Composer {
    fn run(mut self, source: &str) -> Result<Option<Arc<Node>>, LoadError> {
        let mut bytes = source.as_bytes();
        let mut parser = Parser::new();
        parser.set_input_string(&mut bytes);
        loop {
            let event = parser
                .parse()
                .map_err(|error| LoadError::from_libyaml(&error))?;
            let start = Mark::from_libyaml(event.start_mark);
            let end = Mark::from_libyaml(event.end_mark);
            if let Some(empty) = self.pending_empty.take() {
                self.complete(empty_at(empty, start, source));
            }
            match event.data {
                EventData::StreamStart { .. } | EventData::DocumentEnd { .. } => {}
                EventData::StreamEnd => break,
                EventData::DocumentStart { .. } => {
                    self.documents += 1;
                    if self.documents > 1 {
                        return Err(LoadError::yaml(
                            "expected a single document in the stream, but found another \
                             document",
                            start,
                        ));
                    }
                }
                EventData::Alias { anchor } => {
                    if self.open.contains(&anchor) {
                        // PyYAML composes it, then `_reject_duplicate_keys`
                        // refuses the cycle; no tree can hold one.
                        return Err(LoadError::yaml(
                            format!("recursive alias at line {}", start.line + 1),
                            start,
                        ));
                    }
                    let Some(built) = self.anchors.get(&anchor).cloned() else {
                        return Err(LoadError::yaml(
                            format!("found undefined alias {anchor:?}"),
                            start,
                        ));
                    };
                    self.complete(built);
                }
                EventData::Scalar {
                    anchor,
                    tag,
                    value,
                    plain_implicit,
                    ..
                } => {
                    self.register(anchor.as_deref(), start)?;
                    let tag = match tag.as_deref() {
                        None | Some("!") if plain_implicit => yaml11::resolve_plain(&value),
                        None | Some("!") => Tag::Str,
                        Some(tag) => Tag::explicit(tag),
                    };
                    let node_value = self.construct_scalar(&tag, &value, start);
                    let built = Built {
                        node: Arc::new(Node {
                            value: node_value,
                            start,
                            end,
                        }),
                        tag,
                        raw: Some(value),
                    };
                    let is_empty_block_value = built.raw.as_deref() == Some("")
                        && anchor.is_none()
                        && start == end
                        && plain_implicit
                        && matches!(
                            self.frames.last(),
                            Some(Frame::Map {
                                key: Some(_),
                                block: true,
                                ..
                            })
                        );
                    if let Some(name) = anchor {
                        self.anchors.insert(name, built.clone());
                    }
                    if is_empty_block_value {
                        self.pending_empty = Some(built);
                    } else {
                        self.complete(built);
                    }
                }
                EventData::SequenceStart { anchor, tag, .. } => {
                    self.register(anchor.as_deref(), start)?;
                    if let Some(name) = &anchor {
                        self.open.insert(name.clone());
                    }
                    self.frames.push(Frame::Seq {
                        tag: collection_tag(tag.as_deref(), Tag::Seq),
                        anchor,
                        start,
                        items: Vec::new(),
                    });
                }
                EventData::MappingStart {
                    anchor, tag, style, ..
                } => {
                    self.register(anchor.as_deref(), start)?;
                    if let Some(name) = &anchor {
                        self.open.insert(name.clone());
                    }
                    self.frames.push(Frame::Map {
                        tag: collection_tag(tag.as_deref(), Tag::Map),
                        anchor,
                        start,
                        pairs: Vec::new(),
                        key: None,
                        block: style == MappingStyle::Block,
                    });
                }
                EventData::SequenceEnd => {
                    let Some(Frame::Seq {
                        tag,
                        anchor,
                        start,
                        items,
                    }) = self.frames.pop()
                    else {
                        return Err(LoadError::yaml("unbalanced sequence end", start));
                    };
                    let value = self.construct_seq(&tag, items, start);
                    self.finish(anchor, tag, value, start, end)?;
                }
                EventData::MappingEnd => {
                    let Some(Frame::Map {
                        tag,
                        anchor,
                        start,
                        pairs,
                        ..
                    }) = self.frames.pop()
                    else {
                        return Err(LoadError::yaml("unbalanced mapping end", start));
                    };
                    self.check_duplicates(&pairs);
                    let value = self.construct_map(&tag, pairs, start);
                    self.finish(anchor, tag, value, start, end)?;
                }
            }
        }
        if let Some(error) = self.check_error.take() {
            return Err(error);
        }
        if let Some(error) = self.construct_error.take() {
            return Err(error);
        }
        Ok(self.root.map(|built| built.node))
    }

    /// PyYAML's composer refuses an anchor defined twice in one document.
    fn register(&mut self, anchor: Option<&str>, start: Mark) -> Result<(), LoadError> {
        if let Some(name) = anchor
            && (self.anchors.contains_key(name) || self.open.contains(name))
        {
            let mut error = LoadError::yaml("second occurrence", start);
            error.context = Some(format!("found duplicate anchor {name:?}; first occurrence"));
            return Err(error);
        }
        Ok(())
    }

    fn finish(
        &mut self,
        anchor: Option<String>,
        tag: Tag,
        value: Value,
        start: Mark,
        end: Mark,
    ) -> Result<(), LoadError> {
        let built = Built {
            node: Arc::new(Node { value, start, end }),
            tag,
            raw: None,
        };
        if let Some(name) = anchor {
            self.open.remove(&name);
            self.anchors.insert(name, built.clone());
        }
        self.complete(built);
        Ok(())
    }

    /// Hands a finished node to the collection it belongs to.
    fn complete(&mut self, built: Built) {
        let is_key = matches!(self.frames.last(), Some(Frame::Map { key: None, .. }));
        if !is_key && matches!(built.tag, Tag::Merge | Tag::Value) {
            self.fail_construct(LoadError::yaml(
                format!(
                    "could not determine a constructor for the tag '{}'",
                    built.tag.name()
                ),
                built.node.start,
            ));
        }
        match self.frames.last_mut() {
            None => self.root = Some(built),
            Some(Frame::Seq { items, .. }) => items.push(built),
            Some(Frame::Map { pairs, key, .. }) => match key.take() {
                None => *key = Some(built),
                Some(k) => pairs.push((k, built)),
            },
        }
    }

    fn fail_construct(&mut self, error: LoadError) {
        self.construct_error.get_or_insert(error);
    }

    fn construct_scalar(&mut self, tag: &Tag, value: &str, start: Mark) -> Value {
        let result = match tag {
            Tag::Null => Ok(Scalar::Null),
            Tag::Bool => yaml11::construct_bool(value),
            Tag::Int => yaml11::construct_int(value),
            Tag::Float => yaml11::construct_float(value),
            Tag::Timestamp => yaml11::construct_timestamp(value),
            Tag::Str => Ok(Scalar::Str(value.to_owned())),
            // As a key, `<<` is merged and `=` is a string (`flatten_mapping`).
            // Anywhere else PyYAML has no constructor for them: `complete`
            // reports that once it knows where the node is.
            Tag::Merge | Tag::Value => Ok(Scalar::Str(value.to_owned())),
            Tag::Unknown(_) => Err(ScalarError::Yaml(format!(
                "could not determine a constructor for the tag '{}'",
                tag.name()
            ))),
            Tag::Seq | Tag::Map => Err(ScalarError::Yaml(format!(
                "expected a {} node, but found scalar",
                if *tag == Tag::Seq {
                    "sequence"
                } else {
                    "mapping"
                }
            ))),
            Tag::Unsupported(name) => {
                self.fail_construct(LoadError::new(
                    LoadErrorKind::Unsupported,
                    format!("the tag !!{name} is not supported"),
                    Some(start),
                ));
                return Value::Null;
            }
        };
        match result {
            Ok(Scalar::Null) => Value::Null,
            Ok(Scalar::Bool(flag)) => Value::Bool(flag),
            Ok(Scalar::Int(integer)) => Value::Int(integer),
            Ok(Scalar::Float(float)) => Value::Float(float),
            Ok(Scalar::Str(text)) => Value::Str(text),
            Err(ScalarError::Yaml(problem)) => {
                self.fail_construct(LoadError::yaml(problem, start));
                Value::Null
            }
            Err(ScalarError::Python(problem)) => {
                self.fail_construct(LoadError::new(LoadErrorKind::Python, problem, Some(start)));
                Value::Null
            }
        }
    }

    fn construct_seq(&mut self, tag: &Tag, items: Vec<Built>, start: Mark) -> Value {
        match tag {
            Tag::Seq => {}
            Tag::Unsupported(name) => self.fail_construct(LoadError::new(
                LoadErrorKind::Unsupported,
                format!("the tag !!{name} is not supported"),
                Some(start),
            )),
            Tag::Map
            | Tag::Str
            | Tag::Null
            | Tag::Bool
            | Tag::Int
            | Tag::Float
            | Tag::Timestamp => {
                self.fail_construct(LoadError::yaml(
                    format!(
                        "expected a {} node, but found sequence",
                        if *tag == Tag::Map {
                            "mapping"
                        } else {
                            "scalar"
                        }
                    ),
                    start,
                ));
            }
            Tag::Merge | Tag::Value | Tag::Unknown(_) => self.fail_construct(LoadError::yaml(
                format!(
                    "could not determine a constructor for the tag '{}'",
                    tag.name()
                ),
                start,
            )),
        }
        Value::Seq(items.into_iter().map(|built| built.node).collect())
    }

    /// `_reject_duplicate_keys`: a mapping may not repeat a key's text.
    fn check_duplicates(&mut self, pairs: &[(Built, Built)]) {
        if self.check_error.is_some() {
            return;
        }
        let mut seen: BTreeSet<String> = BTreeSet::new();
        for (key, _) in pairs {
            let text = key
                .raw
                .clone()
                .unwrap_or_else(|| format!("{:p}", Arc::as_ptr(&key.node)));
            if !seen.insert(text.clone()) {
                let mut error = LoadError::yaml(
                    format!("duplicate key {}", python_str_repr(&text)),
                    key.node.start,
                );
                error.problem = format!(
                    "duplicate key {} at line {}",
                    python_str_repr(&text),
                    key.node.start.line + 1
                );
                self.check_error = Some(error);
                return;
            }
        }
    }

    fn construct_map(&mut self, tag: &Tag, pairs: Vec<(Built, Built)>, start: Mark) -> Value {
        match tag {
            Tag::Map => {}
            Tag::Unsupported(name) => self.fail_construct(LoadError::new(
                LoadErrorKind::Unsupported,
                format!("the tag !!{name} is not supported"),
                Some(start),
            )),
            Tag::Merge | Tag::Value | Tag::Unknown(_) => self.fail_construct(LoadError::yaml(
                format!(
                    "could not determine a constructor for the tag '{}'",
                    tag.name()
                ),
                start,
            )),
            _ => self.fail_construct(LoadError::yaml(
                format!(
                    "expected a {} node, but found mapping",
                    if *tag == Tag::Seq {
                        "sequence"
                    } else {
                        "scalar"
                    }
                ),
                start,
            )),
        }
        // `flatten_mapping`: merged pairs first (a list of mappings in
        // reverse), then the mapping's own.
        let mut merged: Vec<Entry> = Vec::new();
        let mut own: Vec<Entry> = Vec::new();
        for (key, value) in pairs {
            if key.tag == Tag::Merge {
                match &value.node.value {
                    Value::Map(entries) => merged.extend(entries.iter().map(merged_entry)),
                    Value::Seq(items) => {
                        let mut groups = Vec::new();
                        for item in items {
                            match &item.value {
                                Value::Map(entries) => {
                                    groups
                                        .push(entries.iter().map(merged_entry).collect::<Vec<_>>());
                                }
                                other => {
                                    self.fail_construct(LoadError::yaml(
                                        format!(
                                            "expected a mapping for merging, but found {}",
                                            node_id(other)
                                        ),
                                        item.start,
                                    ));
                                }
                            }
                        }
                        for group in groups.into_iter().rev() {
                            merged.extend(group);
                        }
                    }
                    other => self.fail_construct(LoadError::yaml(
                        format!(
                            "expected a mapping or list of mappings for merging, but found {}",
                            node_id(other)
                        ),
                        value.node.start,
                    )),
                }
                continue;
            }
            let key_node = if key.tag == Tag::Value {
                // `flatten_mapping` retags a `=` key as a string.
                Arc::new(Node {
                    value: Value::Str(key.raw.clone().unwrap_or_default()),
                    start: key.node.start,
                    end: key.node.end,
                })
            } else {
                key.node.clone()
            };
            if matches!(key_node.value, Value::Seq(_) | Value::Map(_)) {
                self.fail_construct(LoadError::yaml("found unhashable key", key_node.start));
                continue;
            }
            own.push(Entry {
                key: key_node,
                value: value.node,
                merged: false,
            });
        }
        let mut entries: Vec<Entry> = Vec::with_capacity(merged.len() + own.len());
        for entry in merged.into_iter().chain(own) {
            match entries
                .iter_mut()
                .find(|existing| python_key_eq(&existing.key.value, &entry.key.value))
            {
                Some(existing) => {
                    // Python keeps the first key object (`1` stays `1` when
                    // `true` overrides it); the CLI's positions (ruamel) are
                    // the last writer's.
                    existing.key = Arc::new(Node {
                        value: existing.key.value.clone(),
                        start: entry.key.start,
                        end: entry.key.end,
                    });
                    existing.value = entry.value;
                    existing.merged = entry.merged;
                }
                None => entries.push(entry),
            }
        }
        Value::Map(entries)
    }
}

fn merged_entry(entry: &Entry) -> Entry {
    Entry {
        merged: true,
        ..entry.clone()
    }
}

/// Where the CLI's position reader (ruamel.yaml) marks an empty value of a
/// block mapping (`key:` and nothing): at the next token, the next key or the
/// end of the block, which is where `next` (the next event) starts; at the
/// colon when a comment follows it on the line (ruamel attaches the comment to
/// the `:` token and then keeps its mark). libyaml marks it at the colon.
fn empty_at(mut empty: Built, next: Mark, source: &str) -> Built {
    let colon = empty.node.start;
    let rest = source.get(colon.index..).unwrap_or_default();
    let line = rest.split(['\r', '\n']).next().unwrap_or_default();
    if line.trim_start_matches([' ', '\t']).starts_with('#') {
        return empty;
    }
    if let Some(node) = Arc::get_mut(&mut empty.node) {
        node.start = next;
        node.end = next;
    }
    empty
}

/// The node's kind as PyYAML names it in a message.
fn node_id(value: &Value) -> &'static str {
    match value {
        Value::Seq(_) => "sequence",
        Value::Map(_) => "mapping",
        _ => "scalar",
    }
}

/// Python's `repr()` of a string, as PyYAML's messages quote keys.
pub(crate) fn python_str_repr(text: &str) -> String {
    let quote = if text.contains('\'') && !text.contains('"') {
        '"'
    } else {
        '\''
    };
    let mut out = String::with_capacity(text.len() + 2);
    out.push(quote);
    for character in text.chars() {
        match character {
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c == quote => {
                out.push('\\');
                out.push(c);
            }
            c if (c as u32) < 0x20 || c as u32 == 0x7f => {
                out.push_str(&format!("\\x{:02x}", c as u32));
            }
            c => out.push(c),
        }
    }
    out.push(quote);
    out
}

/// Python's `==` between two dictionary keys: `1`, `1.0` and `True` are one key.
fn python_key_eq(a: &Value, b: &Value) -> bool {
    fn number(value: &Value) -> Option<f64> {
        match value {
            Value::Bool(flag) => Some(f64::from(u8::from(*flag))),
            Value::Int(integer) => integer.to_f64(),
            Value::Float(float) => Some(*float),
            _ => None,
        }
    }
    match (a, b) {
        (Value::Null, Value::Null) => true,
        (Value::Str(x), Value::Str(y)) => x == y,
        (Value::Int(x), Value::Int(y)) => x == y,
        (Value::Bool(x), Value::Bool(y)) => x == y,
        (Value::Seq(_) | Value::Map(_), _) | (_, Value::Seq(_) | Value::Map(_)) => false,
        _ => match (number(a), number(b)) {
            (Some(x), Some(y)) => x == y,
            _ => false,
        },
    }
}

impl fmt::Display for Value {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.python_str())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn deep_nesting_neither_recurses_nor_overflows() {
        // The oracle reads 10 000 nested lists (and its C stack gives out
        // somewhere past that); dropping or composing must not recurse.
        let depth = 20_000;
        let text = format!("{}{}", "[".repeat(depth), "]".repeat(depth));
        let document = load(&text).unwrap();
        drop(document);
    }

    #[test]
    fn aliases_share_one_node() {
        let document = load("a: &x [1, 2]\nb: *x\n").unwrap();
        let root = document.root().unwrap();
        assert!(Arc::ptr_eq(root.get("a").unwrap(), root.get("b").unwrap()));
    }

    #[test]
    fn keys_compare_as_python_keys() {
        assert!(python_key_eq(
            &Value::Bool(true),
            &Value::Int(Integer::from_i64(1))
        ));
        assert!(python_key_eq(
            &Value::Float(1.0),
            &Value::Int(Integer::from_i64(1))
        ));
        assert!(!python_key_eq(
            &Value::Str("1".into()),
            &Value::Int(Integer::from_i64(1))
        ));
    }

    #[test]
    fn repr_quotes_as_python() {
        assert_eq!(python_str_repr("a"), "'a'");
        assert_eq!(python_str_repr("it's"), "\"it's\"");
        assert_eq!(python_str_repr("a\nb"), "'a\\nb'");
    }
}
