//! The data model of the Tide field catalog (`fields.json`, #1743).
//!
//! Shared by the crate (`lib.rs` builds its catalog from the models) and by its build script
//! (`#[path]`), which parses the bundled `fields.json` once and stores it pre-parsed: this file
//! depends on `serde` and `std` and on nothing else of the crate.

use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::sync::Arc;

/// One opentide schema node, keyed by `(schema id, YAML path)`: `rule::1.0`
/// and `rule::1.1` each have their own rows. A catalog from an older
/// `opentide generate schemas` keys rows by family (`rule`); such a row
/// applies to every revision of the family.
///
/// Generated by opentide (`python -m opentide.generation.lsp_catalog`) from
/// its models. Titles, types, required, enums, and consts come from JSON Schema.
/// `markdown` / `hidden` come from Pydantic `json_schema_extra` flags the schema
/// emitter drops. `capture` is a HighlightSpec presentation choice.
#[derive(Debug, Clone, Deserialize)]
#[expect(
    clippy::struct_excessive_bools,
    reason = "the generated catalog's columns: one flag per schema property"
)]
pub struct TideField {
    pub schema: String,
    pub path: String,
    pub name: String,
    #[serde(default)]
    pub title: String,
    #[serde(default)]
    pub description: String,
    #[serde(default, rename = "type")]
    pub type_name: String,
    #[serde(default)]
    pub required: bool,
    #[serde(default)]
    pub markdown: bool,
    #[serde(default)]
    pub hidden: bool,
    #[serde(default = "default_tide_capture")]
    pub capture: String,
    /// The values the field allows.
    #[serde(default, rename = "enum")]
    pub enum_values: Choices,
    #[serde(default)]
    pub enum_docs: Vec<String>,
    #[serde(default, rename = "ref")]
    pub ref_kind: Option<String>,
    #[serde(default, rename = "const")]
    pub const_value: Option<String>,
    #[serde(default)]
    pub array: bool,
    /// Pydantic string default (`status = "STAGING"`). Not a vocabulary.
    /// Omitted when the default is outside a non-empty schema enum.
    #[serde(default, rename = "default")]
    pub default_value: Option<String>,
    /// JSON Schema `minItems`, when the field is an array.
    #[serde(default)]
    pub min_items: Option<u32>,
    /// The templates ask for it, validation does not require it: a warning
    /// when it is missing, where a `required` field is an error.
    #[serde(default)]
    pub recommended: bool,
    /// An object (or the items of an array of objects) that forbids keys it
    /// does not define: JSON Schema `additionalProperties: false`.
    #[serde(default)]
    pub closed: bool,
    /// Keys this mapping also accepts, though no schema lists them: a legacy
    /// spelling opentide's validation rewrites, and the field it fills
    /// (`search` → `query`), or `None` when it is dropped.
    #[serde(default)]
    pub legacy: BTreeMap<String, Option<String>>,
}

/// The values an enum field allows: the list a catalog file gave it, or a place in the table of
/// lists the bundled catalog stores (#1743). Each list is shared by every revision of every schema
/// that has it, and is decoded when one is first read: a document that checks no enum field never
/// decodes them. Reads as a slice. Only the crate makes a place of the bundled table, so a
/// place is always one the table has.
#[derive(Debug, Clone)]
pub struct Choices(pub(crate) Repr);

/// What [`Choices`] holds.
#[derive(Debug, Clone)]
pub(crate) enum Repr {
    /// The field's own list.
    Own(Arc<[String]>),
    /// The place in the bundled table of lists.
    Bundled(u32),
}

impl Default for Choices {
    fn default() -> Self {
        Self(Repr::Own(Arc::from([])))
    }
}

impl<'de> Deserialize<'de> for Choices {
    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        Vec::<String>::deserialize(deserializer).map(|list| Self(Repr::Own(list.into())))
    }
}

/// One revision's document root, from `fields.json`'s `schemas` map.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct TideSchemaRoot {
    #[serde(default)]
    pub family: String,
    /// The root forbids keys the revision does not define.
    #[serde(default)]
    pub closed: bool,
    /// Legacy root keys, as on [`TideField::legacy`].
    #[serde(default)]
    pub legacy: BTreeMap<String, Option<String>>,
}

fn default_tide_capture() -> String {
    "tide.property".into()
}

/// What `fields.json` holds that the catalog reads.
#[derive(Debug, Deserialize)]
pub struct TideFieldsFile {
    pub opentide: String,
    #[serde(default)]
    pub schemas: BTreeMap<String, TideSchemaRoot>,
    pub fields: Vec<TideField>,
}

/// A [`TideField`] with each of its strings given as a place in [`StoredCatalog::strings`].
#[derive(Debug, Serialize, Deserialize)]
#[expect(
    clippy::struct_excessive_bools,
    reason = "the generated catalog's columns: one flag per schema property"
)]
pub struct StoredField {
    pub schema: u32,
    pub path: u32,
    pub name: u32,
    pub title: u32,
    pub description: u32,
    pub type_name: u32,
    pub required: bool,
    pub markdown: bool,
    pub hidden: bool,
    pub capture: u32,
    /// The place of the field's list of enum values in the table of lists, plus one; 0 for none.
    pub choices: u32,
    pub enum_docs: Vec<u32>,
    pub ref_kind: Option<u32>,
    pub const_value: Option<u32>,
    pub array: bool,
    pub default_value: Option<u32>,
    pub min_items: Option<u32>,
    pub recommended: bool,
    pub closed: bool,
    pub legacy: Vec<(u32, Option<u32>)>,
}

/// The bundled catalog as the build stores it (#1743): every string once, and the fields by place
/// in that table. `fields.json` repeated each of them for each field, which was a large part of its
/// 1.1 MB. The lists of enum values (the same list for each revision of each schema that has it)
/// are a blob of their own, decoded when one is first read.
#[derive(Debug, Serialize, Deserialize)]
pub struct StoredCatalog {
    pub opentide: String,
    pub schemas: BTreeMap<String, TideSchemaRoot>,
    pub strings: Vec<String>,
    pub fields: Vec<StoredField>,
}
