//! The data model of the SPL catalogs (#1743).
//!
//! Shared by the crate (`lib.rs` reads the models) and by its build script (`#[path]`), which
//! parses the catalog files once and stores them pre-parsed: this file depends on `serde` and
//! on nothing else of the crate.

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CommandRow {
    pub name: String,
    pub kind: String,
    pub docs: Option<String>,
    pub citation: Option<String>,
    /// The Splunk app that adds the command (`MLTK`); `None` for a Search
    /// Reference command that every search head has.
    #[serde(default)]
    pub app: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FunctionRow {
    pub name: String,
    pub kind: Option<String>,
    pub docs: Option<String>,
    #[serde(default)]
    pub signature: Option<String>,
    #[serde(default)]
    pub citation: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FieldRow {
    pub name: String,
    #[serde(default)]
    pub models: Vec<String>,
    pub kind: Option<String>,
    pub docs: Option<String>,
    pub citation: Option<String>,
}

/// One dataset of a data model (`data/catalogs/spl/datamodels.toml`, generated by
/// `scripts/engine/sync_cim_datamodels.py`).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DatamodelRow {
    /// `Model.Dataset`, the dataset's object name (`Endpoint.Processes`).
    pub name: String,
    /// The root dataset: tstats fields are `<prefix>.<field>`.
    pub prefix: String,
    pub model: Option<String>,
    /// Root to dataset (`All_Changes.Account_Management`); a field the
    /// dataset defines is `<lineage>.<field>`. The prefix when absent.
    #[serde(default)]
    pub lineage: Option<String>,
    pub docs: Option<String>,
    /// The fields this dataset defines; children inherit their parents'.
    #[serde(default)]
    pub fields: Vec<String>,
    /// Values CIM expects for a field.
    #[serde(default)]
    pub values: std::collections::BTreeMap<String, Vec<String>>,
    /// The field list is complete, so a near miss of one of its fields is a
    /// typo (`spl_unknown_datamodel_field`).
    #[serde(default)]
    pub complete: bool,
    pub citation: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MacroRow {
    pub name: String,
    pub signature: Option<String>,
    pub docs: Option<String>,
    pub citation: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CommandOption {
    pub command: String,
    pub name: String,
    #[serde(default)]
    pub values: Vec<String>,
    pub docs: Option<String>,
    pub citation: Option<String>,
}
