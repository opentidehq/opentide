#[derive(Debug, Clone)]
pub struct Catalog {
    pub commands: Vec<CommandRow>,
    pub functions: Vec<FunctionRow>,
    pub fields: Vec<FieldRow>,
    pub datamodels: Vec<DatamodelRow>,
    /// Data models known by name only, beyond the ones `datamodels` covers.
    pub extra_models: Vec<String>,
    pub macros: Vec<MacroRow>,
    pub options: Vec<CommandOption>,
}

impl Catalog {
    #[expect(
        clippy::expect_used,
        reason = "parses a catalog compiled in with include_str!: a bad catalog fails the tests, never a user's document"
    )]
    pub fn load() -> Self {
        let file: CommandsFile = toml::from_str(COMMANDS_TOML).expect("commands.toml");
        let fields: FieldsFile = toml::from_str(FIELDS_TOML).expect("fields.toml");
        let datamodels: DatamodelsFile = toml::from_str(DATAMODELS_TOML).expect("datamodels.toml");
        let macros: MacrosFile = toml::from_str(MACROS_TOML).expect("macros.toml");
        let options: OptionsFile = toml::from_str(OPTIONS_TOML).expect("command-options.toml");
        Self {
            commands: file.commands,
            functions: file.functions,
            fields: fields.fields,
            datamodels: datamodels.datamodels,
            extra_models: datamodels.models,
            macros: macros.macros,
            options: options.options,
        }
    }

    pub fn cached() -> &'static Self {
        static CATALOG: OnceLock<Catalog> = OnceLock::new();
        CATALOG.get_or_init(Self::load)
    }

    pub fn command(&self, name: &str) -> Option<&CommandRow> {
        self.commands
            .iter()
            .find(|c| c.name.eq_ignore_ascii_case(name))
    }

    pub fn function(&self, name: &str) -> Option<&FunctionRow> {
        self.functions
            .iter()
            .find(|f| f.name.eq_ignore_ascii_case(name))
    }

    /// Eval and aggregate rows can share a name (`sum`, `avg`, `min`, `max`).
    /// `aggregate` selects the stats/chart form; otherwise the eval form wins.
    pub fn function_in_context(&self, name: &str, aggregate: bool) -> Option<&FunctionRow> {
        let mut fallback = None;
        for f in &self.functions {
            if !f.name.eq_ignore_ascii_case(name) {
                continue;
            }
            let is_agg = f.kind.as_deref() == Some("aggregate");
            if fallback.is_none() {
                fallback = Some(f);
            }
            if aggregate == is_agg {
                return Some(f);
            }
        }
        fallback
    }

    pub fn options_for<'a>(&'a self, command: &str) -> Vec<&'a CommandOption> {
        self.options
            .iter()
            .filter(|o| o.command.eq_ignore_ascii_case(command))
            .collect()
    }

    /// The catalogued command `name` most likely means
    /// ([`opentide_core::suggest`]). A name one typo from a command (one
    /// edit, or swapped neighbours, which `spl_unknown_command` reports as an
    /// error) names the best of those commands, so an error that calls the
    /// name a typo always says of what (`tsast`, two swaps, is `stats`).
    pub fn suggest_command(&self, name: &str) -> Option<String> {
        let typos = self.command_typos(name);
        if typos.is_empty() {
            suggest::closest(name, self.commands.iter().map(|c| c.name.as_str()))
        } else {
            suggest::best(name, typos)
        }
        .map(str::to_string)
    }

    /// The catalogued commands `name` is one typo from ([`one_typo`]).
    fn command_typos(&self, name: &str) -> Vec<&str> {
        let lower = name.to_ascii_lowercase();
        self.commands
            .iter()
            .filter(|c| one_typo(&c.name.to_ascii_lowercase(), &lower))
            .map(|c| c.name.as_str())
            .collect()
    }

    /// Whether `name` is one typo from a catalogued command ([`one_typo`]):
    /// then `spl_unknown_command` is an error, not a warning an app may
    /// explain.
    fn is_command_typo(&self, name: &str) -> bool {
        !self.command_typos(name).is_empty()
    }

    pub fn field(&self, name: &str) -> Option<&FieldRow> {
        let bare = name.rsplit('.').next().unwrap_or(name);
        self.fields
            .iter()
            .find(|f| f.name == name || f.name == bare)
    }

    pub fn datamodel(&self, name: &str) -> Option<&DatamodelRow> {
        self.datamodels
            .iter()
            .find(|d| d.name.eq_ignore_ascii_case(name) || d.prefix.eq_ignore_ascii_case(name))
    }

    pub fn macro_named(&self, name: &str) -> Option<&MacroRow> {
        let bare = name.trim_matches('`').split('(').next().unwrap_or(name);
        self.macros
            .iter()
            .find(|m| m.name == bare || m.name == name)
    }

    /// The first data model dataset the search reads (`tstats ... from
    /// datamodel=Endpoint.Processes`, `| datamodel Endpoint Processes`,
    /// `| from datamodel:Endpoint.Processes`).
    pub fn active_datamodel(&self, source: &str) -> Option<&'static DatamodelRow> {
        cim::first_dataset(source)
    }
}

/// Whether `a` and `b` are one typo apart: one insertion, deletion or
/// substitution, or swapped neighbours, once or twice (`stast` and `tsast`
/// are `stats`). Equal strings are not.
fn one_typo(a: &str, b: &str) -> bool {
    match strsim::osa_distance(a, b) {
        1 => true,
        2 => only_swaps(a, b),
        _ => false,
    }
}

/// Whether `b` is `a` with disjoint pairs of neighbours swapped and nothing
/// else changed.
fn only_swaps(a: &str, b: &str) -> bool {
    let a: Vec<char> = a.chars().collect();
    let b: Vec<char> = b.chars().collect();
    if a.len() != b.len() {
        return false;
    }
    let mut i = 0;
    while i < a.len() {
        if a[i] == b[i] {
            i += 1;
        } else if i + 1 < a.len() && a[i] == b[i + 1] && a[i + 1] == b[i] {
            i += 2;
        } else {
            return false;
        }
    }
    true
}

pub struct AnalyzeResult {
    pub diagnostics: Vec<Diagnostic>,
    pub tokens: Vec<HighlightToken>,
}

#[expect(
    clippy::expect_used,
    reason = "loads the HighlightSpec compiled in (highlights/spec.toml): a bad spec fails the tests, never a user's document"
)]
pub fn analyze(source: &str) -> AnalyzeResult {
    let catalog = Catalog::cached();
    let spec = HighlightSpec::load().expect("spec");
    let mut diagnostics = Vec::new();
    let Some(tree) = ts_parse(LanguageId::Spl, source) else {
        return AnalyzeResult {
            diagnostics: vec![Diagnostic::error(
                codes::SPL_PARSE_ERROR,
                "failed to initialize SPL parser",
                Range::point(0, 0),
            )],
            tokens: Vec::new(),
        };
    };
    parse_errors::collect(tree.root_node(), source, &mut diagnostics);
    collect_unknown_commands(tree.root_node(), source, catalog, &mut diagnostics);
    perf::collect(source, catalog, &mut diagnostics);
    search_operators::collect(source, catalog, &mut diagnostics);
    parens::refine(source, &mut diagnostics);
    stages::collect(tree.root_node(), source, catalog, &mut diagnostics);
    rejects::collect(tree.root_node(), source, &mut diagnostics);
    cim::collect(source, &mut diagnostics);
    declared::collect(source, catalog, &mut diagnostics);
    let tokens = highlight_tree(&spec, source, tree.root_node()).unwrap_or_default();
    AnalyzeResult {
        diagnostics,
        tokens,
    }
}

fn node_range(source: &str, node: Node) -> Range {
    span_to_range(
        source,
        ByteSpan::new(
            node.start_byte(),
            node.end_byte().max(node.start_byte() + 1),
        ),
    )
}

/// `spl_unknown_command` for a name in command position only: after a `|`,
/// at the start of a subsearch, or first in the query. A word that error
/// recovery strands mid-command is not a command, and nothing inside an
/// `ERROR` region is reported. An app on the search head can add commands the
/// catalog cannot know (MLTK, DECRYPT2, MISP42), so an unknown name is a
/// warning; one edit from a known command it is almost certainly a typo
/// (`statz`), which Splunk rejects, so it stays an error.
fn collect_unknown_commands(
    root: Node,
    source: &str,
    catalog: &Catalog,
    out: &mut Vec<Diagnostic>,
) {
    walk_with_ancestors(root, |node, ancestors| {
        if node.kind() != "unknown_command"
            || ancestors.iter().any(|a| a.is_error())
            || !in_command_position(node)
        {
            return;
        }
        let name = node
            .child_by_field_name("name")
            .and_then(|n| n.utf8_text(source.as_bytes()).ok())
            .unwrap_or("");
        if catalog.command(name).is_none() {
            out.push(unknown_command(name, node_range(source, node), catalog));
        }
    });
}

fn in_command_position(node: Node) -> bool {
    match previous_token(node) {
        None => true,
        Some(token) => matches!(token.kind(), "|" | "[") && !token.is_missing(),
    }
}

/// The token before `node` in document order, skipping comments and the
/// zero-width tokens error recovery inserts.
fn previous_token(node: Node) -> Option<Node> {
    let mut at = node;
    // Each step moves strictly backwards in the tree, so this ends; the bound
    // only guards against a malformed recovered tree.
    for _ in 0..MAX_TOKEN_STEPS {
        let sibling = loop {
            if let Some(s) = opentide_syntax::prev_sibling(at) {
                break s;
            }
            at = at.parent()?;
        };
        let mut leaf = sibling;
        while leaf.child_count() > 0 {
            leaf = leaf.child(leaf.child_count() - 1)?;
        }
        if leaf.is_extra() || leaf.is_missing() || leaf.start_byte() == leaf.end_byte() {
            at = leaf;
            continue;
        }
        return Some(leaf);
    }
    None
}

/// More steps than any query has tokens.
const MAX_TOKEN_STEPS: usize = 1 << 20;

fn unknown_command(name: &str, range: Range, catalog: &Catalog) -> Diagnostic {
    let message = format!(
        "'{name}' is not a command opentide knows; if an app on the search head provides it, declare it"
    );
    let mut d = if catalog.is_command_typo(name) {
        Diagnostic::error(codes::SPL_UNKNOWN_COMMAND, message, range)
    } else {
        Diagnostic::warning(codes::SPL_UNKNOWN_COMMAND, message, range)
    };
    if let Some(suggestion) = catalog.suggest_command(name) {
        d = d.with_suggestion(suggestion);
    }
    d
}

#[expect(
    clippy::manual_assert,
    reason = "a broken highlights.scm panics in debug builds (the tests) and falls back to the tree walk in release builds"
)]
fn highlight_tree(
    spec: &HighlightSpec,
    source: &str,
    root: Node,
) -> Result<Vec<HighlightToken>, opentide_highlight::HighlightError> {
    let catalog = Catalog::cached();
    match opentide_syntax::query_captures(
        LanguageId::Spl,
        source,
        opentide_highlight::SPL_HIGHLIGHTS_SCM,
    ) {
        Ok(mut owned) => {
            for (span, capture) in &mut owned {
                let end = span.end.min(source.len());
                if span.start >= end {
                    continue;
                }
                let text = &source[span.start..end];
                if catalog.function(text).is_some()
                    && (*capture == "variable" || *capture == "function")
                {
                    *capture = "function.builtin".into();
                } else if (matches!(
                    text,
                    "by" | "AS"
                        | "as"
                        | "from"
                        | "datamodel"
                        | "summariesonly"
                        | "where"
                        | "prestats"
                        | "allow_old_summaries"
                        | "fillnull_value"
                ) && *capture == "variable")
                    || (catalog.command(text).is_some()
                        && (*capture == "variable" || *capture == "error"))
                {
                    *capture = "keyword".into();
                } else if looks_like_macro(text)
                    || (*capture == "comment" && looks_like_macro(text))
                {
                    *capture = "macro".into();
                } else if catalog.datamodel(text).is_some() && *capture == "variable" {
                    *capture = "type".into();
                } else if catalog.field(text).is_some() && *capture == "variable" {
                    *capture = "property".into();
                }
            }
            let refs: Vec<(ByteSpan, &str)> = owned
                .iter()
                .map(|(span, cap)| (*span, cap.as_str()))
                .collect();
            tokens_from_spans(spec, source, &refs)
        }
        Err(err) => {
            if cfg!(debug_assertions) {
                panic!("SPL highlights.scm query failed: {err}");
            }
            let mut spans = Vec::new();
            collect_highlights(root, source, &mut spans);
            tokens_from_spans(spec, source, &spans)
        }
    }
}

#[expect(
    clippy::used_underscore_binding,
    reason = "`_source` only passes through the recursion (clippy::only_used_in_recursion)"
)]
fn collect_highlights(node: Node, _source: &str, out: &mut Vec<(ByteSpan, &'static str)>) {
    let kind = node.kind();
    let capture = match kind {
        "comment" => Some("comment"),
        "string" => Some("string"),
        "number" => Some("number"),
        "boolean" => Some("boolean"),
        "|" => Some("operator.pipe"),
        "catalog_command_name" => Some("keyword"),
        "macro" => Some("macro"),
        "search"
        | "where"
        | "eval"
        | "stats"
        | "rex"
        | "table"
        | "rename"
        | "fields"
        | "dedup"
        | "sort"
        | "head"
        | "tail"
        | "join"
        | "lookup"
        | "makemv"
        | "mvexpand"
        | "tstats"
        | "eventstats"
        | "streamstats"
        | "sistats"
        | "chart"
        | "timechart"
        | "sichart"
        | "sitimechart"
        | "geostats"
        | "fillnull"
        | "foreach"
        | "spath"
        | "tojson"
        | "inputlookup"
        | "outputlookup"
        | "as"
        | "by"
        | "over"
        | "output"
        | "outputnew"
        | "desc"
        | "in"
        | "notin"
        | "from"
        | "datamodel"
        | "summariesonly"
        | "prestats"
        | "allow_old_summaries"
        | "fillnull_value"
        | "TERM"
        | "CASE"
        | "PREFIX"
        | "IN" => Some("keyword"),
        "glob" | "search_word" => Some("variable"),
        "term_text" => Some("string"),
        "search_boolean" => Some("operator"),
        "identifier" => {
            if node.parent().map(|p| p.kind()) == Some("function_call") {
                Some("function")
            } else if node.parent().map(|p| p.kind()) == Some("field_value")
                && node
                    .parent()
                    .and_then(|p| p.child_by_field_name("field"))
                    .map(|n| n.id())
                    == Some(node.id())
            {
                Some("property")
            } else if node.parent().map(|p| p.kind()) == Some("unknown_command") {
                Some("error")
            } else {
                Some("variable")
            }
        }
        "AND" | "OR" | "NOT" | "and" | "or" | "not" | "=" | "==" | "!=" => Some("operator"),
        "(" | ")" | "[" | "]" => Some("punctuation.bracket"),
        "," => Some("punctuation.delimiter"),
        _ => None,
    };
    if let Some(capture) = capture
        && (node.child_count() == 0 || matches!(kind, "string" | "comment" | "number" | "macro"))
    {
        out.push((ByteSpan::new(node.start_byte(), node.end_byte()), capture));
    }
    let mut cursor = node.walk();
    for child in node.children(&mut cursor) {
        collect_highlights(child, _source, out);
    }
}

fn looks_like_macro(text: &str) -> bool {
    let t = text.trim();
    t.starts_with('`') && t.ends_with('`') && !t.starts_with("```") && t.len() >= 3
}

fn complete_item(
    label: impl Into<String>,
    kind: &str,
    detail: Option<String>,
    docs: Option<String>,
) -> CompletionItem {
    let mut item = CompletionItem::new(label, kind);
    if let Some(d) = detail {
        item = item.with_detail(d);
    }
    if let Some(d) = docs {
        item = item.with_docs(d);
    }
    item
}

fn last_command(before: &str) -> Option<String> {
    let chunk = before
        .rsplit('|')
        .next()?
        .trim_start()
        .trim_start_matches('|')
        .trim_start();
    let op = chunk
        .split(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
        .next()?
        .to_ascii_lowercase();
    if op.is_empty() { None } else { Some(op) }
}

const AGGREGATE_COMMANDS: &[&str] = &[
    "stats",
    "eventstats",
    "streamstats",
    "tstats",
    "chart",
    "timechart",
    "mstats",
    "sistats",
    "sichart",
    "sitimechart",
];

fn aggregate_command(cmd: &str) -> bool {
    AGGREGATE_COMMANDS.contains(&cmd)
}

/// `bucket` is the Search Reference alias of `bin` and takes the same arguments.
fn argument_command(cmd: &str) -> &str {
    match cmd {
        "bucket" => "bin",
        _ => cmd,
    }
}

fn eval_command(cmd: &str) -> bool {
    matches!(cmd, "eval" | "where" | "fieldformat")
}

fn field_command(cmd: &str) -> bool {
    matches!(
        cmd,
        "tstats" | "stats" | "where" | "table" | "fields" | "eval"
    )
}

fn option_is_clause(opt: &CommandOption) -> bool {
    let name = opt.name.to_ascii_lowercase();
    matches!(
        name.as_str(),
        "from"
            | "where"
            | "by"
            | "over"
            | "output"
            | "outputnew"
            | "search"
            | "flat"
            | "acceleration_search"
            | "search_string"
            | "flat_string"
            | "acceleration_search_string"
            | "lookup"
            | "savedsearch"
            | "assignment"
    ) || (opt.command.eq_ignore_ascii_case("from") && name == "datamodel")
}

fn option_fragment(opt: &CommandOption) -> String {
    if option_is_clause(opt) {
        format!("[{}]", opt.name)
    } else {
        format!("[{}=]", opt.name)
    }
}

fn assigned_option<'a>(before: &str, catalog: &'a Catalog, cmd: &str) -> Option<&'a CommandOption> {
    let trimmed = before.trim_end();
    if !trimmed.ends_with('=') {
        return None;
    }
    let left = trimmed[..trimmed.len() - 1].trim_end();
    let name = left
        .rsplit(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
        .next()
        .unwrap_or("");
    if name.is_empty() {
        return None;
    }
    catalog
        .options_for(argument_command(cmd))
        .into_iter()
        .find(|o| o.name.eq_ignore_ascii_case(name) && !o.values.is_empty())
}

pub fn completions(source: &str, offset: usize) -> Vec<CompletionItem> {
    // An offset inside a character (a decoded escape) completes nothing.
    let Some(before) = source.get(..offset.min(source.len())) else {
        return Vec::new();
    };
    let catalog = Catalog::cached();
    let trimmed = before.trim_end();
    if trimmed.ends_with('`') && !trimmed.ends_with("```") {
        return catalog
            .macros
            .iter()
            .map(|m| {
                complete_item(
                    format!("`{}`", m.name.trim_matches('`')),
                    "macro",
                    m.docs.clone(),
                    m.docs.clone(),
                )
            })
            .collect();
    }
    if trimmed.to_ascii_lowercase().ends_with("datamodel=") {
        return catalog
            .datamodels
            .iter()
            .map(|d| complete_item(d.name.clone(), "type", d.docs.clone(), d.docs.clone()))
            .collect();
    }
    if let Some(values) = cim::expected_values(source, before) {
        return values
            .iter()
            .map(|v| complete_item(v.clone(), "enum", Some("CIM expected value".into()), None))
            .collect();
    }
    if before.trim_end().ends_with('|') || before.ends_with("| ") {
        return catalog
            .commands
            .iter()
            .map(|c| complete_item(c.name.clone(), "command", c.docs.clone(), c.docs.clone()))
            .collect();
    }
    if let Some(cmd) = last_command(before) {
        if let Some(opt) = assigned_option(before, catalog, &cmd) {
            return opt
                .values
                .iter()
                .map(|v| {
                    complete_item(
                        v.clone(),
                        "keyword",
                        Some(format!("{cmd} {}=", opt.name)),
                        opt.docs.clone(),
                    )
                })
                .collect();
        }
        let opts = catalog.options_for(argument_command(&cmd));
        let wants_fields = field_command(&cmd);
        let wants_agg = aggregate_command(&cmd);
        let wants_eval = eval_command(&cmd);
        if !opts.is_empty() || wants_fields || wants_agg || wants_eval {
            let mut items = Vec::new();
            let mut seen = std::collections::BTreeSet::new();
            for opt in &opts {
                if seen.insert(opt.name.to_ascii_lowercase()) {
                    items.push(complete_item(
                        opt.name.clone(),
                        "keyword",
                        opt.docs.clone(),
                        opt.citation.clone(),
                    ));
                }
            }
            if wants_agg {
                for f in catalog
                    .functions
                    .iter()
                    .filter(|f| f.kind.as_deref() == Some("aggregate"))
                {
                    if seen.insert(f.name.to_ascii_lowercase()) {
                        items.push(complete_item(
                            f.name.clone(),
                            "function",
                            f.signature.clone().or(f.docs.clone()),
                            f.docs.clone(),
                        ));
                    }
                }
            } else if wants_eval {
                for f in catalog
                    .functions
                    .iter()
                    .filter(|f| f.kind.as_deref() != Some("aggregate"))
                {
                    if seen.insert(f.name.to_ascii_lowercase()) {
                        items.push(complete_item(
                            f.name.clone(),
                            "function",
                            f.signature.clone().or(f.docs.clone()),
                            f.docs.clone(),
                        ));
                    }
                }
            }
            if wants_fields {
                for (dataset, column) in declared::declared_fields(source, catalog) {
                    if seen.insert(column.name.to_ascii_lowercase()) {
                        let detail = format!(
                            "{dataset} ({})",
                            column.type_name.as_deref().unwrap_or("field")
                        );
                        items.push(complete_item(
                            column.name,
                            "column",
                            Some(detail),
                            column.description,
                        ));
                    }
                }
                if let Some(dm) = catalog.active_datamodel(source) {
                    for (prefixed, f) in cim::visible_fields(dm) {
                        if seen.insert(prefixed.to_ascii_lowercase()) {
                            items.push(complete_item(
                                prefixed,
                                "column",
                                Some(format!("{} field", dm.name)),
                                catalog.field(f).and_then(|row| row.docs.clone()),
                            ));
                        }
                        if seen.insert(f.to_ascii_lowercase()) {
                            items.push(complete_item(
                                f,
                                "column",
                                Some(format!("{} field", dm.name)),
                                catalog.field(f).and_then(|row| row.docs.clone()),
                            ));
                        }
                    }
                }
                for field in &catalog.fields {
                    if seen.insert(field.name.to_ascii_lowercase()) {
                        items.push(complete_item(
                            field.name.clone(),
                            "column",
                            Some(field.kind.clone().unwrap_or_else(|| "field".into())),
                            field.docs.clone(),
                        ));
                    }
                }
            }
            if cmd == "tstats" {
                for m in &catalog.macros {
                    let label = format!("`{}`", m.name.trim_matches('`'));
                    if seen.insert(label.to_ascii_lowercase()) {
                        items.push(complete_item(
                            label,
                            "macro",
                            m.docs.clone(),
                            m.docs.clone(),
                        ));
                    }
                }
            }
            if !items.is_empty() {
                return items;
            }
        }
    }
    let mut seen = std::collections::BTreeSet::new();
    catalog
        .functions
        .iter()
        .filter(|f| seen.insert(f.name.to_ascii_lowercase()))
        .map(|f| {
            complete_item(
                f.name.clone(),
                "function",
                f.signature.clone().or(f.docs.clone()),
                f.docs.clone(),
            )
        })
        .collect()
}

fn spl_word_at(source: &str, offset: usize) -> Option<String> {
    let bytes = source.as_bytes();
    if bytes.is_empty() {
        return None;
    }
    let mut i = offset.min(bytes.len().saturating_sub(1));
    while i > 0 && (bytes[i].is_ascii_alphanumeric() || matches!(bytes[i], b'_' | b'.' | b'`')) {
        i -= 1;
    }
    if !(bytes[i].is_ascii_alphanumeric() || matches!(bytes[i], b'_' | b'`')) {
        i += 1;
    }
    let mut j = offset.min(bytes.len());
    while j < bytes.len()
        && (bytes[j].is_ascii_alphanumeric() || matches!(bytes[j], b'_' | b'.' | b'`'))
    {
        j += 1;
    }
    if i >= j {
        None
    } else {
        Some(source[i..j].to_string())
    }
}

/// Hover at byte `offset` of `source` (an LSP host converts the editor's
/// UTF-16 position once, with `opentide_core::position_to_offset`).
pub fn hover(source: &str, offset: usize) -> Option<String> {
    let offset = offset.min(source.len());
    // An offset inside a character (a decoded escape) has nothing to show.
    if !source.is_char_boundary(offset) {
        return None;
    }
    let catalog = Catalog::cached();
    let word = spl_word_at(source, offset)?;
    let macro_name = word.trim_matches('`');
    if let Some(m) = catalog.macro_named(macro_name) {
        let mut md = format!(
            "**`{}`** (search macro)\n\n{}",
            m.name,
            m.docs.clone().unwrap_or_default()
        );
        if let Some(s) = &m.signature {
            md.push_str(&format!("\n\n`{s}`"));
        }
        return Some(md);
    }
    if let Some(cmd) = last_command(&source[..offset])
        && let Some(opt) = catalog
            .options_for(argument_command(&cmd))
            .into_iter()
            .find(|o| o.name.eq_ignore_ascii_case(&word))
    {
        return Some(option_markdown(opt));
    }
    if let Some(c) = catalog.command(&word) {
        let source_label = c.app.as_deref().unwrap_or("searchbnf");
        let citation = c
            .citation
            .as_deref()
            .map(|c| format!("\n\n[{source_label}]({c})"))
            .unwrap_or_default();
        let kind = match &c.app {
            Some(app) => format!("{}, {app} app", c.kind),
            None => c.kind.clone(),
        };
        return Some(format!(
            "**{}** ({kind})\n\n{}{citation}",
            c.name,
            c.docs.clone().unwrap_or_default()
        ));
    }
    let aggregate = last_command(&source[..offset]).is_some_and(|cmd| aggregate_command(&cmd));
    if let Some(f) = catalog.function_in_context(&word, aggregate) {
        return Some(function_markdown(f));
    }
    if let Some(d) = catalog.datamodel(&word) {
        return Some(format!(
            "**{}** CIM data model (prefix `{}`)\n\n{}",
            d.name,
            d.prefix,
            d.docs.clone().unwrap_or_default()
        ));
    }
    if let Some((dataset, column)) = declared::declared_fields(source, catalog)
        .into_iter()
        .find(|(_, c)| c.name == word)
    {
        let mut md = format!(
            "**{}** field (`{}`), declared in visibility.toml on `{dataset}`",
            column.name,
            column.type_name.as_deref().unwrap_or("field")
        );
        if let Some(description) = &column.description {
            md.push_str(&format!("\n\n{description}"));
        }
        return Some(md);
    }
    if let Some(field) = catalog.field(&word) {
        let models = field.models.join(", ");
        let mut md = format!(
            "**{}** field ({})\n\n{}",
            field.name,
            field.kind.as_deref().unwrap_or("cim"),
            field.docs.clone().unwrap_or_default()
        );
        if !models.is_empty() {
            md.push_str(&format!("\n\nModels: {models}"));
        }
        return Some(md);
    }
    None
}

fn function_markdown(f: &FunctionRow) -> String {
    let kind = f.kind.clone().unwrap_or_else(|| "function".into());
    let mut md = format!(
        "**{}** ({})\n\n{}",
        f.name,
        kind,
        f.docs.clone().unwrap_or_default()
    );
    if let Some(s) = &f.signature {
        md.push_str(&format!("\n\n`{s}`"));
    }
    if let Some(c) = &f.citation {
        md.push_str(&format!("\n\n[Search Reference]({c})"));
    }
    md
}

fn option_markdown(opt: &CommandOption) -> String {
    let mut md = format!(
        "**{}** (`{}` argument)\n\n{}",
        opt.name,
        opt.command,
        opt.docs.clone().unwrap_or_default()
    );
    if !opt.values.is_empty() {
        md.push_str(&format!("\n\nValues: {}", opt.values.join(", ")));
    }
    if let Some(c) = &opt.citation {
        md.push_str(&format!("\n\n[Search Reference]({c})"));
    }
    md
}

pub fn signature_help(source: &str, offset: usize) -> Option<SignatureHelp> {
    // An offset inside a character (a decoded escape) has nothing to show.
    let before = source.get(..offset.min(source.len()))?;
    let catalog = Catalog::cached();
    if let Some((name, active)) = innermost_call(before) {
        let cmd = last_command(before);
        let same_as_command = cmd.as_ref().is_some_and(|c| c.eq_ignore_ascii_case(&name));
        if !same_as_command {
            let aggregate = cmd.as_ref().is_some_and(|c| aggregate_command(c));
            if let Some(f) = catalog.function_in_context(&name, aggregate)
                && let Some(help) = function_signature(f, active)
            {
                return Some(help);
            }
        }
        if let Some(m) = catalog.macro_named(&name) {
            let label = m
                .signature
                .clone()
                .unwrap_or_else(|| format!("`{}`", m.name));
            return Some(signature_from_label(label, m.docs.clone(), active));
        }
    }
    let cmd = last_command(before)?;
    command_signature(catalog, &cmd, before)
}

fn function_signature(f: &FunctionRow, active: u32) -> Option<SignatureHelp> {
    let label = f.signature.clone()?;
    if !label.contains('(') {
        return None;
    }
    Some(signature_from_label(label, f.docs.clone(), active))
}

#[expect(
    clippy::cast_possible_truncation,
    reason = "a signature has a handful of parameters, far below u32::MAX"
)]
fn signature_from_label(
    label: String,
    documentation: Option<String>,
    active: u32,
) -> SignatureHelp {
    let parameters = parameters_from_signature(&label);
    let active = if parameters.is_empty() {
        0
    } else {
        active.min(parameters.len().saturating_sub(1) as u32)
    };
    SignatureHelp {
        signatures: vec![SignatureInformation {
            label,
            documentation,
            parameters,
        }],
        active_signature: 0,
        active_parameter: active,
    }
}

fn command_signature(catalog: &Catalog, cmd: &str, before: &str) -> Option<SignatureHelp> {
    let opts = catalog.options_for(argument_command(cmd));
    if opts.is_empty() {
        return None;
    }
    let label = format!(
        "{cmd} {}",
        opts.iter()
            .map(|opt| option_fragment(opt))
            .collect::<Vec<_>>()
            .join(" ")
    );
    let parameters = opts
        .iter()
        .map(|opt| ParameterInformation {
            label: opt.name.clone(),
            documentation: opt.docs.clone(),
        })
        .collect();
    let row = catalog.command(cmd);
    let mut documentation = row.and_then(|c| c.docs.clone());
    if let Some(citation) = row.and_then(|c| c.citation.clone()) {
        let line = format!("[Search Reference]({citation})");
        documentation = Some(match documentation {
            Some(docs) if !docs.is_empty() => format!("{docs}\n\n{line}"),
            _ => line,
        });
    }
    Some(SignatureHelp {
        signatures: vec![SignatureInformation {
            label,
            documentation,
            parameters,
        }],
        active_signature: 0,
        active_parameter: active_option(before, &opts),
    })
}

#[expect(
    clippy::cast_possible_truncation,
    reason = "an index into one command's options, a handful"
)]
fn active_option(before: &str, opts: &[&CommandOption]) -> u32 {
    let lower = before.to_ascii_lowercase();
    let mut best: Option<(usize, u32)> = None;
    for (i, opt) in opts.iter().enumerate() {
        let needle = opt.name.to_ascii_lowercase();
        if let Some(pos) = rfind_word(&lower, &needle)
            && best.map(|(at, _)| pos >= at).unwrap_or(true)
        {
            best = Some((pos, i as u32));
        }
    }
    best.map(|(_, index)| index).unwrap_or(0)
}

fn rfind_word(haystack: &str, needle: &str) -> Option<usize> {
    let bytes = haystack.as_bytes();
    let needle = needle.as_bytes();
    if needle.is_empty() || needle.len() > bytes.len() {
        return None;
    }
    let mut i = bytes.len() - needle.len();
    loop {
        if &bytes[i..i + needle.len()] == needle {
            let before_ok = i == 0 || !bytes[i - 1].is_ascii_alphanumeric();
            let after = i + needle.len();
            let after_ok = after == bytes.len() || !bytes[after].is_ascii_alphanumeric();
            if before_ok && after_ok {
                return Some(i);
            }
        }
        if i == 0 {
            break;
        }
        i -= 1;
    }
    None
}

fn innermost_call(before: &str) -> Option<(String, u32)> {
    let bytes = before.as_bytes();
    let mut depth = 0i32;
    let mut open = None;
    for (i, b) in bytes.iter().enumerate().rev() {
        match b {
            b')' => depth += 1,
            b'(' => {
                if depth == 0 {
                    open = Some(i);
                    break;
                }
                depth -= 1;
            }
            _ => {}
        }
    }
    let open = open?;
    let mut i = open;
    while i > 0 {
        let c = bytes[i - 1];
        if c.is_ascii_alphanumeric() || c == b'_' || c == b'`' {
            i -= 1;
        } else {
            break;
        }
    }
    let name = before[i..open].trim_matches('`').to_string();
    if name.is_empty() {
        return None;
    }
    let inside = &before[open + 1..];
    let mut commas = 0u32;
    let mut nested = 0i32;
    for b in inside.bytes() {
        match b {
            b'(' => nested += 1,
            b')' => nested -= 1,
            b',' if nested == 0 => commas += 1,
            _ => {}
        }
    }
    Some((name, commas))
}

fn parameters_from_signature(sig: &str) -> Vec<ParameterInformation> {
    let Some(open) = sig.find('(') else {
        return Vec::new();
    };
    let start = open + 1;
    let end = sig.rfind(')').unwrap_or(sig.len());
    if start >= end {
        return Vec::new();
    }
    let mut params = Vec::new();
    let mut depth = 0i32;
    let mut cur = String::new();
    for ch in sig[start..end].chars() {
        match ch {
            '(' => {
                depth += 1;
                cur.push(ch);
            }
            ')' => {
                depth -= 1;
                cur.push(ch);
            }
            ',' if depth == 0 => {
                push_param(&mut params, &cur);
                cur.clear();
            }
            _ => cur.push(ch),
        }
    }
    push_param(&mut params, &cur);
    params
}

fn push_param(out: &mut Vec<ParameterInformation>, raw: &str) {
    let label = raw.trim();
    if label.is_empty() {
        return;
    }
    out.push(ParameterInformation {
        label: label.to_string(),
        documentation: None,
    });
}
