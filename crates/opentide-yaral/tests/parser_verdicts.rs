#[test]
fn the_verdicts_hold() {
    let mut different = Vec::new();
    for &(text, broken) in TEXTS {
        if (parse_error_count(text) > 0) != broken {
            different.push(format!(
                "{text:?}: expected {}",
                if broken { "an error" } else { "no error" }
            ));
        }
        assert!(parse_is_lossless(text), "{text:?} is not lossless");
    }
    assert!(different.is_empty(), "{}", different.join("\n"));
}
