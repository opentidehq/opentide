//! The command line's behaviour, owned by Rust (#1139): every case of
//! `tests/golden/cases.toml` run in-process ([`opentide_cli::run`]) on a fresh
//! copy of its fixture, and what it did (exit code, stdout, stderr, every
//! file it wrote, changed or deleted) held to an insta snapshot of the Rust
//! CLI's own output, under `tests/cli_snapshots/<command>/`.
//!
//! Only what differs between two runs of the same case is normalised (the
//! goldens' [`Normaliser`]: the case's temporary paths, the clock, durations,
//! crash-log names, catalog fingerprints, and minted UUIDs where the case
//! opts in). JSON is snapshotted as its parsed value, pretty-printed, so its
//! fields are checked and its spacing is not. A change in what a command
//! prints or writes is a snapshot diff, reviewed with `cargo insta review`
//! (tests/golden/README.md, "Snapshots").

#![allow(dead_code, reason = "each test binary uses part of the helpers")]

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::sync::{Arc, Mutex};

use opentide_cli::env::Env;
use opentide_cli::logging::Sink;
use opentide_cli::{Host, run};
use opentide_compare::normalise::{Normaliser, Rule, Volatile};

use crate::replay::{self, Buffer};

/// The version every case's host reports: fixed, so a release does not
/// change a snapshot (`--version`, the catalogue, digests over it).
pub const VERSION: &str = "0.28.1";

/// Above this size a written file is snapshotted as its size and digest,
/// not its text (the editor schemas `generate schemas` writes, megabytes
/// each): a change still fails, and the diff names the file.
const INLINE_LIMIT: usize = 64 * 1024;

/// Fixtures generated by `cargo xtask corpus` (UC-0.6), which a test of
/// this crate cannot build: their cases run by hand only, through
/// `cargo xtask golden`.
const GENERATED: &[&str] = &["fault", "fault-lint", "heavy-small"];

/// One expanded case of `tests/golden/cases.toml`.
#[derive(Clone, Debug)]
pub struct Case {
    /// `<command dir>/<mode>/<fixture>/<variant>`.
    pub id: String,
    /// The command's directory name: `validate.query`, `_root` for the root.
    pub command_dir: String,
    pub mode: String,
    pub fixture: String,
    pub variant: String,
    /// The arguments after `opentide`.
    pub args: Vec<String>,
    pub env: BTreeMap<String, String>,
    pub cwd: Option<String>,
    pub cassette: Option<String>,
    pub normalise: Vec<Rule>,
}

/// Every case of `tests/golden/cases.toml` this harness runs, in the
/// manifest's order: each `[[case]]` over its modes and fixtures, a fixture
/// lacking a `{variable}` the arguments use left out, as `cargo xtask golden
/// record` expands it (`xtask/src/golden/case.rs`). Cases on a generated
/// fixture, and cases that feed standard input (`serve`'s session, which
/// `tests/serve.rs` drives), are left out.
pub fn cases() -> Vec<Case> {
    let text = std::fs::read_to_string(replay::repo().join("tests/golden/cases.toml")).unwrap();
    let spec: Spec = toml::from_str(&text).unwrap();
    let mut out = Vec::new();
    for case in spec.case.iter().filter(|case| case.input.is_empty()) {
        let command_dir = if case.command.is_empty() {
            "_root".to_owned()
        } else {
            case.command.replace(' ', ".")
        };
        let modes = case.modes.as_ref().unwrap_or(&spec.defaults.modes);
        let fixtures = case.fixtures.as_ref().unwrap_or(&spec.defaults.fixtures);
        for mode in modes {
            for fixture in fixtures
                .iter()
                .filter(|name| !GENERATED.contains(&name.as_str()))
            {
                let Some(mut args) = substitute(&case.args, &spec.fixtures[fixture].vars) else {
                    continue;
                };
                if mode == "json" && !args.iter().any(|arg| arg == "--json") {
                    args.insert(0, "--json".to_owned());
                }
                let mut env = base_env(mode);
                if case.cassette.is_some() {
                    for value in env.values_mut().filter(|value| *value == REFUSING_PROXY) {
                        "<CASSETTE_PROXY>".clone_into(value);
                    }
                    for name in ["SSL_CERT_FILE", "REQUESTS_CA_BUNDLE", "CURL_CA_BUNDLE"] {
                        env.insert(name.to_owned(), "<TMP>/cassette-ca.pem".to_owned());
                    }
                }
                env.extend(case.env.clone());
                out.push(Case {
                    id: format!("{command_dir}/{mode}/{fixture}/{}", case.variant),
                    command_dir: command_dir.clone(),
                    mode: mode.clone(),
                    fixture: fixture.clone(),
                    variant: case.variant.clone(),
                    args,
                    env,
                    cwd: case.cwd.clone(),
                    cassette: case.cassette.clone(),
                    normalise: case.normalise.clone(),
                });
            }
        }
    }
    out
}

/// `tests/golden/cases.toml`, the parts this harness reads
/// (`xtask/src/golden/case.rs` `Spec` is the whole).
#[derive(serde::Deserialize)]
struct Spec {
    defaults: Defaults,
    fixtures: BTreeMap<String, FixtureSpec>,
    case: Vec<CaseSpec>,
}

#[derive(serde::Deserialize)]
struct Defaults {
    modes: Vec<String>,
    fixtures: Vec<String>,
}

#[derive(serde::Deserialize)]
struct FixtureSpec {
    #[serde(default)]
    vars: BTreeMap<String, String>,
}

#[derive(serde::Deserialize)]
struct CaseSpec {
    command: String,
    variant: String,
    args: Vec<String>,
    modes: Option<Vec<String>>,
    fixtures: Option<Vec<String>>,
    #[serde(default)]
    env: BTreeMap<String, String>,
    #[serde(default)]
    input: String,
    cwd: Option<String>,
    #[serde(default)]
    normalise: Vec<Rule>,
    cassette: Option<String>,
}

/// Replaces `{name}` in each argument; `None` when a variable is missing.
fn substitute(args: &[String], vars: &BTreeMap<String, String>) -> Option<Vec<String>> {
    args.iter()
        .map(|arg| {
            let mut result = String::new();
            let mut rest = arg.as_str();
            while let Some(start) = rest.find('{') {
                let end = rest[start..].find('}')? + start;
                result.push_str(&rest[..start]);
                result.push_str(vars.get(&rest[start + 1..end])?);
                rest = &rest[end + 1..];
            }
            result.push_str(rest);
            Some(result)
        })
        .collect()
}

/// Where every case's network traffic goes unless it has a cassette: the
/// discard port, which refuses it.
const REFUSING_PROXY: &str = "http://127.0.0.1:9";

/// The environment every case starts from (nothing inherited): the goldens'
/// (`xtask/src/golden/case.rs` `base_env`), less the Python oracle's own.
fn base_env(mode: &str) -> BTreeMap<String, String> {
    let mut env: BTreeMap<String, String> = [
        ("PATH", "/usr/local/bin:/usr/bin:/bin"),
        ("HOME", "<HOME>"),
        ("TMPDIR", "<TMP>/tmp"),
        ("USER", "golden"),
        ("LOGNAME", "golden"),
        ("LANG", "C.UTF-8"),
        ("LC_ALL", "C.UTF-8"),
        ("TZ", "UTC"),
        ("TERM", "xterm-256color"),
        ("HTTP_PROXY", REFUSING_PROXY),
        ("HTTPS_PROXY", REFUSING_PROXY),
        ("ALL_PROXY", REFUSING_PROXY),
        ("http_proxy", REFUSING_PROXY),
        ("https_proxy", REFUSING_PROXY),
        ("all_proxy", REFUSING_PROXY),
        ("GIT_CEILING_DIRECTORIES", "<TMP>"),
        ("GIT_CONFIG_NOSYSTEM", "1"),
        ("GIT_AUTHOR_NAME", "golden"),
        ("GIT_AUTHOR_EMAIL", "golden@example.invalid"),
        ("GIT_AUTHOR_DATE", "2026-01-01T00:00:00Z"),
        ("GIT_COMMITTER_NAME", "golden"),
        ("GIT_COMMITTER_EMAIL", "golden@example.invalid"),
        ("GIT_COMMITTER_DATE", "2026-01-01T00:00:00Z"),
    ]
    .into_iter()
    .map(|(key, value)| (key.to_owned(), value.to_owned()))
    .collect();
    if mode == "agent" {
        env.insert("AI_AGENT".to_owned(), "golden".to_owned());
    }
    env
}

/// A folder's files and subfolders before a run.
type Snapshot = (
    BTreeMap<String, Vec<u8>>,
    std::collections::BTreeSet<String>,
);

/// Runs `case` and renders what it did as the snapshot's text.
pub fn run_case(case: &Case) -> String {
    let scratch = replay::case_root();
    let root = std::fs::canonicalize(scratch.path()).unwrap();
    let (home, tmp, ws) = (root.join("home"), root.join("tmp"), root.join("ws"));
    for folder in [&home, &tmp, &ws] {
        std::fs::create_dir_all(folder).unwrap();
    }
    replay::fixture(&case.fixture, &ws);
    std::fs::create_dir_all(tmp.join("tmp")).unwrap();
    let roots = [
        ("ws", ws.clone()),
        ("tmp", tmp.join("tmp")),
        ("home", home.clone()),
    ];
    let before: Vec<_> = roots
        .iter()
        .map(|(_, root)| (replay::files(root), replay::dirs(root)))
        .collect();
    let proxy = case.cassette.as_ref().map(|name| {
        let text =
            std::fs::read_to_string(replay::repo().join(format!("tests/cassettes/{name}.json")))
                .unwrap();
        let proxy = opentide_cassette::Proxy::start(
            opentide_cassette::Mode::Replay {
                cassette: opentide_cassette::Cassette::parse(&text).unwrap(),
            },
            opentide_cassette::Redaction::default(),
        )
        .unwrap();
        std::fs::write(tmp.join("cassette-ca.pem"), proxy.ca_pem()).unwrap();
        proxy
    });
    let proxy_url = proxy
        .as_ref()
        .map_or_else(|| REFUSING_PROXY.to_owned(), opentide_cassette::Proxy::url);
    let env = Env::from_pairs(case.env.iter().map(|(key, value)| {
        let value = value
            .replace("<CASSETTE_PROXY>", &proxy_url)
            .replace("<HOME>", &home.display().to_string())
            .replace("<TMP>", &tmp.display().to_string())
            .replace("<WS>", &ws.display().to_string());
        (key.clone(), value)
    }));
    let terminal = case.mode == "human";
    let stderr = Buffer::default();
    let sink: Sink = Arc::new(Mutex::new(stderr.clone()));
    let cwd = match case.cwd.as_deref() {
        None | Some(".") => ws.clone(),
        Some(sub) => ws.join(sub),
    };
    let host = Host {
        version: VERSION.into(),
        stdout_tty: terminal,
        stderr_tty: terminal,
        log_sink: sink,
        cwd: Some(cwd),
        width: terminal.then_some(100),
        interrupt: opentide_cli::app::Interrupt::default(),
    };
    let mut out = Vec::new();
    let mut err = stderr.clone();
    let exit_code = run(&case.args, &env, &host, &mut out, &mut err);
    let mut normaliser = normaliser(case, &before, [&ws, &home, &tmp]);
    let stdout = normaliser.text(&String::from_utf8_lossy(&out));
    let stderr = normaliser.text(&String::from_utf8_lossy(&stderr.0.lock().unwrap()));

    // Every path the run touched: what happened to it, and a file's bytes.
    let mut changes: BTreeMap<String, (String, Option<Vec<u8>>)> = BTreeMap::new();
    for ((prefix, root), (files_before, folders_before)) in roots.iter().zip(&before) {
        let after = replay::files(root);
        for (path, bytes) in &after {
            let what = match files_before.get(path) {
                Some(old) if old == bytes => continue,
                Some(_) => "modified",
                None => "created",
            };
            let what = format!("{what} {:04o}", mode_of(&root.join(path)));
            changes.insert(format!("{prefix}/{path}"), (what, Some(bytes.clone())));
        }
        for path in files_before
            .keys()
            .filter(|path| !after.contains_key(*path))
        {
            changes.insert(format!("{prefix}/{path}"), ("deleted".into(), None));
        }
        let folders_after = replay::dirs(root);
        for folder in folders_before.difference(&folders_after) {
            changes.insert(format!("{prefix}/{folder}/"), ("removed".into(), None));
        }
        for folder in folders_after.difference(folders_before) {
            let what = format!("created {:04o}", mode_of(&root.join(folder)));
            changes.insert(format!("{prefix}/{folder}/"), (what, None));
        }
    }

    let mut text = String::new();
    writeln!(text, "args: {}", shell_words(&case.args)).unwrap();
    writeln!(text, "exit: {exit_code}").unwrap();
    if let Some(proxy) = &proxy {
        for mismatch in proxy.verify() {
            writeln!(text, "cassette: not the recorded requests: {mismatch}").unwrap();
        }
    }
    section(&mut text, "stdout", &stdout);
    section(&mut text, "stderr", &stderr);
    for (path, (what, bytes)) in changes {
        writeln!(text, "\n━━━ {path} · {what}").unwrap();
        if let Some(bytes) = bytes {
            text.push_str(&file_body(&mut normaliser, &path, &bytes));
        }
    }
    text
}

/// The goldens' normaliser for `case`: its root's paths, the clock (today
/// and the week before, which a default query window reaches back to), and
/// the case's own rules, with the UUIDs no run mints (the fixture's, the
/// arguments', the package's data).
fn normaliser(case: &Case, before: &[Snapshot], [ws, home, tmp]: [&PathBuf; 3]) -> Normaliser {
    let day = |days: u64| {
        opentide_compare::normalise::utc_date(
            std::time::SystemTime::now() - std::time::Duration::from_secs(days * 86_400),
        )
    };
    let mut known_uuids = std::collections::BTreeSet::new();
    if case.normalise.contains(&Rule::FreshUuids) {
        for arg in &case.args {
            known_uuids.extend(opentide_compare::normalise::uuids_in(arg));
        }
        known_uuids.extend(replay::package_uuids().iter().cloned());
    }
    let fixture_text: Vec<String> = before
        .iter()
        .flat_map(|(files, _)| files.values())
        .map(|bytes| String::from_utf8_lossy(bytes).into_owned())
        .collect();
    Normaliser::new(
        &Volatile {
            literals: vec![
                (ws.display().to_string(), "<WS>".into()),
                (home.display().to_string(), "<HOME>".into()),
                (tmp.display().to_string(), "<TMP>".into()),
            ],
            dates: vec![day(0)],
            recent_dates: (1..=7).map(day).collect(),
            known_uuids,
            ..Volatile::default()
        },
        &case.normalise,
        fixture_text.iter().map(String::as_str),
    )
}

fn mode_of(path: &Path) -> u32 {
    use std::os::unix::fs::PermissionsExt;
    std::fs::symlink_metadata(path)
        .unwrap()
        .permissions()
        .mode()
        & 0o7777
}

/// The arguments as a person would type them.
fn shell_words(args: &[String]) -> String {
    let words: Vec<String> = args
        .iter()
        .map(|arg| {
            if !arg.is_empty()
                && arg
                    .chars()
                    .all(|c| c.is_ascii_alphanumeric() || "-_./:=,@+".contains(c))
            {
                arg.clone()
            } else {
                format!("'{}'", arg.replace('\'', "'\\''"))
            }
        })
        .collect();
    std::iter::once("opentide".to_owned())
        .chain(words)
        .collect::<Vec<_>>()
        .join(" ")
}

/// One stream: a JSON document as its parsed value, pretty-printed; any
/// other text as it is, with control characters made visible.
fn section(text: &mut String, name: &str, body: &str) {
    if body.is_empty() {
        writeln!(text, "\n━━━ {name} · empty").unwrap();
        return;
    }
    match as_json(body) {
        Some(pretty) => {
            writeln!(text, "\n━━━ {name} · json").unwrap();
            text.push_str(&pretty);
        }
        None => {
            writeln!(text, "\n━━━ {name}").unwrap();
            text.push_str(&visible(body));
            if !body.ends_with('\n') {
                text.push_str("\n⏎ no final newline\n");
            }
        }
    }
}

/// `text` as one JSON document (an object or an array), pretty-printed.
fn as_json(text: &str) -> Option<String> {
    let trimmed = text.trim_start();
    if !(trimmed.starts_with('{') || trimmed.starts_with('[')) {
        return None;
    }
    let value: serde_json::Value = serde_json::from_str(text).ok()?;
    let mut pretty = serde_json::to_string_pretty(&value).ok()?;
    pretty.push('\n');
    Some(pretty)
}

/// A written file's body: its text (a JSON file as its parsed value), or,
/// past [`INLINE_LIMIT`] or not UTF-8, its size and SHA-256.
fn file_body(normaliser: &mut Normaliser, path: &str, bytes: &[u8]) -> String {
    use sha2::Digest as _;
    let text = std::str::from_utf8(bytes)
        .ok()
        .map(|text| normaliser.text(text));
    match text {
        Some(text) if text.len() <= INLINE_LIMIT => {
            if Path::new(path)
                .extension()
                .is_some_and(|ext| ext.eq_ignore_ascii_case("json"))
                && let Some(pretty) = as_json(&text)
            {
                return pretty;
            }
            let mut body = visible(&text);
            if !text.is_empty() && !text.ends_with('\n') {
                body.push_str("\n⏎ no final newline\n");
            }
            body
        }
        _ => {
            let body = text.map_or_else(|| bytes.to_vec(), String::into_bytes);
            let digest = sha2::Sha256::digest(&body);
            let hex = digest.iter().fold(String::new(), |mut hex, byte| {
                let _ = write!(hex, "{byte:02x}");
                hex
            });
            format!("({} bytes, sha256 {hex})\n", body.len())
        }
    }
}

/// Control characters other than newline and tab, shown: ESC as `␛`, the
/// rest as `\u{..}`, so a snapshot diff shows a colour or cursor change.
fn visible(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        match c {
            '\n' | '\t' => out.push(c),
            '\u{1b}' => out.push('␛'),
            c if c.is_control() => write!(out, "\\u{{{:x}}}", u32::from(c)).unwrap(),
            c => out.push(c),
        }
    }
    out
}

/// Runs every case of `commands` (command directories: `validate.query`,
/// `_root`) on every core, each case's text held to its snapshot,
/// `tests/cli_snapshots/<command>/<mode>__<fixture>__<variant>.snap`. Every
/// mismatch is reported (and, outside CI, written as a `.snap.new` for
/// `cargo insta review`) before the test fails. `OPENTIDE_SNAPSHOT_FILTER`
/// (part of a case id) narrows a run.
pub fn check(commands: &[&str], at_least: usize) {
    let filter = std::env::var("OPENTIDE_SNAPSHOT_FILTER").unwrap_or_default();
    let selected: Vec<Case> = cases()
        .into_iter()
        .filter(|case| commands.contains(&case.command_dir.as_str()) && case.id.contains(&filter))
        .collect();
    if filter.is_empty() {
        assert!(
            selected.len() >= at_least,
            "only {} cases found",
            selected.len()
        );
    }
    let failed = for_each_parallel(&selected, |case| {
        let text = run_case(case);
        let mut settings = insta::Settings::clone_current();
        settings.set_snapshot_path(
            Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("tests/cli_snapshots")
                .join(&case.command_dir),
        );
        settings.set_prepend_module_to_snapshot(false);
        settings.set_omit_expression(true);
        settings.set_description(case.id.clone());
        let name = format!("{}__{}__{}", case.mode, case.fixture, case.variant);
        settings.bind(|| {
            std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
                insta::assert_snapshot!(name, text);
            }))
            .is_err()
        })
    });
    assert!(
        failed.is_empty(),
        "{} snapshot(s) differ (cargo insta review):\n{}",
        failed.len(),
        failed.join("\n")
    );
}

/// Runs `work` on each case on every core (a case runs the CLI in process
/// with its own environment, working directory and buffers); the ids of the
/// cases for which it returned `true`, in order.
fn for_each_parallel(cases: &[Case], work: impl Fn(&Case) -> bool + Sync) -> Vec<String> {
    use std::sync::atomic::{AtomicUsize, Ordering};
    let next = AtomicUsize::new(0);
    let threads = std::thread::available_parallelism()
        .map_or(2, std::num::NonZero::get)
        .min(cases.len().max(1));
    let mut failed: Vec<(usize, String)> = std::thread::scope(|scope| {
        let workers: Vec<_> = (0..threads)
            .map(|_| {
                std::thread::Builder::new()
                    // The CLI's deepest paths (YAML, the query parsers) need
                    // more than a spawned thread's default 2 MiB.
                    .stack_size(16 * 1024 * 1024)
                    .spawn_scoped(scope, || {
                        let mut out = Vec::new();
                        loop {
                            let at = next.fetch_add(1, Ordering::Relaxed);
                            let Some(case) = cases.get(at) else { break };
                            if work(case) {
                                out.push((at, case.id.clone()));
                            }
                        }
                        out
                    })
                    .unwrap()
            })
            .collect();
        workers
            .into_iter()
            .flat_map(|worker| {
                worker
                    .join()
                    .unwrap_or_else(|panic| std::panic::resume_unwind(panic))
            })
            .collect()
    });
    failed.sort();
    failed.into_iter().map(|(_, id)| id).collect()
}
