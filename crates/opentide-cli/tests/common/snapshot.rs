//! The command line's behaviour, owned by Rust (#1139): every case of
//! `tests/golden/cases.toml` run in-process ([`opentide_cli::run`]) on a fresh
//! copy of its fixture, and what it did (exit code, stdout, stderr, every
//! file it wrote, changed or deleted) held to an insta snapshot of the Rust
//! CLI's own output, under `tests/cli_snapshots/<command>/`.
//!
//! Only what differs between two runs of the same case is normalised (the
//! goldens' [`Normaliser`]: the case's temporary paths, the clock, durations,
//! crash-log names, catalog fingerprints, and minted UUIDs where the case
//! opts in). JSON is snapshotted as its parsed value, pretty-printed, so its
//! fields are checked and its spacing is not. A change in what a command
//! prints or writes is a snapshot diff, reviewed with `cargo insta review`
//! (tests/golden/README.md, "Snapshots").

#![allow(dead_code, reason = "each test binary uses part of the helpers")]

