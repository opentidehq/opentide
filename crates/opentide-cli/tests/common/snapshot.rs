/// One path under a root, links not followed.
#[derive(PartialEq)]
enum Entry {
    File(u32, Vec<u8>),
    Link(String),
    Dir(u32),
}

/// Every path under `root` (relative; a folder's ends in `/`).
fn entries(root: &Path) -> BTreeMap<String, Entry> {
    use std::os::unix::fs::PermissionsExt;
    let mut out = BTreeMap::new();
    let mut pending = vec![root.to_path_buf()];
    while let Some(dir) = pending.pop() {
        for entry in std::fs::read_dir(&dir).unwrap() {
            let path = entry.unwrap().path();
            let relative = path
                .strip_prefix(root)
                .unwrap()
                .to_string_lossy()
                .into_owned();
            let meta = std::fs::symlink_metadata(&path).unwrap();
            let mode = meta.permissions().mode() & 0o7777;
            if meta.is_symlink() {
                let target = std::fs::read_link(&path).unwrap().display().to_string();
                out.insert(relative, Entry::Link(target));
            } else if meta.is_dir() {
                out.insert(format!("{relative}/"), Entry::Dir(mode));
                pending.push(path);
            } else {
                out.insert(relative, Entry::File(mode, std::fs::read(&path).unwrap()));
            }
        }
    }
    out
}

/// What happened to one path, and a file's new bytes.
fn change<'a>(
    before: Option<&Entry>,
    after: Option<&'a Entry>,
) -> Option<(String, Option<&'a [u8]>)> {
    let mode = |old: u32, new: u32| {
        if old == new {
            String::new()
        } else {
            format!(" (mode was {old:04o})")
        }
    };
    Some(match (before, after) {
        (Some(old), Some(new)) if old == new => return None,
        (_, None) => ("deleted".to_owned(), None),
        (Some(Entry::File(old, bytes_before)), Some(Entry::File(new, bytes)))
            if bytes_before == bytes =>
        {
            (format!("mode {new:04o}{}", mode(*old, *new)), None)
        }
        (Some(Entry::File(old, _)), Some(Entry::File(new, bytes))) => (
            format!("modified {new:04o}{}", mode(*old, *new)),
            Some(bytes),
        ),
        (Some(Entry::Dir(old)), Some(Entry::Dir(new))) => {
            (format!("mode {new:04o}{}", mode(*old, *new)), None)
        }
        (_, Some(Entry::File(new, bytes))) => (format!("created {new:04o}"), Some(bytes)),
        (_, Some(Entry::Dir(new))) => (format!("created {new:04o}"), None),
        (_, Some(Entry::Link(target))) => (format!("link → {target}"), None),
    })
}

/// Stops a run whose case root folds case (macOS's default volume): the
/// `tide-corpus` fixtures hold `Objects/` and `objects/` side by side, which
/// would be one folder there, so a snapshot recorded on it is not Linux's.
fn assert_case_sensitive(root: &Path) {
    let probe = root.join("Case-Probe");
    std::fs::write(&probe, "").unwrap();
    let folds = root.join("case-probe").exists();
    std::fs::remove_file(&probe).unwrap();
    assert!(
        !folds,
        "{} is on a case-insensitive volume, where `Objects/` and `objects/` are one folder: \
         set OPENTIDE_CASE_ROOT to a folder on a case-sensitive volume \
         (tests/golden/README.md, \"Snapshots\")",
        root.display()
    );
}

/// Runs `case` and renders what it did as the snapshot's text.
pub fn run_case(case: &Case) -> String {
    let scratch = replay::case_root();
    // `<TMP>` is the case's root, which holds `ws/`, `home/` and `tmp/`
    // (`$TMPDIR`), as `cargo xtask golden` lays it out.
    let root = std::fs::canonicalize(scratch.path()).unwrap();
    let (home, tmp, ws) = (root.join("home"), root.join("tmp"), root.join("ws"));
    for folder in [&home, &tmp, &ws] {
        std::fs::create_dir_all(folder).unwrap();
    }
    if case.fixture.starts_with("tide-corpus") {
        assert_case_sensitive(&root);
    }
    replay::fixture(&case.fixture, &ws);
    replay::fix_modes(&ws);
    let roots = [
        ("ws", ws.clone()),
        ("tmp", tmp.clone()),
        ("home", home.clone()),
    ];
    let before: Vec<_> = roots.iter().map(|(_, root)| entries(root)).collect();
    let cassette_text = case.cassette.as_ref().map(|name| {
        std::fs::read_to_string(replay::repo().join(format!("tests/cassettes/{name}.json")))
            .unwrap()
    });
    let proxy = cassette_text.as_ref().map(|text| {
        let proxy = opentide_cassette::Proxy::start(
            opentide_cassette::Mode::Replay {
                cassette: opentide_cassette::Cassette::parse(text).unwrap(),
            },
            opentide_cassette::Redaction::default(),
        )
        .unwrap();
        std::fs::write(root.join("cassette-ca.pem"), proxy.ca_pem()).unwrap();
        proxy
    });
    let proxy_url = proxy
        .as_ref()
        .map_or_else(|| REFUSING_PROXY.to_owned(), opentide_cassette::Proxy::url);
    let env = Env::from_pairs(case.env.iter().map(|(key, value)| {
        let value = value
            .replace("<CASSETTE_PROXY>", &proxy_url)
            .replace("<HOME>", &home.display().to_string())
            .replace("<TMP>", &root.display().to_string())
            .replace("<WS>", &ws.display().to_string());
        (key.clone(), value)
    }));
    let terminal = case.mode == "human";
    let stderr = Buffer::default();
    let sink: Sink = Arc::new(Mutex::new(stderr.clone()));
    let cwd = match case.cwd.as_deref() {
        None | Some(".") => ws.clone(),
        Some(sub) => ws.join(sub),
    };
    let host = Host {
        version: VERSION.into(),
        stdout_tty: terminal,
        stderr_tty: terminal,
        log_sink: sink,
        cwd: Some(cwd),
        width: terminal.then_some(100),
        interrupt: opentide_cli::app::Interrupt::default(),
    };
    let mut out = Vec::new();
    let mut err = stderr.clone();
    let started = std::time::SystemTime::now();
    let exit_code = run(&case.args, &env, &host, &mut out, &mut err);
    let literals = [
        (ws.display().to_string(), "<WS>"),
        (home.display().to_string(), "<HOME>"),
        (root.display().to_string(), "<TMP>"),
    ];
    let mut normaliser = normaliser(case, &before, &literals, started, cassette_text.as_deref());
    let stdout = normaliser.text(&String::from_utf8_lossy(&out));
    let stderr = normaliser.text(&String::from_utf8_lossy(&stderr.0.lock().unwrap()));

    let mut text = String::new();
    writeln!(text, "args: {}", shell_words(&case.args)).unwrap();
    writeln!(text, "exit: {exit_code}").unwrap();
    // Requests the cassette does not hold fail the case outright: a snapshot
    // must never record them as expected.
    if let Some(proxy) = &proxy {
        let mismatches = proxy.verify();
        assert!(
            mismatches.is_empty(),
            "{}: not the cassette's requests: {mismatches:#?}",
            case.id
        );
    }
    section(&mut text, "stdout", &stdout);
    section(&mut text, "stderr", &stderr);
    // Every path the run touched, in path order (the order fresh UUIDs are
    // numbered in).
    for ((prefix, root), before) in roots.iter().zip(&before) {
        let after = entries(root);
        let paths: std::collections::BTreeSet<&String> =
            before.keys().chain(after.keys()).collect();
        for path in paths {
            let Some((what, bytes)) = change(before.get(path), after.get(path)) else {
                continue;
            };
            writeln!(text, "\n━━━ {prefix}/{path} · {what}").unwrap();
            if let Some(bytes) = bytes {
                text.push_str(&file_body(&mut normaliser, &literals, path, bytes));
            }
        }
    }
    text
}

/// The goldens' normaliser for `case`: its root's paths, the clock (the
/// dates the run spans and, for `query`'s default window, the week before),
/// and the case's own rules, with the UUIDs no run mints (the fixture's, the
/// arguments', the package's data).
///
/// A date the case's own inputs hold (its cassette's, its fixture's) is
/// content, never the clock: the cassettes carry `2026-10-27` results, and
/// masking them for the week after that day would make a snapshot depend on
/// the day it is run.
fn normaliser(
    case: &Case,
    before: &[BTreeMap<String, Entry>],
    literals: &[(String, &str)],
    started: std::time::SystemTime,
    cassette: Option<&str>,
) -> Normaliser {
    let day = |at: std::time::SystemTime, days: u64| {
        opentide_compare::normalise::utc_date(at - std::time::Duration::from_secs(days * 86_400))
    };
    let fixture_text: Vec<String> = before
        .iter()
        .flat_map(BTreeMap::values)
        .filter_map(|entry| match entry {
            Entry::File(_, bytes) => Some(String::from_utf8_lossy(bytes).into_owned()),
            _ => None,
        })
        .collect();
    let held: Vec<&str> = fixture_text
        .iter()
        .map(String::as_str)
        .chain(cassette)
        .collect();
    let clock = |dates: Vec<String>| clock_dates(dates, &held);
    let mut dates = vec![day(started, 0), day(std::time::SystemTime::now(), 0)];
    dates.dedup();
    let dates = clock(dates);
    let windowed = matches!(case.command_dir.as_str(), "query" | "validate.query");
    let mut known_uuids = std::collections::BTreeSet::new();
    if case.normalise.contains(&Rule::FreshUuids) {
        for arg in &case.args {
            known_uuids.extend(opentide_compare::normalise::uuids_in(arg));
        }
        known_uuids.extend(replay::package_uuids().iter().cloned());
    }
    Normaliser::new(
        &Volatile {
            // The case's paths, and a refused connection's errno, which is
            // the host's (111 on Linux, 61 on macOS). A message wrapped
            // inside `(os error N)` leaves `error N)` at the start of a line,
            // so that tail is masked on its own too.
            literals: literals
                .iter()
                .map(|(literal, placeholder)| (literal.clone(), (*placeholder).to_owned()))
                .chain(REFUSED_ERRNOS.iter().flat_map(|errno| {
                    [
                        (
                            format!("Connection refused (os error {errno})"),
                            "Connection refused (os error <ECONNREFUSED>)".to_owned(),
                        ),
                        (
                            format!(" error {errno})"),
                            " error <ECONNREFUSED>)".to_owned(),
                        ),
                    ]
                }))
                .collect(),
            dates,
            recent_dates: if windowed {
                clock((1..=7).map(|days| day(started, days)).collect())
            } else {
                Vec::new()
            },
            known_uuids,
            git_version: git_version(),
        },
        &case.normalise,
        fixture_text.iter().map(String::as_str),
    )
}

/// What a refused connection's `errno` is on the hosts the snapshots run
/// on: `ECONNREFUSED` is 111 on Linux and 61 on macOS.
const REFUSED_ERRNOS: [&str; 2] = ["111", "61"];

/// The dates of `candidates` that no text of `held` contains: the ones that
/// can only be the clock.
pub fn clock_dates(candidates: Vec<String>, held: &[&str]) -> Vec<String> {
    candidates
        .into_iter()
        .filter(|date| !held.iter().any(|text| text.contains(date.as_str())))
        .collect()
}

/// What `git --version` says after `git version `, which `doctor` reports
/// whole (the case's `host-git` rule replaces it): `2.43.0` on Linux, `2.54.0
/// (Apple Git-157)` on macOS, so the vendor's suffix goes with the number.
fn git_version() -> Option<String> {
    static VERSION: std::sync::OnceLock<Option<String>> = std::sync::OnceLock::new();
    VERSION
        .get_or_init(|| {
            let out = std::process::Command::new("git")
                .arg("--version")
                .output()
                .ok()?;
            git_version_in(&String::from_utf8(out.stdout).ok()?)
        })
        .clone()
}

/// The version in `git --version`'s `text`, with the vendor's suffix.
pub fn git_version_in(text: &str) -> Option<String> {
    let version = text.trim().strip_prefix("git version ")?;
    (!version.is_empty()).then(|| version.to_owned())
}

/// The arguments as a person would type them.
fn shell_words(args: &[String]) -> String {
    let words: Vec<String> = args
        .iter()
        .map(|arg| {
            if !arg.is_empty()
                && arg
                    .chars()
                    .all(|c| c.is_ascii_alphanumeric() || "-_./:=,@+".contains(c))
            {
                arg.clone()
            } else {
                format!("'{}'", arg.replace('\'', "'\\''"))
            }
        })
        .collect();
    std::iter::once("opentide".to_owned())
        .chain(words)
        .collect::<Vec<_>>()
        .join(" ")
}

/// One stream: a JSON document as its parsed value, pretty-printed; any
/// other text as it is, with control characters made visible.
fn section(text: &mut String, name: &str, body: &str) {
    if body.is_empty() {
        writeln!(text, "\n━━━ {name} · empty").unwrap();
        return;
    }
    match as_json(body) {
        Some(pretty) => {
            // The layout the document came in: its line count and final
            // newline (one line for NDJSON and `--json`, pretty for people).
            let newline = if body.ends_with('\n') {
                ""
            } else {
                ", no final newline"
            };
            writeln!(
                text,
                "\n━━━ {name} · json, {} lines{newline}",
                body.lines().count()
            )
            .unwrap();
            text.push_str(&pretty);
        }
        None => {
            writeln!(text, "\n━━━ {name}").unwrap();
            text.push_str(&visible(body));
            if !body.ends_with('\n') {
                text.push_str("\n⏎ no final newline\n");
            }
        }
    }
}

/// `text` as one JSON document (an object or an array), pretty-printed.
fn as_json(text: &str) -> Option<String> {
    let trimmed = text.trim_start();
    if !(trimmed.starts_with('{') || trimmed.starts_with('[')) {
        return None;
    }
    let mut value: serde_json::Value = serde_json::from_str(text).ok()?;
    host_dependent(&mut value);
    let mut pretty = serde_json::to_string_pretty(&value).ok()?;
    pretty.push('\n');
    Some(pretty)
}

/// `validate`'s worker counts (`stats.workers`, `object_workers`,
/// `id_workers`, `parallel`), which follow the host's cores, as `"<CORES>"`.
fn host_dependent(value: &mut serde_json::Value) {
    match value {
        serde_json::Value::Object(fields) => {
            for (key, field) in fields.iter_mut() {
                if matches!(
                    key.as_str(),
                    "workers" | "object_workers" | "id_workers" | "parallel"
                ) && (field.is_number() || field.is_boolean())
                {
                    *field = serde_json::Value::String("<CORES>".to_owned());
                } else {
                    host_dependent(field);
                }
            }
        }
        serde_json::Value::Array(items) => items.iter_mut().for_each(host_dependent),
        _ => {}
    }
}

/// A written file's body: its text (a JSON file as its parsed value). Past
/// [`INLINE_LIMIT`] only the case's paths are replaced (the full normaliser
/// takes seconds on megabytes), and a JSON document keeps its structure with
/// every long string as its length and digest; anything else, or a document
/// still too large, is its size and SHA-256.
fn file_body(
    normaliser: &mut Normaliser,
    literals: &[(String, &str)],
    path: &str,
    bytes: &[u8],
) -> String {
    // A `.json` or `.sarif` file, past the limit, is shown structurally.
    let json = Path::new(path)
        .extension()
        .is_some_and(|ext| ext.eq_ignore_ascii_case("json") || ext.eq_ignore_ascii_case("sarif"));
    let Ok(text) = std::str::from_utf8(bytes) else {
        return digest_line(bytes);
    };
    if text.len() <= INLINE_LIMIT {
        // As written, not reparsed: a file's layout (key order, indentation,
        // final newline) is what a user's editor and tools see.
        let text = normaliser.text(text);
        let mut body = visible(&text);
        if !text.is_empty() && !text.ends_with('\n') {
            body.push_str("\n⏎ no final newline\n");
        }
        return body;
    }
    let mut text = text.to_owned();
    for (literal, placeholder) in literals {
        text = text.replace(literal.as_str(), placeholder);
    }
    if json {
        return large_json(&text).unwrap_or_else(|| digest_line(text.as_bytes()));
    }
    digest_line(text.as_bytes())
}

/// A large JSON document (`text`, its paths replaced) in at most 16 KiB:
/// its long strings and largest parts elided ([`elide`], [`shrink`]).
/// Rendered once per content in a test process: the editor schemas recur
/// in every case that generates them.
fn large_json(text: &str) -> Option<String> {
    static RENDERED: Mutex<BTreeMap<String, Option<String>>> = Mutex::new(BTreeMap::new());
    let key = digest_line(text.as_bytes());
    if let Some(done) = RENDERED.lock().unwrap().get(&key) {
        return done.clone();
    }
    let rendered = serde_json::from_str::<serde_json::Value>(text)
        .ok()
        .map(|mut value| {
            elide(&mut value);
            shrink(&mut value, INLINE_LIMIT / 4);
            let pretty = serde_json::to_string_pretty(&value).unwrap();
            format!(
                "({} bytes; long strings and the largest parts elided)\n{pretty}\n",
                text.len()
            )
        });
    RENDERED.lock().unwrap().insert(key, rendered.clone());
    rendered
}

/// Every string over 200 characters in `value`, as its length and digest.
fn elide(value: &mut serde_json::Value) {
    match value {
        serde_json::Value::String(text) if text.chars().count() > 200 => {
            let digest = digest_line(text.as_bytes());
            *text = format!(
                "<{} chars, {}>",
                text.chars().count(),
                digest.trim_end().trim_matches(['(', ')'])
            );
        }
        serde_json::Value::Array(items) => items.iter_mut().for_each(elide),
        serde_json::Value::Object(fields) => fields.values_mut().for_each(elide),
        _ => {}
    }
}

/// Replaces the largest part of `value` by its size and digest until it
/// fits in `limit` bytes: the part found by descending into the largest
/// child while that child is over a quarter of the limit (a SARIF report's
/// rule catalogue, a schema's definitions), so the rest stays readable.
fn shrink(value: &mut serde_json::Value, limit: usize) {
    let size =
        |value: &serde_json::Value| serde_json::to_string(value).map_or(0, |text| text.len());
    while size(value) > limit {
        // Find the part immutably, as a JSON pointer, then replace it.
        let (mut node, mut pointer) = (&*value, String::new());
        loop {
            let children: Vec<(String, &serde_json::Value)> = match node {
                serde_json::Value::Array(items) => items
                    .iter()
                    .enumerate()
                    .map(|(index, item)| (index.to_string(), item))
                    .collect(),
                serde_json::Value::Object(fields) => fields
                    .iter()
                    .map(|(key, item)| (key.replace('~', "~0").replace('/', "~1"), item))
                    .collect(),
                _ => Vec::new(),
            };
            match children.into_iter().max_by_key(|(_, child)| size(child)) {
                Some((key, child)) if size(child) > limit / 4 => {
                    write!(pointer, "/{key}").unwrap();
                    node = child;
                }
                _ => break,
            }
        }
        let digest = digest_line(serde_json::to_string(node).unwrap().as_bytes());
        let elided = format!("<elided {}>", digest.trim_end().trim_matches(['(', ')']));
        *value.pointer_mut(&pointer).unwrap() = serde_json::Value::String(elided);
    }
}

/// `(N bytes, sha256 HEX)`.
fn digest_line(bytes: &[u8]) -> String {
    let hex = opentide_compare::ledger::sha256_hex(bytes);
    format!("({} bytes, sha256 {hex})\n", bytes.len())
}

/// Control characters other than newline and tab, shown: ESC as `␛`, the
/// rest as `\u{..}`, so a snapshot diff shows a colour or cursor change.
fn visible(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        match c {
            '\n' | '\t' => out.push(c),
            '\u{1b}' => out.push('␛'),
            c if c.is_control() => write!(out, "\\u{{{:x}}}", u32::from(c)).unwrap(),
            c => out.push(c),
        }
    }
    out
}

/// Runs every case of `commands` (command directories: `validate.query`,
/// `_root`) on every core, each case's text held to its snapshot,
/// `tests/cli_snapshots/<command>/<mode>__<fixture>__<variant>.snap`. Every
/// mismatch is reported (and, outside CI, written as a `.snap.new` for
/// `cargo insta review`) before the test fails. `expected` is the group's
/// case count: a case the manifest stops expanding fails it. `OPENTIDE_SNAPSHOT_FILTER`
/// (part of a case id) narrows a run.
pub fn check(commands: &[&str], expected: usize) {
    let filter = std::env::var("OPENTIDE_SNAPSHOT_FILTER").unwrap_or_default();
    let selected: Vec<Case> = cases()
        .into_iter()
        .filter(|case| {
            !case.is_generated()
                && commands.contains(&case.command_dir.as_str())
                && case.id.contains(&filter)
        })
        .collect();
    run_selected(&selected, expected, filter.is_empty());
}

/// The cases on one generated fixture (`fault`, `fault-lint` or
/// `heavy-small`), when this run has them ([`generated_fixtures_present`]).
pub fn check_generated(fixture: &str, expected: usize) {
    if !generated_fixtures_present() {
        eprintln!("skipped: OPENTIDE_REPLAY_FIXTURES does not name the generated fixtures");
        return;
    }
    let filter = std::env::var("OPENTIDE_SNAPSHOT_FILTER").unwrap_or_default();
    let selected: Vec<Case> = cases()
        .into_iter()
        .filter(|case| case.fixture == fixture && case.id.contains(&filter))
        .collect();
    run_selected(&selected, expected, filter.is_empty());
}

fn run_selected(selected: &[Case], expected: usize, whole: bool) {
    if whole {
        assert_eq!(
            selected.len(),
            expected,
            "the group's case count changed: update it with the manifest"
        );
    }
    isolate_process();
    let failed = for_each_parallel(selected, |case| {
        let Ok(text) = std::panic::catch_unwind(|| run_case(case)) else {
            eprintln!("{}: the case panicked", case.id);
            return true;
        };
        let mut settings = insta::Settings::clone_current();
        settings.set_snapshot_path(
            Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("tests/cli_snapshots")
                .join(&case.command_dir),
        );
        settings.set_prepend_module_to_snapshot(false);
        settings.set_omit_expression(true);
        settings.set_description(case.id.clone());
        settings.bind(|| {
            std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
                insta::assert_snapshot!(snapshot_name(case), text);
            }))
            .is_err()
        })
    });
    assert!(
        failed.is_empty(),
        "{} snapshot(s) differ (cargo insta review):\n{}",
        failed.len(),
        failed.join("\n")
    );
}

/// A case's snapshot file name (without `.snap`).
pub fn snapshot_name(case: &Case) -> String {
    format!("{}__{}__{}", case.mode, case.fixture, case.variant)
}

/// What the process gives every case alike, whoever runs the tests: the
/// umask (files are created `0644`, as a snapshot records them) and a
/// standard input that is no terminal (`/dev/null`, as nextest gives it;
/// `cargo test` from a terminal would otherwise show a prompt).
fn isolate_process() {
    static ONCE: std::sync::Once = std::sync::Once::new();
    ONCE.call_once(|| {
        rustix::process::umask(rustix::fs::Mode::from_raw_mode(0o022));
        let null = std::fs::File::open("/dev/null").unwrap();
        rustix::stdio::dup2_stdin(&null).unwrap();
    });
}

/// Runs `work` on each case on every core (a case runs the CLI in process
/// with its own environment, working directory and buffers); the ids of the
/// cases for which it returned `true`, in order.
fn for_each_parallel(cases: &[Case], work: impl Fn(&Case) -> bool + Sync) -> Vec<String> {
    use std::sync::atomic::{AtomicUsize, Ordering};
    let next = AtomicUsize::new(0);
    let threads = std::thread::available_parallelism()
        .map_or(2, std::num::NonZero::get)
        .min(cases.len().max(1));
    let mut failed: Vec<(usize, String)> = std::thread::scope(|scope| {
        let workers: Vec<_> = (0..threads)
            .map(|_| {
                std::thread::Builder::new()
                    // The CLI's deepest paths (YAML, the query parsers) need
                    // more than a spawned thread's default 2 MiB.
                    .stack_size(16 * 1024 * 1024)
                    .spawn_scoped(scope, || {
                        let mut out = Vec::new();
                        loop {
                            let at = next.fetch_add(1, Ordering::Relaxed);
                            let Some(case) = cases.get(at) else { break };
                            if work(case) {
                                out.push((at, case.id.clone()));
                            }
                        }
                        out
                    })
                    .unwrap()
            })
            .collect();
        workers
            .into_iter()
            .flat_map(|worker| {
                worker
                    .join()
                    .unwrap_or_else(|panic| std::panic::resume_unwind(panic))
            })
            .collect()
    });
    failed.sort();
    failed.into_iter().map(|(_, id)| id).collect()
}
