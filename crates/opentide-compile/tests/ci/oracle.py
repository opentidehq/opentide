"""Record the oracle's CI pipelines for `tests/setup_ci.rs` (UC-3.2c, #916).

Renders each case of CASES with the Python CLI's `opentide.ci.render.render_ci`
and writes `<case>.toml` (the render's inputs, as `opentide-compile`'s
`setup::ci::Options` reads them) and `<case>.<ext>` (the pipeline). Run it with
the interpreter of an opentide checkout's environment, from this folder:

    ../../../../.venv/bin/python oracle.py

Never edit the outputs by hand: re-run this script.
"""

from __future__ import annotations

import json
import tempfile
from pathlib import Path

from opentide.ci.models import CiRenderOptions
from opentide.ci.render import render_ci
from opentide.ci.stages import query_platforms, workspace_credential_names
from opentide.ci.writeback import rules_folder

HERE = Path(__file__).resolve().parent
ALL = [
    "bitdefender",
    "carbon_black_cloud",
    "crowdstrike",
    "defender_for_endpoint",
    "elastic",
    "exabeam",
    "google_secops",
    "graylog",
    "harfanglab",
    "sentinel",
    "sentinel_one",
    "splunk",
    "sysdig",
]

#: (name, options): every provider with its defaults, then each switch.
CASES: list[tuple[str, dict[str, object]]] = []
for ci in ("github", "gitlab", "azure"):
    CASES += [
        (f"{ci}-default", {"ci": ci, "platforms": ALL}),
        (f"{ci}-none", {"ci": ci, "platforms": []}),
        (
            f"{ci}-switched",
            {
                "ci": ci,
                "platforms": ["sentinel", "crowdstrike", "splunk"],
                "staging": False,
                "inflight": False,
                "sharing": True,
                "lint_changed": True,
                "explorer_pages": True,
                "python_version": "3.11",
                "default_branch": "trunk",
            },
        ),
        (
            f"{ci}-workspace",
            {
                "ci": ci,
                "platforms": ["sentinel", "elastic"],
                "repo": True,
                "default_branch": "release/v1.2",
                "opentide_version": "1.0",
            },
        ),
    ]

SENTINEL = """\
[platform]
enabled = true

[[tenants]]
name = "prod"
[tenants.setup]
tenant_id = "$AZ_TENANT"
client_secret = "${AZ_SECRET}"
literal = "$not-a-var!"
"""

PATHS = """\
[paths.objects]
rule = "detections/rules/"
"""


def workspace(root: Path) -> Path:
    config = root / ".opentide" / "configurations"
    (config / "platforms").mkdir(parents=True)
    (config / "platforms" / "sentinel.toml").write_text(SENTINEL, encoding="utf-8")
    (config / "paths.toml").write_text(PATHS, encoding="utf-8")
    return root


def toml_value(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(item) for item in value) + "]"
    return json.dumps(value)


def main() -> None:
    with tempfile.TemporaryDirectory() as scratch:
        repo = workspace(Path(scratch))
        for name, given in CASES:
            fields = dict(given)
            use_repo = bool(fields.pop("repo", False))
            version = str(fields.pop("opentide_version", "0.23.0"))
            options = CiRenderOptions(**fields, opentide_version=version)
            if use_repo:
                options.repo = repo
            ((path, text),) = render_ci(options).items()
            inputs = {
                "ci": options.ci,
                "path": path,
                "platforms": options.platforms,
                "staging": options.staging,
                "inflight": options.inflight,
                "sharing": options.sharing,
                "lint_changed": options.lint_changed,
                "explorer_pages": options.explorer_pages,
                "python_version": options.python_version,
                "opentide_version": options.opentide_version,
                "default_branch": options.default_branch,
                "rules_folder": rules_folder(options.repo),
            }
            lines = [f"{key} = {toml_value(value)}" for key, value in inputs.items()]
            lines.append("")
            lines.append("[credentials]")
            for platform in query_platforms(options):
                names = workspace_credential_names(repo, platform) if use_repo else []
                lines.append(f"{platform} = {toml_value(names)}")
            header = "# Generated by oracle.py from the Python CLI: never edit.\n"
            (HERE / f"{name}.toml").write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
            (HERE / f"{name}.yml").write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
