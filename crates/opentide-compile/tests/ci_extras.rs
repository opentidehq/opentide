//! `setup ci`'s `--app-token`, the user-owned region and Azure's push base
//! step, as the pipelines hold them.

#![expect(
    clippy::unwrap_used,
    reason = "a test helper: a broken case is a failure"
)]

use indexmap::IndexMap;
use opentide_compile::Json;
use opentide_compile::ci::{
    Options, Provider, USER_BEGIN, USER_END, app_token, dropped_jobs, render, user_region,
};

fn options(provider: Provider) -> Options {
    Options {
        provider,
        platforms: vec!["sentinel".into()],
        staging: true,
        inflight: true,
        sharing: true,
        lint_changed: true,
        explorer_pages: false,
        python_version: "3.12".into(),
        opentide_version: "1.0.0".into(),
        default_branch: "main".into(),
        docs_output: "docs".into(),
        rules_folder: "objects/rules".into(),
        credentials: IndexMap::new(),
        sharing_credentials: Vec::new(),
        variable_groups: Vec::new(),
        app_token: false,
        prune: true,
        user_region: None,
    }
}

fn data(text: &str) -> Json {
    let document = opentide_schema::node::load(text).unwrap_or_else(|error| {
        panic!("not YAML: {error:?}\n{text}");
    });
    Json::from_node(document.root().unwrap())
}

fn steps(job: &Json) -> &[Json] {
    job.get("steps").and_then(Json::as_array).unwrap()
}

const GITHUB_JOB: &str =
    "  my_job:\n    runs-on: ubuntu-latest\n    steps:\n      - run: echo mine";
const AZURE_STAGE: &str =
    "  - stage: Mine\n    jobs:\n      - job: mine\n        steps:\n          - script: echo mine";

#[test]
fn app_token_goes_into_the_production_job_only() {
    let mut on = options(Provider::GitHub);
    on.app_token = true;
    let written = render(&on).unwrap();
    let root = data(&written);
    let production = root
        .get("jobs")
        .and_then(|jobs| jobs.get("deploy_production"))
        .unwrap();
    let production_steps = steps(production);
    let token = &production_steps[0];
    assert_eq!(token.get("id").and_then(Json::as_str), Some("app-token"));
    assert_eq!(
        token.get("uses").and_then(Json::as_str),
        Some("actions/create-github-app-token@v3")
    );
    let with = token.get("with").unwrap();
    assert_eq!(
        with.get("client-id").and_then(Json::as_str),
        Some("${{ vars.OPENTIDE_APP_CLIENT_ID }}")
    );
    assert!(with.get("app-id").is_none());
    assert_eq!(
        with.get("permission-contents").and_then(Json::as_str),
        Some("write")
    );
    assert_eq!(
        with.get("private-key").and_then(Json::as_str),
        Some("${{ secrets.OPENTIDE_APP_PRIVATE_KEY }}")
    );
    let checkout = production_steps[1].get("with").unwrap();
    assert_eq!(
        checkout.get("token").and_then(Json::as_str),
        Some("${{ steps.app-token.outputs.token }}")
    );
    // The production job and, with inflight on, the prune job (a push to the
    // default branch); the shards job runs on pull requests and keeps
    // GITHUB_TOKEN.
    assert_eq!(written.matches("create-github-app-token").count(), 2);
    assert_eq!(written.matches("steps.app-token.outputs.token").count(), 2);
    let prune = root
        .get("jobs")
        .and_then(|jobs| jobs.get("inflight_prune"))
        .unwrap();
    assert_eq!(
        steps(prune)[0].get("uses").and_then(Json::as_str),
        Some("actions/create-github-app-token@v3")
    );
    let shards = root
        .get("jobs")
        .and_then(|jobs| jobs.get("inflight_shards"))
        .unwrap();
    assert!(!format!("{:?}", steps(shards)).contains("app-token"));
    assert!(written.starts_with(
        "# Generated by opentide — regenerate with `opentide setup ci github --app-token`\n"
    ));
    assert!(written.contains(
        "#   OPENTIDE_APP_CLIENT_ID (variable)\n#   OPENTIDE_APP_PRIVATE_KEY (secret)\n"
    ));
    assert!(app_token(&written));
}

#[test]
fn without_app_token_the_workflow_has_no_trace_of_it() {
    let written = render(&options(Provider::GitHub)).unwrap();
    assert!(!written.contains("app-token"), "{written}");
    assert!(!written.contains("OPENTIDE_APP"), "{written}");
    assert!(!app_token(&written));
    // What the flag adds is the header's lines, the token step and the
    // checkout's `token:`; the rest is byte for byte.
    let mut on = options(Provider::GitHub);
    on.app_token = true;
    let with = render(&on).unwrap();
    let step = "      - name: Create GitHub App token\n        id: app-token\n        uses: actions/create-github-app-token@v3\n        with:\n          client-id: ${{ vars.OPENTIDE_APP_CLIENT_ID }}\n          private-key: ${{ secrets.OPENTIDE_APP_PRIVATE_KEY }}\n          permission-contents: write\n";
    let header = "# --app-token: the jobs that push to the default branch use a GitHub App token. Set the repository variable and secret:\n#   OPENTIDE_APP_CLIENT_ID (variable)\n#   OPENTIDE_APP_PRIVATE_KEY (secret)\n";
    let restored = with
        .replace(step, "")
        .replace(header, "")
        .replace(
            "          token: ${{ steps.app-token.outputs.token }}\n",
            "",
        )
        .replace(" --app-token`", "`");
    assert_eq!(restored, written);
}

#[test]
fn the_user_region_ends_each_pipelines_jobs() {
    let cases = [
        (
            Provider::GitHub,
            "\n  # opentide:user-begin\n  # opentide:user-end\n",
        ),
        (
            Provider::GitLab,
            "\n# opentide:user-begin\n# opentide:user-end\n",
        ),
        (
            Provider::Azure,
            "\n  # opentide:user-begin\n  # opentide:user-end\n",
        ),
    ];
    for (provider, tail) in cases {
        let written = render(&options(provider)).unwrap();
        assert!(written.ends_with(tail), "{}:\n{written}", provider.name());
        assert!(written.contains("survive `opentide setup ci"), "{written}");
        data(&written);
        assert_eq!(user_region(&written), Ok(None));
    }
}

#[test]
fn a_regenerate_copies_the_region_verbatim() {
    for (provider, mine, kind) in [
        (Provider::GitHub, GITHUB_JOB, "github"),
        (Provider::Azure, AZURE_STAGE, "azure"),
        (
            Provider::GitLab,
            "my_job:\n  script:\n    - echo mine\n  # a note of mine",
            "gitlab",
        ),
    ] {
        let mut with = options(provider);
        with.user_region = Some(mine.to_owned());
        let written = render(&with).unwrap();
        assert!(
            written.ends_with(&format!(
                "{USER_BEGIN}\n{mine}\n{}{USER_END}\n",
                pad(provider)
            )),
            "{kind}:\n{written}"
        );
        let root = data(&written);
        match provider {
            Provider::GitHub => assert!(root.get("jobs").unwrap().get("my_job").is_some()),
            Provider::GitLab => assert!(root.get("my_job").is_some()),
            Provider::Azure => {
                let stages = root.get("stages").and_then(Json::as_array).unwrap();
                let last = stages.last().unwrap();
                assert_eq!(last.get("stage").and_then(Json::as_str), Some("Mine"));
            }
        }
        // Read back and written again: the same file.
        let region = user_region(&written).unwrap();
        assert_eq!(region.as_deref(), Some(mine));
        let mut again = options(provider);
        again.user_region = region;
        assert_eq!(render(&again).unwrap(), written, "{kind}");
    }
}

fn pad(provider: Provider) -> &'static str {
    if provider == Provider::GitLab {
        ""
    } else {
        "  "
    }
}

#[test]
fn jobs_in_the_region_are_not_dropped() {
    for (provider, mine) in [
        (Provider::GitHub, GITHUB_JOB),
        (Provider::Azure, AZURE_STAGE),
    ] {
        let mut with = options(provider);
        with.user_region = Some(mine.to_owned());
        let before = render(&with).unwrap();
        let after = render(&options(provider)).unwrap();
        // Rendered without the region, the jobs are what a regenerate drops...
        assert!(
            !dropped_jobs(provider, &before, &after).is_empty(),
            "{}",
            provider.name()
        );
        // ...and rendered with it, nothing is.
        let kept = render(&with).unwrap();
        assert_eq!(dropped_jobs(provider, &before, &kept), Vec::<String>::new());
    }
}

#[test]
fn a_region_that_cannot_be_read_is_an_error() {
    let begin = format!("a: 1\n  {USER_BEGIN}\n  x: 1\n");
    assert!(
        user_region(&begin)
            .unwrap_err()
            .contains("no `# opentide:user-end`")
    );
    let end = format!("a: 1\n{USER_END}\n");
    assert!(
        user_region(&end)
            .unwrap_err()
            .contains("no `# opentide:user-begin`")
    );
    let twice = format!("{USER_BEGIN}\n{USER_END}\n{USER_BEGIN}\n{USER_END}\n");
    assert!(user_region(&twice).unwrap_err().contains("more than one"));
    // CRLF line endings are read as lines; blank content is no region.
    let crlf = format!("{USER_BEGIN}\r\n  a: 1\r\n{USER_END}\r\n");
    assert_eq!(user_region(&crlf), Ok(Some("  a: 1".to_owned())));
    assert_eq!(
        user_region(&format!("{USER_BEGIN}\n\n{USER_END}\n")),
        Ok(None)
    );
}

/// The jobs that read a push's changed files get the base step, before the
/// step that runs opentide; the others do not.
#[test]
fn azure_finds_the_push_base_before_opentide_runs() {
    let mut options = options(Provider::Azure);
    options.sharing = true;
    let written = render(&options).unwrap();
    let root = data(&written);
    let mut with_step = Vec::new();
    for stage in root.get("stages").and_then(Json::as_array).unwrap() {
        for job in stage.get("jobs").and_then(Json::as_array).unwrap() {
            let name = job.get("job").and_then(Json::as_str).unwrap().to_owned();
            let all = steps(job);
            let Some(at) = all.iter().position(|step| {
                step.get("displayName").and_then(Json::as_str)
                    == Some("Find this push's base commit")
            }) else {
                continue;
            };
            let step = &all[at];
            assert_eq!(
                step.get("condition").and_then(Json::as_str),
                Some(
                    "and(succeeded(), in(variables['Build.Reason'], 'IndividualCI', 'BatchedCI'))"
                ),
                "{name}"
            );
            assert_eq!(
                step.get("env")
                    .and_then(|env| env.get("SYSTEM_ACCESSTOKEN"))
                    .and_then(Json::as_str),
                Some("$(System.AccessToken)"),
                "{name}"
            );
            // The checkout has the history, and the step runs before the
            // step that runs opentide (the last one).
            let checkout = all[0].get("fetchDepth").and_then(|depth| depth.as_i64());
            assert_eq!(checkout, Some(0), "{name}");
            assert!(at < all.len() - 1, "{name}");
            with_step.push(name);
        }
    }
    assert_eq!(
        with_step,
        [
            "validate",
            "validate_query_sentinel",
            "deploy_production",
            "share"
        ]
    );
    for needle in [
        "resultFilter=succeeded",
        "statusFilter=completed",
        "queryOrder=finishTimeDescending",
        "'$top=1'",
        "api-version=7.1",
        "_apis/build/builds",
        "git merge-base --is-ancestor",
        "##vso[task.setvariable variable=OPENTIDE_PUSH_BASE]",
    ] {
        assert!(written.contains(needle), "{needle}");
    }
    // Only Azure has it.
    for provider in [Provider::GitHub, Provider::GitLab] {
        let other = render(&self::options(provider)).unwrap();
        assert!(!other.contains("OPENTIDE_PUSH_BASE"), "{}", provider.name());
    }
}

#[cfg(unix)]
mod push_base_script {
    use std::path::Path;
    use std::process::Command;

    use super::*;

    fn script() -> String {
        let written = render(&options(Provider::Azure)).unwrap();
        let root = data(&written);
        let stages = root.get("stages").and_then(Json::as_array).unwrap();
        let production = stages
            .iter()
            .flat_map(|stage| stage.get("jobs").and_then(Json::as_array).unwrap())
            .find(|job| job.get("job").and_then(Json::as_str) == Some("deploy_production"))
            .unwrap();
        steps(production)
            .iter()
            .find(|step| {
                step.get("displayName").and_then(Json::as_str)
                    == Some("Find this push's base commit")
            })
            .and_then(|step| step.get("script"))
            .and_then(Json::as_str)
            .unwrap()
            .to_owned()
    }

    fn git(dir: &Path, args: &[&str]) -> String {
        let done = Command::new("git")
            .args(["-c", "user.name=t", "-c", "user.email=t@t"])
            .args(args)
            .current_dir(dir)
            .output()
            .unwrap();
        assert!(done.status.success(), "{args:?}: {done:?}");
        String::from_utf8(done.stdout).unwrap().trim().to_owned()
    }

    /// Runs the step in a checkout whose HEAD descends from `first`, with a
    /// `curl` that answers `body`: what it printed.
    fn run(body: &str, build: &dyn Fn(&str, &str) -> String) -> (String, String) {
        let dir = tempfile::tempdir().unwrap();
        let repo = dir.path().join("repo");
        std::fs::create_dir(&repo).unwrap();
        git(&repo, &["init", "-q"]);
        let branch = git(&repo, &["branch", "--show-current"]);
        git(&repo, &["commit", "-q", "--allow-empty", "-m", "one"]);
        let first = git(&repo, &["rev-parse", "HEAD"]);
        git(&repo, &["commit", "-q", "--allow-empty", "-m", "two"]);
        git(&repo, &["checkout", "-q", "--orphan", "other"]);
        git(&repo, &["commit", "-q", "--allow-empty", "-m", "unrelated"]);
        let unrelated = git(&repo, &["rev-parse", "HEAD"]);
        git(&repo, &["checkout", "-q", &branch]);
        let bin = dir.path().join("bin");
        std::fs::create_dir(&bin).unwrap();
        let curl = bin.join("curl");
        let response = if body.is_empty() {
            build(&first, &unrelated)
        } else {
            body.to_owned()
        };
        std::fs::write(
            &curl,
            format!(
                "#!/bin/sh\nprintf '%s\\n' \"$@\" > \"{dir}/curl.args\"\ncat > \"{dir}/curl.stdin\"\ncat <<'JSON'\n{response}\nJSON\n",
                dir = dir.path().display()
            ),
        )
        .unwrap();
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(&curl, std::fs::Permissions::from_mode(0o755)).unwrap();
        let path = format!("{}:{}", bin.display(), std::env::var("PATH").unwrap());
        let done = Command::new("bash")
            .args(["-e", "-c", &script()])
            .current_dir(&repo)
            .env("PATH", path)
            .env("SYSTEM_ACCESSTOKEN", "tok")
            .env("SYSTEM_COLLECTIONURI", "https://dev.azure.com/org/")
            .env("SYSTEM_TEAMPROJECT", "My Project")
            .env("SYSTEM_DEFINITIONID", "7")
            .env("BUILD_SOURCEBRANCH", "refs/heads/main")
            .output()
            .unwrap();
        assert!(done.status.success(), "{done:?}");
        let args = std::fs::read_to_string(dir.path().join("curl.args")).unwrap()
            + &std::fs::read_to_string(dir.path().join("curl.stdin")).unwrap();
        (String::from_utf8(done.stdout).unwrap(), args + &first)
    }

    #[test]
    fn the_last_successful_build_is_the_base_when_it_is_an_ancestor() {
        let (out, args) = run("", &|first, _| {
            format!(r#"{{"count": 1, "value": [{{"sourceVersion": "{first}"}}]}}"#)
        });
        let first = args.lines().last().unwrap();
        assert!(
            out.contains(&format!(
                "##vso[task.setvariable variable=OPENTIDE_PUSH_BASE]{first}\n"
            )),
            "{out}"
        );
        // The token is on stdin (`-H @-`), never in the arguments.
        assert!(args.contains("Authorization: Bearer tok"), "{args}");
        let arguments = args.split("Authorization").next().unwrap();
        assert!(!arguments.contains("tok"), "{arguments}");
        assert!(arguments.contains("-H\n@-\n"), "{arguments}");
        assert!(
            arguments.contains("--connect-timeout\n10\n--max-time\n30\n"),
            "{arguments}"
        );
        assert!(args.contains("definitions=7"), "{args}");
        assert!(args.contains("branchName=refs/heads/main"), "{args}");
        assert!(args.contains("$top=1"), "{args}");
        assert!(
            args.contains("https://dev.azure.com/org/My%20Project/_apis/build/builds"),
            "{args}"
        );
    }

    #[test]
    fn nothing_is_set_without_a_build_or_an_ancestor() {
        for body in [
            r#"{"count": 0, "value": []}"#.to_owned(),
            "not json".to_owned(),
            r#"{"value": [{"sourceVersion": "--not-a-commit"}]}"#.to_owned(),
            r#"{"value": [{"sourceVersion": "0123456789012345678901234567890123456789"}]}"#
                .to_owned(),
        ] {
            let (out, _) = run(&body, &|_, _| String::new());
            assert!(!out.contains("##vso"), "{body}: {out}");
            assert!(
                out.contains("reads the push's last commit only"),
                "{body}: {out}"
            );
        }
        // A commit that is not an ancestor of HEAD.
        let (out, _) = run("", &|_, unrelated| {
            format!(r#"{{"value": [{{"sourceVersion": "{unrelated}"}}]}}"#)
        });
        assert!(!out.contains("##vso"), "{out}");
    }
}
