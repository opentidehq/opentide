//! Page layout (`documentation/markdown/page.py`): one title, a lead, a
//! contents line, ordered sections.
//!
//! Every page is assembled here, so the three families and the folder
//! indexes share one layout and one set of spacing rules. A renderer adds
//! sections in reading order; empty ones are dropped, and the contents line
//! is built from those that remain, with the anchors the flavour gives their
//! headings. A page reads, top to bottom:
//!
//! 1. the breadcrumb back to the indexes, and the title (or GitLab wiki
//!    front matter);
//! 2. the lead: the subtitle, the TLP banner, the description, the overview;
//! 3. the contents line, when the page has enough sections to need one;
//! 4. the sections, each a level-2 heading with level-3 children;
//! 5. the generated-page notice.
//!
//! The Markdown primitives (tables, callouts, fences) are here too, each a
//! block a section body joins with [`join`].

use std::collections::HashMap;

use super::flavor::Flavor;
use super::text::{join, table_cell};

/// A page with fewer listed sections than this gets no contents line.
pub const CONTENTS_THRESHOLD: usize = 4;

/// Ends every generated page: invisible when rendered, plain to someone
/// editing the file.
pub const GENERATED_NOTICE: &str = "<!-- Generated by opentide (opentide generate docs). Edit \
                                    the object's YAML instead: this page is rewritten on every \
                                    run. -->";

/// A heading and its body; children are rendered one level deeper.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Section {
    /// The heading's text.
    pub title: String,
    /// The body, Markdown blocks.
    pub body: String,
    /// The subsections, the empty ones left out.
    pub children: Vec<Section>,
    /// Listed in the page's contents line.
    pub in_contents: bool,
}

impl Section {
    /// A section whose body is `parts` joined as blocks.
    pub fn new<I, S>(title: &str, parts: I) -> Self
    where
        I: IntoIterator<Item = S>,
        S: AsRef<str>,
    {
        Self {
            title: title.to_owned(),
            body: join(parts),
            children: Vec::new(),
            in_contents: true,
        }
    }

    /// With `children`, the empty ones left out.
    #[must_use]
    pub fn with_children(mut self, children: Vec<Section>) -> Self {
        self.children = children
            .into_iter()
            .filter(|child| !child.is_empty())
            .collect();
        self
    }

    /// Whether it has nothing to say: no body, and only empty children.
    pub fn is_empty(&self) -> bool {
        self.body.trim().is_empty() && self.children.iter().all(Section::is_empty)
    }
}

/// An object or index page under construction.
#[derive(Debug, Clone)]
pub struct Page {
    flavor: Flavor,
    title: String,
    frontmatter: bool,
    breadcrumb: String,
    lead: Vec<String>,
    sections: Vec<Section>,
}

impl Page {
    /// A page titled `title`; with `frontmatter`, the title is GitLab wiki
    /// front matter rather than a heading.
    pub fn new(flavor: Flavor, title: &str, frontmatter: bool, breadcrumb: String) -> Self {
        Self {
            flavor,
            title: title.to_owned(),
            frontmatter,
            breadcrumb,
            lead: Vec::new(),
            sections: Vec::new(),
        }
    }

    /// Content under the title, before the contents line; blank parts are
    /// left out.
    pub fn add_lead<I, S>(&mut self, parts: I)
    where
        I: IntoIterator<Item = S>,
        S: Into<String>,
    {
        for part in parts {
            let part = part.into();
            if !part.trim().is_empty() {
                self.lead.push(part);
            }
        }
    }

    /// Appends `section` unless it is empty.
    pub fn add(&mut self, section: Section) {
        if !section.is_empty() {
            self.sections.push(section);
        }
    }

    /// The sections, as added.
    pub fn sections(&self) -> &[Section] {
        &self.sections
    }

    /// Replaces the body of the top-level section at `index`.
    pub fn set_body(&mut self, index: usize, body: String) {
        if let Some(section) = self.sections.get_mut(index) {
            section.body = body;
        }
    }

    /// The anchor each heading gets, in page order (`[section, child,
    /// child, section, …]`), as the flavour assigns them: a repeated heading
    /// gets `-1`, `-2`.
    pub fn anchors(&self) -> Vec<String> {
        let mut claims = Anchors::new(self.flavor);
        claims.claim(&self.title);
        let mut found = Vec::new();
        fn walk(items: &[Section], claims: &mut Anchors, found: &mut Vec<String>) {
            for item in items {
                found.push(claims.claim(&item.title));
                walk(&item.children, claims, found);
            }
        }
        walk(&self.sections, &mut claims, &mut found);
        found
    }

    /// The anchors of the top-level sections, in order.
    fn top_anchors(&self) -> Vec<String> {
        let all = self.anchors();
        let mut out = Vec::with_capacity(self.sections.len());
        let mut at = 0;
        for section in &self.sections {
            out.push(all.get(at).cloned().unwrap_or_default());
            at += 1 + descendants(section);
        }
        out
    }

    /// The anchors of the children of the top-level section at `index`.
    pub fn child_anchors(&self, index: usize) -> Vec<String> {
        let all = self.anchors();
        let mut at = 0;
        for (position, section) in self.sections.iter().enumerate() {
            if position == index {
                let mut out = Vec::new();
                let mut child_at = at + 1;
                for child in &section.children {
                    out.push(all.get(child_at).cloned().unwrap_or_default());
                    child_at += 1 + descendants(child);
                }
                return out;
            }
            at += 1 + descendants(section);
        }
        Vec::new()
    }

    /// The page's Markdown, ending in one newline.
    pub fn render(&self) -> String {
        let mut blocks: Vec<String> = Vec::new();
        if self.frontmatter {
            blocks.push(frontmatter(&self.title));
            blocks.push(self.breadcrumb.clone());
        } else {
            blocks.push(self.breadcrumb.clone());
            blocks.push(heading(1, &self.title));
        }
        blocks.extend(self.lead.iter().cloned());
        blocks.push(self.contents());
        for section in &self.sections {
            blocks.push(section_text(section, 2));
        }
        blocks.push(GENERATED_NOTICE.to_owned());
        join(blocks) + "\n"
    }

    /// The contents line: the flavour's own, else a line of links to the
    /// listed sections; empty under [`CONTENTS_THRESHOLD`].
    fn contents(&self) -> String {
        let listed = self.sections.iter().filter(|item| item.in_contents).count();
        if listed < CONTENTS_THRESHOLD {
            return String::new();
        }
        let native = table_of_contents(self.flavor);
        if !native.is_empty() {
            return native.to_owned();
        }
        let links: Vec<String> = self
            .sections
            .iter()
            .zip(self.top_anchors())
            .filter(|(item, _)| item.in_contents)
            .map(|(item, anchor)| Flavor::link(&table_cell(&item.title), &format!("#{anchor}")))
            .collect();
        paragraph(&format!("**On this page:** {}", links.join(" · ")))
    }
}

/// How many headings a section holds below its own.
fn descendants(section: &Section) -> usize {
    section
        .children
        .iter()
        .map(|child| 1 + descendants(child))
        .sum()
}

/// A section and its children as Markdown.
fn section_text(section: &Section, level: usize) -> String {
    let mut parts = vec![heading(level, &section.title), section.body.clone()];
    parts.extend(
        section
            .children
            .iter()
            .map(|child| section_text(child, level + 1)),
    );
    join(parts)
}

/// Heading anchors as the flavour assigns them.
struct Anchors {
    flavor: Flavor,
    seen: HashMap<String, usize>,
}

impl Anchors {
    fn new(flavor: Flavor) -> Self {
        Self {
            flavor,
            seen: HashMap::new(),
        }
    }

    fn claim(&mut self, title: &str) -> String {
        let base = self.flavor.heading_anchor(title);
        let count = self.seen.entry(base.clone()).or_insert(0);
        let anchor = if *count == 0 {
            base
        } else {
            format!("{base}-{count}")
        };
        *count += 1;
        anchor
    }
}

/// `## Title`.
pub fn heading(level: usize, text: &str) -> String {
    format!("{} {text}\n", "#".repeat(level.max(1)))
}

/// A paragraph: the text, trimmed.
pub fn paragraph(text: &str) -> String {
    format!("{}\n\n", text.trim())
}

/// A fenced code block.
pub fn code_block(language: &str, body: &str) -> String {
    format!("```{language}\n{body}\n```\n\n")
}

/// GitLab wiki front matter naming the page.
pub fn frontmatter(title: &str) -> String {
    format!("---\ntitle: {title}\n---\n\n")
}

/// The flavour's own table of contents: `[[_TOC_]]` on GitLab and Azure
/// DevOps.
pub fn table_of_contents(flavor: Flavor) -> &'static str {
    match flavor {
        Flavor::Gitlab | Flavor::AzureDevops => "[[_TOC_]]\n",
        _ => "",
    }
}

/// One table cell as a table writes it: a line break would end the row and
/// a bare `|` the cell.
pub fn cell(text: &str) -> String {
    let lines: Vec<&str> = text.lines().collect();
    let joined = lines.join(" ");
    let mut out = String::with_capacity(joined.len());
    let mut previous = '\0';
    for c in joined.chars() {
        if c == '|' && previous != '\\' {
            out.push('\\');
        }
        out.push(c);
        previous = c;
    }
    out
}

/// A Markdown table.
pub fn table<H, R, C>(headers: &[H], rows: &[R]) -> String
where
    H: AsRef<str>,
    R: AsRef<[C]>,
    C: AsRef<str>,
{
    let line = |cells: &mut dyn Iterator<Item = String>| {
        format!("| {} |", cells.collect::<Vec<_>>().join(" | "))
    };
    let mut lines = vec![
        line(&mut headers.iter().map(|header| cell(header.as_ref()))),
        line(&mut headers.iter().map(|_| "---".to_owned())),
    ];
    for row in rows {
        lines.push(line(
            &mut row.as_ref().iter().map(|value| cell(value.as_ref())),
        ));
    }
    lines.join("\n") + "\n"
}

/// A two-column table, the rows without a value (empty or `-`) left out;
/// empty when no row is left.
pub fn key_value_table(rows: &[(&str, String)], headers: [&str; 2]) -> String {
    let kept: Vec<[String; 2]> = rows
        .iter()
        .filter(|(_, value)| !matches!(value.trim(), "" | "-"))
        .map(|(label, value)| [(*label).to_owned(), value.clone()])
        .collect();
    if kept.is_empty() {
        return String::new();
    }
    table(&headers, &kept)
}

/// What a callout says: a neutral aside, or something a reader must act on.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Callout {
    /// An aside.
    Note,
    /// Something to act on.
    Warning,
}

/// A highlighted aside: a GitHub alert (`> [!WARNING]`), elsewhere a
/// blockquote every renderer shows.
pub fn callout(flavor: Flavor, kind: Callout, text: &str) -> String {
    let (upper, title) = match kind {
        Callout::Note => ("NOTE", "Note"),
        Callout::Warning => ("WARNING", "Warning"),
    };
    if flavor == Flavor::Github {
        blockquote(&format!("[!{upper}]\n{}", text.trim()))
    } else {
        blockquote(&format!("**{title}:** {}", text.trim()))
    }
}

/// `text` as a blockquote, every line prefixed so paragraphs stay inside.
pub fn blockquote(text: &str) -> String {
    let trimmed = text.trim();
    let lines: Vec<String> = if trimmed.is_empty() {
        vec![">".to_owned()]
    } else {
        trimmed
            .lines()
            .map(|line| format!("> {line}").trim_end().to_owned())
            .collect()
    };
    lines.join("\n") + "\n\n"
}

#[cfg(test)]
mod tests {
    use super::*;

    fn section(title: &str, body: &str) -> Section {
        Section::new(title, [body])
    }

    #[test]
    fn empty_sections_are_dropped() {
        let mut page = Page::new(Flavor::Generic, "T", false, String::new());
        page.add(section("Empty", " \n"));
        page.add(Section::new("Parent", [""]).with_children(vec![section("Child", "")]));
        assert!(page.sections().is_empty());
        assert_eq!(page.render(), format!("# T\n\n{GENERATED_NOTICE}\n"));
    }

    #[test]
    fn contents_line_from_four_sections() {
        let mut page = Page::new(
            Flavor::Generic,
            "T",
            false,
            paragraph("[Catalogue](../README.md)"),
        );
        page.add_lead(["*subtitle*\n\n", ""]);
        for title in ["A", "B", "A", "ATT&CK techniques"] {
            page.add(section(title, "x"));
        }
        let text = page.render();
        assert!(text.starts_with("[Catalogue](../README.md)\n\n# T\n\n*subtitle*\n\n"));
        assert!(text.contains(
            "**On this page:** [A](#a) · [B](#b) · [A](#a-1) · [ATT&CK \
             techniques](#att-ck-techniques)\n\n## A\n\nx\n\n## B"
        ));
        assert!(text.ends_with(&format!("x\n\n{GENERATED_NOTICE}\n")));
    }

    #[test]
    fn native_contents_and_front_matter() {
        let mut page = Page::new(Flavor::Gitlab, "T", true, "crumb\n\n".to_owned());
        for title in ["A", "B", "C", "D"] {
            page.add(section(title, "x"));
        }
        let text = page.render();
        assert!(text.starts_with("---\ntitle: T\n---\n\ncrumb\n\n[[_TOC_]]\n\n## A"));
    }

    #[test]
    fn children_are_one_level_deeper_and_anchored_in_order() {
        let mut page = Page::new(Flavor::Github, "Deployment", false, String::new());
        page.add(
            section("Deployment", "body").with_children(vec![section("Tenant targeting", "rows")]),
        );
        page.add(
            section("Signals", "s").with_children(vec![section("One", "1"), section("One", "2")]),
        );
        assert_eq!(
            page.anchors(),
            [
                "deployment-1",
                "tenant-targeting",
                "signals",
                "one",
                "one-1"
            ]
        );
        assert_eq!(page.child_anchors(1), ["one", "one-1"]);
        assert_eq!(page.child_anchors(5), Vec::<String>::new());
        assert!(
            page.render()
                .contains("## Deployment\n\nbody\n\n### Tenant targeting\n\nrows")
        );
    }

    #[test]
    fn primitives() {
        assert_eq!(
            table(&["A", "B|"], &[["x\ny", "a|b"]]),
            "| A | B\\| |\n| --- | --- |\n| x y | a\\|b |\n"
        );
        assert_eq!(
            key_value_table(&[("A", "-".to_owned()), ("B", String::new())], ["F", "V"]),
            ""
        );
        assert_eq!(
            callout(Flavor::Github, Callout::Warning, "Act.\n"),
            "> [!WARNING]\n> Act.\n\n"
        );
        assert_eq!(
            callout(Flavor::Gitlab, Callout::Note, "Aside.\n\nMore."),
            "> **Note:** Aside.\n>\n> More.\n\n"
        );
        assert_eq!(blockquote(""), ">\n\n");
        assert_eq!(code_block("kql", "x"), "```kql\nx\n```\n\n");
    }
}
