# --- annotate_editor_schema -------------------------------------------------


def test_root_comment_names_opentide_and_the_tagline() -> None:
    schema = annotate_editor_schema({"title": "Thing", "type": "object"})
    assert schema["$comment"] == SCHEMA_COMMENT
    assert "opentide" in schema["$comment"]
    assert TAGLINE.lower() in schema["$comment"].lower()
    assert schema["description"] == (
        "Thing, generated by opentide: spec-driven development for agentic detection engineering."
    )


def test_root_description_is_kept_when_present() -> None:
    schema = annotate_editor_schema({"title": "Thing", "description": "A thing."})
    assert schema["description"] == "A thing."
    assert schema["$comment"] == SCHEMA_COMMENT


def test_markdown_description_gets_a_plain_twin() -> None:
    node: dict[str, Any] = {
        "description": "Schema id, for\nexample `rule::1.0`. See [the spec](https://x.y/z)."
    }
    annotate_editor_schema({"properties": {"schema": node}})
    assert node["markdownDescription"] == (
        "Schema id, for\nexample `rule::1.0`. See [the spec](https://x.y/z)."
    )
    assert node["description"] == "Schema id, for example rule::1.0. See the spec."


def test_plain_description_is_unwrapped_without_markdown_twin() -> None:
    node: dict[str, Any] = {"description": "First line\ncontinued.\n\nSecond paragraph."}
    annotate_editor_schema({"properties": {"field": node}})
    assert node["description"] == "First line continued.\n\nSecond paragraph."
    assert "markdownDescription" not in node


def test_enum_descriptions_derive_from_markdown_and_are_mirrored() -> None:
    node: dict[str, Any] = {
        "enum": ["DESIGN", "STAGING"],
        "markdownEnumDescriptions": [
            "**Strategy**: `INERT` - _Does not deploy_\n\nBeing designed",
            "### Staging\nDeployed to **preview** tenants",
        ],
    }
    annotate_editor_schema({"properties": {"status": node}})
    assert node["enumDescriptions"] == [
        "Strategy: INERT - Does not deploy. Being designed",
        "Staging. Deployed to preview tenants",
    ]
    assert node["x-enumDescriptions"] == node["enumDescriptions"]


def test_existing_enum_descriptions_are_mirrored_not_rewritten() -> None:
    node: dict[str, Any] = {
        "enum": ["a"],
        "enumDescriptions": ["Plain A."],
        "markdownEnumDescriptions": ["**A**"],
    }
    annotate_editor_schema({"items": node})
    assert node["enumDescriptions"] == ["Plain A."]
    assert node["x-enumDescriptions"] == ["Plain A."]


def test_mismatched_markdown_enum_descriptions_are_not_derived() -> None:
    node: dict[str, Any] = {"enum": [""], "markdownEnumDescriptions": []}
    annotate_editor_schema({"properties": {"empty": node}})
    assert "enumDescriptions" not in node
    assert "x-enumDescriptions" not in node


def test_property_named_like_a_data_keyword_is_still_annotated() -> None:
    # ElasticSeverity has a field called `default`.
    default_field: dict[str, Any] = {"description": "An `alert_severity` value."}
    schema: dict[str, Any] = {
        "properties": {"default": default_field},
        "default": {"description": "data, not a schema `x`"},
    }
    annotate_editor_schema(schema)
    assert default_field["markdownDescription"] == "An `alert_severity` value."
    assert schema["default"] == {"description": "data, not a schema `x`"}


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("One. Two.", "One."),
        ("Uses e.g. this one. Then more.", "Uses e.g. this one."),
        ("Ends without stop", "Ends without stop"),
        (
            "Leverage the <code>Foo</code> API.(Citation: Apple) The purpose is X.",
            "Leverage the Foo API.",
        ),
        ("Spans\nlines. Next.", "Spans lines."),
        ("Version 1.2 ships. Next.", "Version 1.2 ships."),
    ],
)
def test_first_sentence(text: str, expected: str) -> None:
    assert first_sentence(text) == expected


def test_plain_text_one_line() -> None:
    assert plain_text("### Title\n\n**Bold** and _italic_ `code`", one_line=True) == (
        "Title. Bold and italic code"
    )
    # A log source dropdown: heading and label lines, no blank lines between.
    logsource = "### Proxy\n**System**: splunk\n**Description**: Web proxy logs.\n\n"
    assert plain_text(logsource, one_line=True) == (
        "Proxy. System: splunk. Description: Web proxy logs."
    )
    assert plain_text("Ends with a colon:\n\nthen text", one_line=True) == (
        "Ends with a colon: then text"
    )
    # A soft-wrapped sentence stays one sentence.
    assert plain_text("One sentence\nwrapped here.", one_line=True) == (
        "One sentence wrapped here."
    )
    assert plain_text("snake_case_name stays") == "snake_case_name stays"


# --- model field descriptions -----------------------------------------------


def _models(roots: list[type[TideModel]]) -> Iterator[type[TideModel]]:
    seen: set[type[TideModel]] = set()
    todo = list(roots)
    while todo:
        model = todo.pop()
        if model in seen:
            continue
        seen.add(model)
        yield model
        for field in model.model_fields.values():
            todo.extend(_nested_models(field.annotation))


def _nested_models(annotation: Any) -> Iterator[type[TideModel]]:
    if isinstance(annotation, type) and issubclass(annotation, TideModel):
        yield annotation
    for arg in getattr(annotation, "__args__", ()) or ():
        yield from _nested_models(arg)


def test_every_schema_model_field_has_a_description() -> None:
    roots = [resolve_model(schema_id) for schema_id in registered_identifiers()]
    roots.append(VisibilityConfig)
    missing = [
        f"{model.__name__}.{name}"
        for model in _models(roots)
        for name, field in model.model_fields.items()
        if not field.description
    ]
    assert missing == []


