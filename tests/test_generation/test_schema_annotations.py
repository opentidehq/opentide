def _properties(node: Any, path: str = "#") -> Iterator[tuple[str, dict[str, Any]]]:
    if isinstance(node, list):
        for index, item in enumerate(node):
            yield from _properties(item, f"{path}/{index}")
        return
    if not isinstance(node, dict):
        return
    for key, value in node.items():
        if key == "properties" and isinstance(value, dict):
            for name, subschema in value.items():
                if isinstance(subschema, dict):
                    yield f"{path}/properties/{name}", subschema
                    yield from _properties(subschema, f"{path}/properties/{name}")
        elif key not in ("enum", "default", "const"):
            yield from _properties(value, f"{path}/{key}")


@pytest.mark.parametrize("schema_id", ["threat::1.0", "rule::1.1"])
def test_every_generated_field_has_title_and_description(
    schemas: dict[str, dict[str, Any]], schema_id: str
) -> None:
    schema = schemas[schema_id]
    Draft202012Validator.check_schema(schema)
    assert schema["$comment"] == SCHEMA_COMMENT
    assert isinstance(schema["description"], str)
    missing = [
        path
        for path, node in _properties(schema)
        if not node.get("title") or not node.get("description")
    ]
    assert missing == []


def test_vocabulary_enum_carries_descriptions_from_the_toml(
    schemas: dict[str, dict[str, Any]],
) -> None:
    tlp = schemas["rule::1.1"]["properties"]["metadata"]["properties"]["tlp"]
    vocabulary = load_toml(VOCABULARIES / "tlp.vocab.toml")
    expected = {
        str(entry["name"]): first_sentence(str(entry["description"]))
        for entry in vocabulary["keys"]
    }
    assert len(tlp["enum"]) == len(tlp["enumDescriptions"]) == len(tlp["markdownEnumDescriptions"])
    assert tlp["x-enumDescriptions"] == tlp["enumDescriptions"]
    assert dict(zip(tlp["enum"], tlp["enumDescriptions"], strict=True)) == {
        value: expected[value] for value in tlp["enum"]
    }
    for value, markdown in zip(tlp["enum"], tlp["markdownEnumDescriptions"], strict=True):
        assert expected[value] in markdown


def test_id_keyed_vocabulary_enum_names_the_entry(schemas: dict[str, dict[str, Any]]) -> None:
    techniques = schemas["rule::1.1"]["properties"]["techniques"]["items"]
    by_value = dict(zip(techniques["enum"], techniques["enumDescriptions"], strict=True))
    assert by_value["T1059"].startswith("Command and Scripting Interpreter: ")
    assert "(Citation:" not in "".join(techniques["enumDescriptions"])


def test_router_carries_tagline_and_mirrored_enum_descriptions() -> None:
    router = build_opentide_router(["rule::1.0", "threat::1.0"])
    assert router["$comment"] == SCHEMA_COMMENT
    schema_field = router["properties"]["metadata"]["properties"]["schema"]
    assert schema_field["x-enumDescriptions"] == schema_field["enumDescriptions"]
    assert router["properties"]["metadata"]["description"]
