"""``opentide/_native/sdk.pyi`` matches the compiled ``opentide._native.sdk`` (UC-5.2, #837).

``cargo xtask stubs`` generates the stub from the extension's introspection data
(UC-5.2b) and ``cargo xtask stubs --check`` fails on drift; these tests hold the
stub to the module that ``uv sync`` built, so a stale stub fails here too. ty
checks ``opentide.sdk`` against the stub, so a method the stub lacks or misnames
would type-check and fail at run time.
"""

from __future__ import annotations

import ast
import inspect
from collections.abc import Callable
from pathlib import Path

import pytest

import opentide._native.sdk as native

STUB = Path(__file__).resolve().parents[2] / "src" / "opentide" / "_native" / "sdk.pyi"
CLASSES = ("Canceller", "Connection", "TenantConfig", "Workspace")


def _stub() -> ast.Module:
    return ast.parse(STUB.read_text(encoding="utf-8"))


def _parameters(function: ast.FunctionDef) -> list[str]:
    arguments = function.args
    names = [a.arg for a in [*arguments.posonlyargs, *arguments.args, *arguments.kwonlyargs]]
    return [name for name in names if name not in {"self", "cls"}]


def _runtime_parameters(member: Callable[..., object]) -> list[str]:
    signature = inspect.signature(member)
    return [p for p in signature.parameters if p not in {"self", "$self", "$cls", "cls"}]


def test_the_stub_is_generated() -> None:
    first = STUB.read_text(encoding="utf-8").splitlines()[0]
    assert first.startswith("# Generated by `cargo xtask stubs`"), first


def test_the_stub_names_every_public_name_of_the_module() -> None:
    body = _stub().body
    declared = {node.name for node in body if isinstance(node, ast.ClassDef | ast.FunctionDef)}
    declared |= {
        node.target.id
        for node in body
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name)
    }
    public = {name for name in dir(native) if not name.startswith("_")}
    assert declared == public
    # The exception is declared as the class it is.
    assert issubclass(native.SdkError, Exception)


@pytest.mark.parametrize("name", CLASSES)
def test_each_method_takes_the_stubs_parameters(name: str) -> None:
    classes = {node.name: node for node in _stub().body if isinstance(node, ast.ClassDef)}
    stubbed = {
        node.name: node
        for node in classes[name].body
        if isinstance(node, ast.FunctionDef) and not node.name.startswith("__")
    }
    cls = getattr(native, name)
    runtime = {member for member in dir(cls) if not member.startswith("_")}
    assert set(stubbed) == runtime
    for method, function in stubbed.items():
        member = inspect.getattr_static(cls, method)
        if not callable(member) and not isinstance(member, staticmethod):
            continue  # a property
        assert _parameters(function) == _runtime_parameters(getattr(cls, method)), method


def test_the_functions_take_the_stubs_parameters() -> None:
    functions = [node for node in _stub().body if isinstance(node, ast.FunctionDef)]
    assert {function.name for function in functions} == {"capabilities", "platforms", "run_json"}
    for function in functions:
        expected = _runtime_parameters(getattr(native, function.name))
        assert _parameters(function) == expected, function.name


def test_the_tenant_operations_are_typed_as_awaitables() -> None:
    classes = {node.name: node for node in _stub().body if isinstance(node, ast.ClassDef)}
    returns = {
        node.name: ast.unparse(node.returns)
        for node in classes["Connection"].body
        if isinstance(node, ast.FunctionDef) and node.returns is not None
    }
    for operation in ("query", "validate_query", "deploy"):
        assert returns[operation] == "Awaitable[str]", operation
