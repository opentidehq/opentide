def test_gitlab_and_azure_deploy_jobs_fetch_full_history() -> None:
    """#348: inflight jobs already fetch history; deploy jobs must too."""
    from opentide.ci.azure import render_azure
    from opentide.ci.gitlab import render_gitlab

    gitlab = render_gitlab(CiRenderOptions(ci="gitlab", staging=True))
    production = gitlab.split("deploy_production:", 1)[1].split("\ndocument:", 1)[0]
    staging = gitlab.split("deploy_staging:", 1)[1].split("deploy_production:", 1)[0]
    validate = gitlab.split("\nvalidate:", 1)[1].split("\ngenerate:", 1)[0]
    assert 'GIT_DEPTH: "0"' in production
    assert 'GIT_DEPTH: "0"' in staging
    assert "GIT_DEPTH" not in validate

    azure = render_azure(CiRenderOptions(ci="azure", staging=True, default_branch="main"))
    prod = azure.split("- job: deploy_production", 1)[1].split("- job:", 1)[0]
    stage = azure.split("- job: deploy_staging", 1)[1].split("- job:", 1)[0]
    validate_job = azure.split("- job: validate\n", 1)[1].split("- job:", 1)[0]
    assert "fetchDepth: 0" in prod
    assert "fetchDepth: 0" in stage
    assert "fetchDepth" not in validate_job


def test_render_github_explorer_pages_jobs() -> None:
    options = CiRenderOptions(ci="github", explorer_pages=True, default_branch="main")
    workflow = render_github(options)
    assert "permissions:" in workflow
    assert "pages: write" in workflow
    assert "explorer:" in workflow
    assert "deploy-explorer:" in workflow
    # The bundle is exported by `opentide generate explorer` and handed to the
    # checked-out explorer repo; there is no `opentide explorer build` (#202).
    assert "opentide --json generate explorer" in workflow
    assert "OPENTIDE_BUNDLE" in workflow
    assert "opentide explorer build" not in workflow
    assert "actions/deploy-pages@v4" in workflow
    assert "concurrency:" in workflow
    assert "HAS_GITHUB_APP" in workflow
    assert "if: ${{ env.HAS_GITHUB_APP == 'true' }}" in workflow
    assert "secrets.GH_APP_ID && secrets.GH_APP_KEY" not in workflow.split("if:")[1:]
