"""Tests for GitHub Actions workflow rendering."""

from __future__ import annotations

from opentide.ci.github import render_github
from opentide.ci.models import CiRenderOptions


def test_render_github_includes_core_jobs() -> None:
    options = CiRenderOptions(
        ci="github",
        platforms=["sentinel", "crowdstrike"],
        default_branch="development",
        python_version="3.12",
    )
    workflow = render_github(options)
    assert "name: OpenTide" in workflow
    assert "validate:" in workflow
    assert "generate:" in workflow
    assert "deploy_production:" in workflow
    assert "document:" in workflow
    assert "branches:" in workflow
    assert "- development" in workflow
    assert "github.ref == 'refs/heads/development'" in workflow
    assert "format(" not in workflow


def test_render_github_validate_includes_query_platforms() -> None:
    options = CiRenderOptions(ci="github", platforms=["sentinel", "splunk"])
    workflow = render_github(options)
    assert "opentide validate query --platform sentinel --live" in workflow
    assert "opentide validate query --platform splunk --live" in workflow
    assert "skip sentinel live query validation" in workflow
    assert "skip splunk live query validation" in workflow
    validate = workflow.split("  validate:", 1)[1].split("  generate:", 1)[0]
    assert "AZURE_CLIENT_SECRET: ${{ secrets.AZURE_CLIENT_SECRET }}" in validate


def test_render_github_staging_job_when_enabled() -> None:
    options = CiRenderOptions(ci="github", staging=True)
    workflow = render_github(options)
    assert "deploy_staging:" in workflow
    assert "opentide deploy --dry-run --plan STAGING" in workflow
    assert "opentide deploy --plan STAGING --skip-unconfigured" in workflow
    assert "opentide validate --strict" in workflow
    assert "opentide lint --strict" in workflow
    assert "AZURE_CLIENT_SECRET: ${{ secrets.AZURE_CLIENT_SECRET }}" in workflow
    assert "OPENTIDE_SECRETS" not in workflow
    production = workflow.split("  deploy_production:", 1)[1].split("  document:", 1)[0]
    assert "needs: generate" in production
    assert "needs: deploy_staging" not in production
    assert "fetch-depth: 0" in production
    staging = workflow.split("  deploy_staging:", 1)[1].split("  deploy_production:", 1)[0]
    assert "fetch-depth: 0" in staging
    validate = workflow.split("  validate:", 1)[1].split("  generate:", 1)[0]
    assert "fetch-depth: 0" not in validate


