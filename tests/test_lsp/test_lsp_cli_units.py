def test_doctor_checks_the_language_server_catalogs(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    import opentide
    from opentide import analysis
    from opentide.generation.lsp_catalog import CATALOG_DIR

    ctx = DoctorContext(workspace=tmp_path)
    assert check_lsp_catalog(ctx)[0].status == "skip"
    (tmp_path / ".opentide").mkdir()
    # opentide generates its own: no committed catalog is needed.
    generated = check_lsp_catalog(ctx)[0]
    assert generated.status == "pass"
    assert f"generated by opentide {opentide.__version__}" in generated.message
    fields = tmp_path / CATALOG_DIR / "fields.json"
    fields.parent.mkdir(parents=True)
    fields.write_text("{", encoding="utf-8")
    assert "does not parse" in check_lsp_catalog(ctx)[0].message
    fields.write_text(json.dumps({"opentide": "0.0.1", "fields": []}), encoding="utf-8")
    stale = check_lsp_catalog(ctx)[0]
    assert stale.status == "warn" and "0.0.1" in stale.message
    assert "editors that run opentide-lsp on their own" in stale.message
    fields.write_text(json.dumps({"opentide": opentide.__version__}), encoding="utf-8")
    assert check_lsp_catalog(ctx)[0].status == "pass"

    def fail(root: Path | None) -> dict[str, str]:
        raise RuntimeError("no registry")

    monkeypatch.setattr(analysis, "own_catalog", fail)
    broken = check_lsp_catalog(ctx)[0]
    assert broken.status == "warn"
    assert (
        "cannot generate the language-server catalog (RuntimeError: no registry)" in broken.message
    )


